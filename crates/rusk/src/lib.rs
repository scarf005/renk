fn is_expression_continuation(text: &str) -> bool {
    [
        ".[", ".", "::", "(", "[", "?", "+", "-", "*", "/", "%", "&&", "||", "&",
        "|", "^", "<<", ">>", "==", "!=", "<=", ">=", "<", ">",
    ]
    .iter()
    .any(|prefix| text.starts_with(prefix))
}

