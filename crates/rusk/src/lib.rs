const GENERATED_HEADER: &str = "// @generated by rusk; do not edit.\n";

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceMapEntry {
    pub source_line: usize,
    pub generated_line: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
