use annotate_snippets::{Annotation, AnnotationKind, Group, Level, Renderer, Snippet};
use std::{
    env, fs,
    io::{self, IsTerminal, Read},
    path::{Path, PathBuf},
    process::{self, Command},
};

use rusk::{
    FormatOptions, SourceSyntax, TranspileError, format_source, rust_to_rusk,
    rust_to_rusk_aggressive,
    script::{
        SCRIPT_EDITION, cache_root, script_cache_path, script_column, script_package, script_parts,
        script_rust,
    },
    source_map_json, to_rust, transpile,
};

const GENERATED_HEADER: &str = "// @generated by rusk; do not edit.\n";
const CARGO_WRAPPER_COMMANDS: &[&str] =
    &["bench", "build", "check", "clippy", "doc", "run", "test"];

#[derive(Debug)]
struct Args {
    input: Option<PathBuf>,
    output: Option<PathBuf>,
    source_map: Option<PathBuf>,
    format: bool,
    reverse: bool,
    aggressive: bool,
    line_width: usize,
}

impl Default for Args {
    fn default() -> Self {
        Self {
            input: None,
            output: None,
            source_map: None,
            format: false,
            reverse: false,
            aggressive: false,
            line_width: FormatOptions::default().line_width,
        }
    }
}

fn main() {
    match run(env::args().skip(1).collect()) {
        Ok(code) => process::exit(code),
        Err(error) => {
            eprintln!("rusk: {error}");
            process::exit(1);
        }
    }
}

fn run(raw_args: Vec<String>) -> Result<i32, Box<dyn std::error::Error>> {
    if is_cargo_wrapper_command(&raw_args) {
        return run_cargo_wrapper(raw_args);
    }
    if raw_args.first().is_some_and(|arg| arg == "script") {
        return run_script(raw_args);
    }
    if raw_args.first().is_some_and(|arg| arg == "add") {
        return run_add(raw_args);
    }

    let args = parse_args(raw_args)?;
    if args.input.is_none() && io::stdin().is_terminal() {
        print_help();
        return Ok(0);
    }

    let source = read_source(args.input.as_ref())?;
    if args.format {
        if args.source_map.is_some() {
            return Err("--source-map is not supported with fmt".into());
        }
        let formatted = format_source(
            &source,
            FormatOptions {
                line_width: args.line_width,
            },
        )?;
        if let Some(path) = args.output {
            fs::write(path, &formatted)?;
        } else {
            print!("{}", &formatted);
        }
        return Ok(0);
    }

    if args.reverse {
        if args.source_map.is_some() {
            return Err("--source-map is not supported with syntax conversion".into());
        }
        let converted = if args.aggressive {
            rust_to_rusk_aggressive(&source)?
        } else {
            rust_to_rusk(&source)?
        };
        if let Some(path) = args.output {
            fs::write(path, &converted)?;
        } else {
            print!("{}", &converted);
        }
        return Ok(0);
    }

    let syntax = source_syntax(args.input.as_deref());
    let output = if syntax == SourceSyntax::Rusk {
        transpile(&source)?
    } else {
        rusk::TranspileOutput {
            rust: to_rust(&source, syntax)?,
            source_map: Vec::new(),
            source_tree: Vec::new(),
        }
    };

    if let Some(path) = args.output {
        fs::write(path, &output.rust)?;
    } else {
        print!("{}", &output.rust);
    }

    if let Some(path) = args.source_map {
        fs::write(path, source_map_json(&output))?;
    }

    Ok(0)
}

fn is_cargo_wrapper_command(raw_args: &[String]) -> bool {
    match raw_args.first().map(String::as_str) {
        Some("cargo") => true,
        Some(command) => CARGO_WRAPPER_COMMANDS.contains(&command),
        None => false,
    }
}

fn run_cargo_wrapper(raw_args: Vec<String>) -> Result<i32, Box<dyn std::error::Error>> {
    let cargo_args = if raw_args.first().is_some_and(|arg| arg == "cargo") {
        raw_args.into_iter().skip(1).collect::<Vec<_>>()
    } else {
        raw_args
    };

    let root = env::current_dir()?;
    transpile_cargo_sources(&root)?;
    let status = Command::new("cargo").args(&cargo_args).status();

    Ok(status?.code().unwrap_or(1))
}

fn run_script(raw_args: Vec<String>) -> Result<i32, Box<dyn std::error::Error>> {
    let mut raw_args = raw_args.into_iter().skip(1).peekable();
    let cargo = raw_args.next_if(|arg| arg == "--cargo").is_some();
    let Some(script_path) = raw_args.next().map(PathBuf::from) else {
        return Err("script requires an input path".into());
    };
    let source = fs::read_to_string(&script_path)?;
    let cache_root = cache_root().ok_or("script requires XDG_CACHE_HOME or HOME")?;
    let source_path = fs::canonicalize(&script_path)?;
    let rust_path = script_cache_path(&cache_root.join("scripts"), &source_path);
    let script = script_rust(
        &source,
        source_syntax(Some(&script_path)),
        &script_package(&rust_path),
    )
    .map_err(|error| format!("{}: {error}", script_path.display()))?;
    write_script_cache(&rust_path, &script.rust)?;
    let build_dir = cache_root.join("build");
    let build_dir = script.named_package.then_some(build_dir.as_path());
    let diagnostic = ScriptDiagnostic {
        rust_path: &rust_path,
        script: &script_path.display().to_string(),
        package: script.named_package.then_some(script.package.as_str()),
        script_source: &source,
        rust: &script.rust,
        source_lines: &script.source_lines,
        styled: io::stderr().is_terminal(),
    };
    let build = || build_script(&rust_path, build_dir, &diagnostic);
    let binary = if cargo {
        match build()? {
            Ok(executable) => executable,
            Err(code) => return Ok(code),
        }
    } else {
        let binary = rust_path.with_extension("");
        if !is_newer(&binary, &rust_path) {
            let executable = match build()? {
                Ok(executable) => executable,
                Err(code) => return Ok(code),
            };
            let staged = rust_path.with_extension(format!("{}.tmp", process::id()));
            fs::copy(executable, &staged)?;
            fs::rename(staged, &binary)?;
        }
        binary
    };
    let mut command = Command::new(&binary);
    // What `cargo run` would set, since the binary runs without it.
    command
        .env("RUSK_SCRIPT", &source_path)
        .env(
            "CARGO_MANIFEST_DIR",
            rust_path.parent().unwrap_or(&rust_path),
        )
        .env("CARGO_PKG_NAME", &script.package)
        .args(raw_args);
    #[cfg(unix)]
    return Err(std::os::unix::process::CommandExt::exec(&mut command).into());
    #[cfg(not(unix))]
    return Ok(command.status()?.code().unwrap_or(1));
}

/// Adds dependencies to a script's frontmatter with `cargo add`, which only edits `.rs`
/// manifests: the frontmatter goes to a scratch `.rs` beside the script, so relative `--path`
/// dependencies resolve the same, and comes back into the script with the rest left as it was.
fn run_add(raw_args: Vec<String>) -> Result<i32, Box<dyn std::error::Error>> {
    let mut raw_args = raw_args.into_iter().skip(1);
    let Some(script_path) = raw_args.next().map(PathBuf::from) else {
        return Err("add requires a script path".into());
    };
    let source = fs::read_to_string(&script_path)?;
    // The scratch manifest names an edition, so cargo does not warn about its missing one.
    let mut pinned = false;
    let frontmatter = edit_manifest(&script_frontmatter(&source)?, |document| {
        let package = document.entry("package").or_insert(toml_edit::table());
        if let Some(package) = package
            .as_table_like_mut()
            .filter(|package| !package.contains_key("edition"))
        {
            package.insert("edition", toml_edit::value(SCRIPT_EDITION));
            pinned = true;
        }
    });
    let scratch = script_path.with_file_name(format!(".rusk-add-{}.rs", process::id()));
    fs::write(&scratch, frontmatter + "fn main() {}\n")?;
    let status = Command::new("cargo")
        .args(["+nightly", "-Zscript", "add", "--manifest-path"])
        .arg(&scratch)
        .args(raw_args)
        .status();
    let edited = fs::read_to_string(&scratch);
    let _ = fs::remove_file(&scratch);
    let status = status?;
    if !status.success() {
        return Ok(status.code().unwrap_or(1));
    }
    let mut frontmatter = script_frontmatter(&edited?)?;
    if pinned {
        frontmatter = edit_manifest(&frontmatter, |document| {
            if let Some(package) = document
                .get_mut("package")
                .and_then(toml_edit::Item::as_table_like_mut)
            {
                package.remove("edition");
                if package.is_empty() {
                    document.remove("package");
                }
            }
        });
    }
    let spliced = splice_frontmatter(&source, &frontmatter)?;
    if spliced != source {
        fs::write(&script_path, spliced)?;
    }
    Ok(0)
}

/// Applies `edit` to the manifest between the fences of a frontmatter; invalid TOML stays as is.
fn edit_manifest(frontmatter: &str, edit: impl FnOnce(&mut toml_edit::DocumentMut)) -> String {
    let lines = frontmatter.split_inclusive('\n').collect::<Vec<_>>();
    let last = lines.len() - 1;
    let manifest = lines[1..last].concat();
    let Ok(mut document) = manifest.parse::<toml_edit::DocumentMut>() else {
        return frontmatter.to_string();
    };
    edit(&mut document);
    // Dropping the first table leaves the blank line that separated it from the next one.
    let edited = document.to_string();
    let edited = if manifest.starts_with('\n') {
        &edited
    } else {
        edited.trim_start_matches('\n')
    };
    lines[0].to_string() + edited + lines[last]
}

fn is_newer(path: &Path, than: &Path) -> bool {
    let modified = |path: &Path| fs::metadata(path).and_then(|metadata| metadata.modified());
    matches!((modified(path), modified(than)), (Ok(path), Ok(than)) if path > than)
}

/// Builds the cached script with cargo-script and returns its executable, or cargo's exit code.
/// Runs without `--cargo` copy the executable next to the cached Rust and exec it without cargo
/// until the Rust changes; scriptr does the same but ships only as a binary, which would make rusk
/// scripts need a second launcher installed. Compiler diagnostics are printed at script lines.
/// Scripts that `build_dir` is given for share it, so a dependency compiles once for all of them.
fn build_script(
    rust_path: &Path,
    build_dir: Option<&Path>,
    diagnostic: &ScriptDiagnostic,
) -> Result<Result<PathBuf, i32>, Box<dyn std::error::Error>> {
    let mut cargo = Command::new("cargo")
        .args(["+nightly", "-Zscript", "build", "--quiet"])
        .arg(if diagnostic.styled {
            "--message-format=json-diagnostic-rendered-ansi"
        } else {
            "--message-format=json"
        })
        .arg("--manifest-path")
        .arg(rust_path)
        .envs(build_dir.map(|dir| ("CARGO_BUILD_BUILD_DIR", dir)))
        // A package the script names itself can share its name with another script's, so it
        // keeps a target dir of its own even when the user sets one for everything.
        .args(build_dir.is_none().then_some("--target-dir"))
        .args(
            build_dir
                .is_none()
                .then(|| rust_path.with_extension("target")),
        )
        .arg(if diagnostic.styled {
            "--color=always"
        } else {
            "--color=never"
        })
        .stdout(process::Stdio::piped())
        .stderr(process::Stdio::piped())
        .spawn()?;
    // Cargo's stderr is read apart from its stdout so a full pipe cannot stall either.
    let mut stderr = cargo.stderr.take().ok_or("cargo has no stderr")?;
    let stderr = std::thread::spawn(move || {
        let mut text = String::new();
        let _ = stderr.read_to_string(&mut text);
        text
    });
    let mut executable = None;
    // Cargo replays the warnings of a fresh package on every build, so a package's warnings wait
    // for its artifact and print only when it was compiled, or before its first error.
    let mut warnings = Vec::<(String, String)>::new();
    let flush = |package: &str, show: bool, warnings: &mut Vec<(String, String)>| {
        for (_, rendered) in warnings.extract_if(.., |(owner, _)| owner == package) {
            if show {
                eprint!("{rendered}");
            }
        }
    };
    // Messages are read as cargo writes them so diagnostics precede cargo's own stderr summary.
    let messages = io::BufReader::new(cargo.stdout.take().ok_or("cargo has no stdout")?);
    for message in io::BufRead::lines(messages)
        .map_while(Result::ok)
        .filter_map(|line| serde_json::from_str::<serde_json::Value>(&line).ok())
    {
        let package = message["package_id"]
            .as_str()
            .unwrap_or_default()
            .to_string();
        if message["reason"] == "compiler-message" {
            let rendered = diagnostic.render(&message["message"]);
            if message["message"]["level"] == "warning" {
                warnings.push((package.clone(), rendered));
            } else {
                flush(&package, true, &mut warnings);
                eprint!("{rendered}");
            }
        }
        if message["reason"] == "compiler-artifact" {
            flush(&package, message["fresh"] != true, &mut warnings);
        }
        if let Some(path) = message["executable"].as_str() {
            executable = Some(PathBuf::from(path));
        }
    }
    for (_, rendered) in warnings {
        eprint!("{rendered}");
    }
    let status = cargo.wait()?;
    // Cargo names the package rusk generated, which the user never wrote.
    let mut summary = stderr.join().unwrap_or_default();
    if let Some(package) = diagnostic.package {
        summary = summary
            .replace(
                &format!("`{package}` (bin \"{package}\")"),
                &format!("`{}`", diagnostic.script),
            )
            .replace(&format!("`{package}`"), &format!("`{}`", diagnostic.script));
    }
    eprint!("{summary}");
    if !status.success() {
        return Ok(Err(status.code().unwrap_or(1)));
    }
    Ok(Ok(executable.ok_or("cargo built no script executable")?))
}

/// Renders rustc's JSON diagnostics about the generated Rust file at the script's lines and
/// columns over the script's own source. Suggested replacements are Rust, so they show only their
/// message; diagnostics about other files print as rustc rendered them.
struct ScriptDiagnostic<'a> {
    rust_path: &'a Path,
    script: &'a str,
    /// The package name rusk generated for the script, which cargo's own messages show.
    package: Option<&'a str>,
    script_source: &'a str,
    rust: &'a str,
    /// The script line of each 1-based Rust line and whether rusk synthesized it.
    source_lines: &'a [(usize, bool)],
    styled: bool,
}

/// The `message` of a rustc diagnostic or child.
fn text(value: &serde_json::Value) -> &str {
    value["message"].as_str().unwrap_or_default()
}

impl ScriptDiagnostic<'_> {
    fn render(&self, message: &serde_json::Value) -> String {
        let rendered = message["rendered"].as_str().unwrap_or_default();
        if !self.mentions_script(message) {
            return rendered.to_string();
        }
        let mut title = level(&message["level"]).primary_title(text(message));
        // Lints name themselves in a note, as rustc renders them; only error codes title the
        // diagnostic.
        if let Some(code) = message["code"]["code"]
            .as_str()
            .filter(|code| code.starts_with('E'))
        {
            title = title.id(code);
        }
        let mut notes = Vec::new();
        let mut sections = Vec::new();
        for child in message["children"].as_array().into_iter().flatten() {
            let level = level(&child["level"]);
            let quoted = child["spans"].as_array().is_some_and(|spans| {
                spans
                    .iter()
                    .all(|span| span["suggested_replacement"].is_null())
            });
            let snippets = if quoted {
                self.snippets(&child["spans"])
            } else {
                Vec::new()
            };
            let help = self.add_hint(text(child)).unwrap_or_else(|| text(child).to_string());
            if snippets.is_empty() {
                notes.push(level.message(help));
            } else {
                sections.push(Group::with_title(level.secondary_title(help)).elements(snippets));
            }
        }
        let main = Group::with_title(title)
            .elements(self.snippets(&message["spans"]))
            .elements(notes);
        let groups = [main].into_iter().chain(sections).collect::<Vec<_>>();
        let renderer = if self.styled {
            Renderer::styled()
        } else {
            Renderer::plain()
        };
        renderer.render(&groups) + "\n\n"
    }

    /// rustc's help for a crate the manifest lacks tells to edit a `Cargo.toml` that a script does
    /// not have, so it becomes the `rusk add` that edits the frontmatter.
    fn add_hint(&self, help: &str) -> Option<String> {
        let (name, rest) = help
            .strip_prefix("if you wanted to use a crate named `")?
            .split_once('`')?;
        rest.contains("`cargo add").then(|| {
            format!(
                "if you wanted to use a crate named `{name}`, add it with `rusk add {} {name}`",
                self.script
            )
        })
    }

    fn is_script(&self, span: &serde_json::Value) -> bool {
        let file = span["file_name"].as_str().unwrap_or_default();
        self.rust_path
            .parent()
            .is_some_and(|dir| dir.join(file) == self.rust_path)
    }

    fn mentions_script(&self, message: &serde_json::Value) -> bool {
        let mut spans = message["spans"].as_array().into_iter().flatten();
        let mut children = message["children"].as_array().into_iter().flatten();
        spans.any(|span| self.is_script(span)) || children.any(|child| self.mentions_script(child))
    }

    /// One snippet over the script for its spans, and one per span in any other file, built from
    /// the source lines rustc quotes.
    fn snippets<'s>(&'s self, spans: &'s serde_json::Value) -> Vec<Snippet<'s, Annotation<'s>>> {
        let spans = spans.as_array().map(Vec::as_slice).unwrap_or_default();
        let annotation = |span: &'s serde_json::Value, range| {
            let kind = if span["is_primary"] == true {
                AnnotationKind::Primary
            } else {
                AnnotationKind::Context
            };
            kind.span(range).label(span["label"].as_str())
        };
        let position = |span: &serde_json::Value, line: &str, column: &str| {
            let number = |key: &str| span[key].as_u64().unwrap_or(1) as usize;
            (number(line), number(column).saturating_sub(1))
        };
        let script = spans
            .iter()
            .filter(|span| self.is_script(span))
            .map(|span| {
                let start = self.script_offset(position(span, "line_start", "column_start"));
                let end = self.script_offset(position(span, "line_end", "column_end"));
                annotation(span, start..end.max(start))
            })
            .collect::<Vec<_>>();
        let others = spans
            .iter()
            .filter(|span| !self.is_script(span))
            .map(|span| {
                let lines = span["text"]
                    .as_array()
                    .map(Vec::as_slice)
                    .unwrap_or_default();
                let quoted = lines
                    .iter()
                    .map(|line| line["text"].as_str().unwrap_or_default())
                    .collect::<Vec<_>>();
                let offset = |(line, column): (usize, usize)| {
                    let line = line.saturating_sub(position(span, "line_start", "column_start").0);
                    let before = quoted[..line.min(quoted.len())]
                        .iter()
                        .map(|text| text.len() + 1);
                    before.sum::<usize>()
                        + char_offset(quoted.get(line).copied().unwrap_or(""), column)
                };
                let start = offset(position(span, "line_start", "column_start"));
                let end = offset(position(span, "line_end", "column_end"));
                Snippet::source(quoted.join("\n"))
                    .line_start(position(span, "line_start", "column_start").0)
                    .path(span["file_name"].as_str())
                    .annotation(annotation(span, start..end.max(start)))
            });
        let script = (!script.is_empty()).then(|| {
            Snippet::source(self.script_source)
                .path(self.script)
                .annotations(script)
        });
        script.into_iter().chain(others).collect()
    }

    /// The byte offset in the script of a 1-based Rust line and 0-based column: the script column
    /// whose character the column's character came from, by a character diff of the two lines.
    fn script_offset(&self, (line, column): (usize, usize)) -> usize {
        let (script_line, synthesized) = self
            .source_lines
            .get(line.saturating_sub(1))
            .copied()
            .unwrap_or((line, false));
        let lines = self.script_source.split_inclusive('\n').collect::<Vec<_>>();
        let index = script_line
            .saturating_sub(1)
            .min(lines.len().saturating_sub(1));
        let script_text = lines
            .get(index)
            .map_or("", |text| text.trim_end_matches(['\n', '\r']));
        let start = lines[..index].iter().map(|text| text.len()).sum::<usize>();
        let rust_text = self
            .rust
            .lines()
            .nth(line.saturating_sub(1))
            .unwrap_or_default();
        let column = if synthesized {
            script_text.chars().count()
        } else {
            script_column(script_text, rust_text, column)
        };
        start + char_offset(script_text, column)
    }
}

/// The byte offset of the character `column` of `text`, or its end.
fn char_offset(text: &str, column: usize) -> usize {
    text.char_indices()
        .nth(column)
        .map_or(text.len(), |(offset, _)| offset)
}

fn level(level: &serde_json::Value) -> Level<'static> {
    match level.as_str() {
        Some("warning") => Level::WARNING,
        Some("note" | "failure-note") => Level::NOTE,
        Some("help") => Level::HELP,
        _ => Level::ERROR,
    }
}

/// Replaces the frontmatter of a script, or puts it after the shebang when there is none.
fn splice_frontmatter(source: &str, frontmatter: &str) -> Result<String, TranspileError> {
    let lines = source.split_inclusive('\n').collect::<Vec<_>>();
    let parts = script_parts(source)?;
    let start = parts.frontmatter.map_or(parts.body_start, |(start, _)| start);
    Ok(lines[..start].concat() + frontmatter + &lines[parts.body_start..].concat())
}

/// The frontmatter of a script with its fences, or an empty one.
fn script_frontmatter(source: &str) -> Result<String, TranspileError> {
    let lines = source.split_inclusive('\n').collect::<Vec<_>>();
    Ok(script_parts(source)?
        .frontmatter
        .map_or("---\n---\n".to_string(), |(start, end)| lines[start..=end].concat()))
}

fn write_script_cache(path: &Path, rust: &str) -> io::Result<()> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == rust) {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(path, rust)
}

fn transpile_cargo_sources(root: &Path) -> Result<Vec<PathBuf>, Box<dyn std::error::Error>> {
    let mut sources = Vec::new();
    collect_rusk_sources(root, &mut sources)?;
    sources.sort();

    let mut generated = Vec::new();
    for source_path in sources {
        let rust_path = source_path.with_extension("rs");
        let source = fs::read_to_string(&source_path)?;
        let rust_source = to_rust(&source, source_syntax(Some(&source_path)))?;
        let rust = format!("{GENERATED_HEADER}{rust_source}");
        write_generated_source(&rust_path, &rust)?;
        generated.push(rust_path);
    }

    Ok(generated)
}

fn collect_rusk_sources(
    root: &Path,
    sources: &mut Vec<PathBuf>,
) -> Result<(), Box<dyn std::error::Error>> {
    for path in cargo_source_roots(root) {
        if path.is_file() {
            if is_transpilable_source(&path) {
                sources.push(path);
            }
        } else if path.is_dir() {
            collect_rusk_sources_in_dir(&path, sources)?;
        }
    }
    Ok(())
}

fn cargo_source_roots(root: &Path) -> Vec<PathBuf> {
    [
        "build.rsk",
        "src",
        "examples",
        "tests",
        "benches",
    ]
    .into_iter()
    .map(|path| root.join(path))
    .collect()
}

fn collect_rusk_sources_in_dir(
    dir: &Path,
    sources: &mut Vec<PathBuf>,
) -> Result<(), Box<dyn std::error::Error>> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            collect_rusk_sources_in_dir(&path, sources)?;
        } else if is_transpilable_source(&path) {
            sources.push(path);
        }
    }
    Ok(())
}

fn is_transpilable_source(path: &Path) -> bool {
    path.extension()
        .and_then(|extension| extension.to_str())
        .is_some_and(|extension| extension == "rsk")
}

fn write_generated_source(path: &Path, rust: &str) -> Result<(), Box<dyn std::error::Error>> {
    if path.exists() {
        let existing = fs::read_to_string(path)?;
        if !existing.starts_with(GENERATED_HEADER) {
            return Err(format!(
                "refusing to overwrite non-generated Rust file: {}",
                path.display()
            )
            .into());
        }
        if existing == rust {
            return Ok(());
        }
    }

    fs::write(path, rust)?;
    Ok(())
}

fn parse_args(raw_args: Vec<String>) -> Result<Args, String> {
    let mut args = Args::default();
    let mut index = 0usize;
    let raw_args = if raw_args.first().is_some_and(|arg| {
        matches!(
            arg.as_str(),
            "transpile" | "fmt" | "format" | "from-rust" | "to-rusk"
        )
    }) {
        args.format = raw_args
            .first()
            .is_some_and(|arg| arg == "fmt" || arg == "format");
        args.reverse = raw_args
            .first()
            .is_some_and(|arg| arg == "from-rust" || arg == "to-rusk");
        raw_args.into_iter().skip(1).collect::<Vec<_>>()
    } else {
        raw_args
    };

    while index < raw_args.len() {
        match raw_args[index].as_str() {
            "-h" | "--help" => {
                print_help();
                process::exit(0);
            }
            "-o" | "--output" => {
                index += 1;
                let Some(value) = raw_args.get(index) else {
                    return Err("--output requires a path".to_string());
                };
                args.output = Some(PathBuf::from(value));
            }
            "--source-map" => {
                index += 1;
                let Some(value) = raw_args.get(index) else {
                    return Err("--source-map requires a path".to_string());
                };
                args.source_map = Some(PathBuf::from(value));
            }
            "--aggressive" => args.aggressive = true,
            "--line-width" => {
                index += 1;
                let Some(value) = raw_args.get(index) else {
                    return Err("--line-width requires a number".to_string());
                };
                args.line_width = value
                    .parse()
                    .map_err(|_| "--line-width requires a number".to_string())?;
            }
            value if value.starts_with('-') => return Err(format!("unknown option: {value}")),
            value => {
                if args.input.is_some() {
                    return Err("only one input path is supported".to_string());
                }
                args.input = Some(PathBuf::from(value));
            }
        }
        index += 1;
    }

    if args.aggressive && !args.reverse {
        return Err("--aggressive is only supported with from-rust".to_string());
    }
    Ok(args)
}

fn read_source(path: Option<&PathBuf>) -> Result<String, Box<dyn std::error::Error>> {
    match path {
        Some(path) => Ok(fs::read_to_string(path)?),
        None => {
            let mut source = String::new();
            io::stdin().read_to_string(&mut source)?;
            Ok(source)
        }
    }
}

fn source_syntax(path: Option<&Path>) -> SourceSyntax {
    match path
        .and_then(Path::extension)
        .and_then(|extension| extension.to_str())
    {
        Some("rs") => SourceSyntax::Rust,
        _ => SourceSyntax::Rusk,
    }
}

fn print_help() {
    println!(
        "rusk - indentation-based Rust syntax transpiler\n\nUSAGE:\n    rusk [transpile] [INPUT.rsk] [-o OUTPUT.rs] [--source-map SOURCE_MAP]\n    rusk from-rust [INPUT.rs] [-o OUTPUT.rsk] [--aggressive]\n    rusk fmt [INPUT.rsk] [-o INPUT] [--line-width N]\n    rusk [cargo] <CARGO_COMMAND> [CARGO_ARGS...]\n    rusk script [--cargo] <SCRIPT.rsk> [ARGS...]\n    rusk add <SCRIPT.rsk> [CARGO_ADD_ARGS...]\n\nScripts keep their cargo-script frontmatter (defaulting package.edition to 2024), are transpiled to $XDG_CACHE_HOME/rusk/scripts, built with cargo +nightly -Zscript in the shared $XDG_CACHE_HOME/rusk/build (scripts that set package.name build apart), and run with RUSK_SCRIPT set to the script path; scripts without a top-level fn main run their lines in a fn main returning Result (anyhow::Result and the like when the script depends on anyhow, eyre, or color-eyre), so they can use ?; compiler diagnostics point at script lines and cargo's failure summary names the script; use #!/usr/bin/env -S rusk script as the shebang. Scripts exec the binary cached next to the generated Rust, building it with cargo only when the Rust changed, so dependency and toolchain updates need an edit to the script or --cargo, which builds through cargo's resolution and freshness checks on every run.\n\nrusk add runs cargo add on the script frontmatter (creating it when missing), so rusk add tool.rsk regex adds a dependency; it is the fix for a missing-crate error.\n\nCargo wrapper commands transpile Cargo source roots (*.rsk under src, examples, tests, benches, plus build.rsk) to cached generated .rs files, then run cargo.\n\nExamples:\n    rusk from-rust src/main.rs -o src/main.rsk\n    rusk fmt src/main.rsk -o src/main.rsk\n    rusk run\n    rusk cargo fmt\n    rusk cargo test\n\nIf INPUT is omitted, rusk reads source from stdin when stdin is piped; otherwise it prints this help."
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_project(name: &str) -> PathBuf {
        let path = env::temp_dir().join(format!("rusk-{name}-{}", process::id()));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(path.join("src")).unwrap();
        fs::write(
            path.join("Cargo.toml"),
            "[package]\nname = \"rusk-wrapper-test\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
        )
        .unwrap();
        path
    }

    #[test]
    fn transpiles_cargo_sources_to_cached_generated_rust() {
        let project = temp_project("cargo-sources");
        let source_path = project.join("src/main.rsk");
        let rust_path = project.join("src/main.rs");
        fs::write(&source_path, "pub fn main():\n    println!(\"hello\")\n").unwrap();

        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);
        let rust = fs::read_to_string(&rust_path).unwrap();
        assert!(rust.starts_with(GENERATED_HEADER));
        assert!(rust.contains("println!(\"hello\");"));

        let mut permissions = fs::metadata(&rust_path).unwrap().permissions();
        permissions.set_readonly(true);
        fs::set_permissions(&rust_path, permissions).unwrap();
        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);

        let mut permissions = fs::metadata(&rust_path).unwrap().permissions();
        permissions.set_readonly(false);
        fs::set_permissions(&rust_path, permissions).unwrap();
        fs::write(&source_path, "pub fn main():\n    println!(\"cached\")\n").unwrap();
        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);
        let rust = fs::read_to_string(&rust_path).unwrap();
        assert!(rust.starts_with(GENERATED_HEADER));
        assert!(rust.contains("println!(\"cached\");"));

        let _ = fs::remove_dir_all(project);
    }

    #[test]
    fn splice_frontmatter_keeps_the_shebang_and_body() {
        let body = "\nfn main():\n    println!(\"---\")\n";
        let source = format!("#!/usr/bin/env -S rusk script\n\n---\n[package]\n---\n{body}");
        let spliced = splice_frontmatter(&source, "---\n[dependencies]\n---\n").unwrap();
        assert_eq!(
            spliced,
            format!("#!/usr/bin/env -S rusk script\n\n---\n[dependencies]\n---\n{body}")
        );
        assert_eq!(script_frontmatter(&source).unwrap(), "---\n[package]\n---\n");
    }

    #[test]
    fn splice_frontmatter_creates_the_frontmatter_after_the_shebang() {
        let source = "#!/usr/bin/env -S rusk script\nprintln!(\"hi\")\n";
        assert_eq!(script_frontmatter(source).unwrap(), "---\n---\n");
        assert_eq!(
            splice_frontmatter(source, "---\n[dependencies]\n---\n").unwrap(),
            "#!/usr/bin/env -S rusk script\n---\n[dependencies]\n---\nprintln!(\"hi\")\n"
        );
        assert_eq!(
            splice_frontmatter("#![allow(unused)]\n", "---\n---\n").unwrap(),
            "---\n---\n#![allow(unused)]\n"
        );
        assert!(splice_frontmatter("---\nx\n", "---\n---\n").is_err());
    }

    #[test]
    fn script_cache_is_rewritten_only_when_the_rust_changes() {
        let project = temp_project("script-cache");
        let path = project.join("tool.rs");

        write_script_cache(&path, "fn main() {}\n").unwrap();
        let writable = fs::metadata(&path).unwrap().permissions();
        let mut permissions = writable.clone();
        permissions.set_readonly(true);
        fs::set_permissions(&path, permissions).unwrap();
        write_script_cache(&path, "fn main() {}\n").unwrap();

        fs::set_permissions(&path, writable).unwrap();
        write_script_cache(&path, "fn main() { () }\n").unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), "fn main() { () }\n");
        let _ = fs::remove_dir_all(project);
    }

    #[test]
    fn refuses_to_overwrite_non_generated_rust() {
        let project = temp_project("cargo-conflict");
        fs::write(project.join("src/main.rsk"), "pub fn main() = 1\n").unwrap();
        fs::write(project.join("src/main.rs"), "fn main() {}\n").unwrap();

        let error = transpile_cargo_sources(&project).unwrap_err().to_string();
        assert!(error.contains("refusing to overwrite non-generated Rust file"));
        let _ = fs::remove_dir_all(project);
    }
}
