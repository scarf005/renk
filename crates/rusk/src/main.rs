#[cfg(test)]
mod tests {
    use super::*;

    fn temp_project(name: &str) -> PathBuf {
        let path = env::temp_dir().join(format!("rusk-{name}-{}", process::id()));
        let _ = fs::remove_dir_all(&path);
        fs::create_dir_all(path.join("src")).unwrap();
        fs::write(
            path.join("Cargo.toml"),
            "[package]\nname = \"rusk-wrapper-test\"\nversion = \"0.1.0\"\nedition = \"2024\"\n",
        )
        .unwrap();
        path
    }

    #[test]
    fn transpiles_cargo_sources_to_cached_generated_rust() {
        let project = temp_project("cargo-sources");
        let source_path = project.join("src/main.rsk");
        let rust_path = project.join("src/main.rs");
        fs::write(&source_path, "pub fn main():\n    println!(\"hello\")\n").unwrap();

        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);
        let rust = fs::read_to_string(&rust_path).unwrap();
        assert!(rust.starts_with(GENERATED_HEADER));
        assert!(rust.contains("println!(\"hello\");"));

        let mut permissions = fs::metadata(&rust_path).unwrap().permissions();
        permissions.set_readonly(true);
        fs::set_permissions(&rust_path, permissions).unwrap();
        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);

        let mut permissions = fs::metadata(&rust_path).unwrap().permissions();
        permissions.set_readonly(false);
        fs::set_permissions(&rust_path, permissions).unwrap();
        fs::write(&source_path, "pub fn main():\n    println!(\"cached\")\n").unwrap();
        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);
        let rust = fs::read_to_string(&rust_path).unwrap();
        assert!(rust.starts_with(GENERATED_HEADER));
        assert!(rust.contains("println!(\"cached\");"));

        let _ = fs::remove_dir_all(project);
    }

    #[test]
    fn transpiles_ruk_cargo_sources_to_cached_generated_rust() {
        let project = temp_project("cargo-ruk-sources");
        let source_path = project.join("src/main.rk");
        let rust_path = project.join("src/main.rs");
        fs::write(
            &source_path,
            "pub fn main() {\n    println!(\"hello\")\n}\n",
        )
        .unwrap();

        let generated = transpile_cargo_sources(&project).unwrap();
        assert_eq!(generated, vec![rust_path.clone()]);
        let rust = fs::read_to_string(&rust_path).unwrap();
        assert!(rust.starts_with(GENERATED_HEADER));
        assert!(rust.contains("println!(\"hello\");"));
        let _ = fs::remove_dir_all(project);
    }

    #[test]
    fn script_rust_keeps_frontmatter_first_and_drops_the_shebang() {
        let source = "#!/usr/bin/env -S rusk script\n---\n[dependencies]\nregex = \"1\"\n---\n\nfn main():\n    println!(\"hi\")\n";

        let rust = script_rust(source, SourceSyntax::Rusk).unwrap().rust;
        assert!(rust.starts_with(
            "---\n[dependencies]\nregex = \"1\"\n\n[package]\nedition = \"2024\"\n---\n"
        ));
        assert!(!rust.contains("#!/usr/bin/env"));
        assert!(rust.contains("println!(\"hi\");"));
    }

    #[test]
    fn script_rust_treats_inner_attributes_and_later_dashes_as_body() {
        let source = "#![allow(unused)]\nfn main():\n    let s = \"\n---\n\"\n    print!(\"{s}\")\n";

        let rust = script_rust(source, SourceSyntax::Rusk).unwrap().rust;
        assert!(rust.starts_with("---\n[package]\nedition = \"2024\"\n---\n#![allow(unused)]"));
        assert!(rust.contains("\n---\n"));
    }

    #[test]
    fn script_rust_accepts_infostrings_and_longer_fences() {
        let source = "#!/usr/bin/env -S rusk script\n----cargo\n[package]\nedition = \"2024\"\n---\n----\nfn main() = ()\n";

        let rust = script_rust(source, SourceSyntax::Rusk).unwrap().rust;
        assert!(rust.starts_with("----cargo\n[package]\nedition = \"2024\"\n---\n----\n"));
        assert!(rust.contains("fn main()"));
    }

    #[test]
    fn script_rust_rejects_unclosed_frontmatter() {
        let error = script_rust("---\n[dependencies]\nfn main() = ()\n", SourceSyntax::Rusk)
            .unwrap_err()
            .to_string();
        assert!(error.contains("unclosed frontmatter"), "{error}");
    }

    #[test]
    fn script_errors_report_the_physical_script_line() {
        let source = "#!/usr/bin/env -S rusk script\n---\n[package]\n---\nfn main():\n\tprintln!(\"tab\")\n";

        let error = script_rust(source, SourceSyntax::Rusk).unwrap_err().to_string();
        assert!(error.contains("line 6"), "{error}");
    }

    #[test]
    fn script_diagnostics_renumber_script_gutters_and_keep_other_files() {
        let diagnostic = ScriptDiagnostic {
            rust_file: "tool.rs",
            script: "bin/tool.rsk",
            source_lines: &[(3, false), (9, false), (10, false), (10, true)],
        };
        let rendered = "error: oops\n --> tool.rs:2:5\n  |\n2 |     a();\n3 |     b()\n4 | }\n  |\n ::: lib.rs:4:1\n4 | fn a() {}\n  = note: x\n";

        assert_eq!(
            diagnostic.remap(rendered),
            "error: oops\n  --> bin/tool.rsk:9:5\n   |\n 9 |     a();\n10 |     b()\n   | }\n   |\n  ::: lib.rs:4:1\n 4 | fn a() {}\n   = note: x\n"
        );
        let styled = "\x1b[1m\x1b[94m--> \x1b[0mtool.rs:1:2\n\x1b[1m\x1b[94m1\x1b[0m \x1b[1m\x1b[94m|\x1b[0m x\n";
        assert_eq!(
            diagnostic.remap(styled),
            "\x1b[1m\x1b[94m--> \x1b[0mbin/tool.rsk:3:2\n\x1b[1m\x1b[94m3\x1b[0m \x1b[1m\x1b[94m|\x1b[0m x\n"
        );
    }

    #[test]
    fn script_cache_is_per_source_path_and_keeps_the_stem() {
        let root = Path::new("/cache");
        let first = script_cache_path(root, Path::new("/a/tool.rsk"));
        let second = script_cache_path(root, Path::new("/b/tool.rsk"));

        assert_ne!(first, second);
        assert_eq!(first.file_name().unwrap(), "tool.rs");
        assert!(first.starts_with("/cache"));
        assert_eq!(first, script_cache_path(root, Path::new("/a/tool.rsk")));
        let dotted = script_cache_path(root, Path::new("/a/setup-itch.io.rsk"));
        assert_eq!(dotted.file_name().unwrap(), "setup-itch.io.rs");
    }

    #[test]
    fn script_cache_is_rewritten_only_when_the_rust_changes() {
        let project = temp_project("script-cache");
        let path = project.join("tool.rs");

        write_script_cache(&path, "fn main() {}\n").unwrap();
        let writable = fs::metadata(&path).unwrap().permissions();
        let mut permissions = writable.clone();
        permissions.set_readonly(true);
        fs::set_permissions(&path, permissions).unwrap();
        write_script_cache(&path, "fn main() {}\n").unwrap();

        fs::set_permissions(&path, writable).unwrap();
        write_script_cache(&path, "fn main() { () }\n").unwrap();
        assert_eq!(fs::read_to_string(&path).unwrap(), "fn main() { () }\n");
        let _ = fs::remove_dir_all(project);
    }

    #[test]
    fn refuses_to_overwrite_non_generated_rust() {
        let project = temp_project("cargo-conflict");
        fs::write(project.join("src/main.rsk"), "pub fn main() = 1\n").unwrap();
        fs::write(project.join("src/main.rs"), "fn main() {}\n").unwrap();

        let error = transpile_cargo_sources(&project).unwrap_err().to_string();
        assert!(error.contains("refusing to overwrite non-generated Rust file"));
        let _ = fs::remove_dir_all(project);
    }
}
