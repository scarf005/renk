/// Hands rust-analyzer's responses to their requests. Its own requests get an answer here: their
/// ids are rust-analyzer's, which would otherwise take the place of a response to a request of
/// ours with the same id. `workspace/configuration` gets `config`, the settings it started with,
/// once per item; the rest get an empty answer. Its notifications go to `notifications`, and so
/// does `workspace/diagnostic/refresh`. When the output ends, the requests that wait for a
/// response fail, and later requests are not sent.
async fn read_rust_analyzer_messages(
    stdout: impl tokio::io::AsyncRead + Unpin,
    pending: PendingReplies,
    replies: mpsc::UnboundedSender<serde_json::Value>,
    notifications: mpsc::UnboundedSender<serde_json::Value>,
    config: serde_json::Value,
) {
    let mut reader = BufReader::new(stdout);
    loop {
        let Some(message) = read_lsp_message(&mut reader).await else {
            break;
        };
        if message.get("method").is_some() {
            if let Some(id) = message.get("id") {
                let result = if message["method"] == "workspace/configuration" {
                    let items = message["params"]["items"].as_array().map_or(0, Vec::len);
                    serde_json::Value::Array(vec![config.clone(); items])
                } else {
                    serde_json::Value::Null
                };
                let _ = replies.send(serde_json::json!({
                    "jsonrpc": "2.0",
                    "id": id,
                    "result": result,
                }));
                if message["method"] == "workspace/diagnostic/refresh" {
                    let _ = notifications.send(message);
                }
            } else {
                let _ = notifications.send(message);
            }
            continue;
        }
        let Some(id) = message.get("id").and_then(serde_json::Value::as_u64) else {
            continue;
        };
        let sender = pending
            .lock()
            .await
            .as_mut()
            .and_then(|pending| pending.remove(&id));
        if let Some(sender) = sender {
            let _ = sender.send(message);
        }
    }
    pending.lock().await.take();
}

async fn read_lsp_message<R: tokio::io::AsyncBufRead + Unpin>(
    reader: &mut R,
) -> Option<serde_json::Value> {
    serde_json::from_slice(&read_lsp_body(reader).await?).ok()
}

async fn read_lsp_body<R: tokio::io::AsyncBufRead + Unpin>(reader: &mut R) -> Option<Vec<u8>> {
    let mut content_length = None;
    loop {
        let mut line = String::new();
        if reader.read_line(&mut line).await.ok()? == 0 {
            return None;
        }
        let line = line.trim_end_matches(['\r', '\n']);
        if line.is_empty() {
            break;
        }
        if let Some((name, value)) = line.split_once(':')
            && name.trim().eq_ignore_ascii_case("content-length")
        {
            content_length = value.trim().parse::<usize>().ok();
        }
    }

    // Read as the bytes arrive: a length that the input never reaches must not allocate.
    let length = content_length?;
    let mut body = Vec::new();
    reader
        .take(length as u64)
        .read_to_end(&mut body)
        .await
        .ok()?;
    (body.len() == length).then_some(body)
}

async fn write_lsp_message<W: tokio::io::AsyncWrite + Unpin>(
    writer: &mut W,
    message: &serde_json::Value,
) -> std::io::Result<()> {
    write_lsp_body(writer, &serde_json::to_vec(message)?).await
}

async fn write_lsp_body<W: tokio::io::AsyncWrite + Unpin>(
    writer: &mut W,
    body: &[u8],
) -> std::io::Result<()> {
    writer
        .write_all(format!("Content-Length: {}\r\n\r\n", body.len()).as_bytes())
        .await?;
    writer.write_all(body).await?;
    writer.flush().await
}

/// Passes the editor's messages from `stdin` on to `server`, tower-lsp's input, and ends that
/// input after `exit`: tower-lsp stops only when its input ends. A `null` `params` is left out,
/// because tower-lsp refuses any `params` of a method that takes none, such as `shutdown`.
async fn forward_editor_messages(
    stdin: impl tokio::io::AsyncRead + Unpin,
    mut server: impl tokio::io::AsyncWrite + Unpin,
) {
    let mut reader = BufReader::new(stdin);
    while let Some(body) = read_lsp_body(&mut reader).await {
        let message = serde_json::from_slice::<serde_json::Value>(&body);
        let exit = message
            .as_ref()
            .is_ok_and(|message| message["method"] == "exit");
        let body = match message {
            Ok(serde_json::Value::Object(mut message))
                if message.get("params") == Some(&serde_json::Value::Null) =>
            {
                message.remove("params");
                serde_json::to_vec(&message).unwrap_or(body)
            }
            _ => body,
        };
        if write_lsp_body(&mut server, &body).await.is_err() || exit {
            break;
        }
    }
}

fn rust_initialize_params(mut params: InitializeParams, rust_root_uri: &Url) -> InitializeParams {
    // Keep rust-analyzer on the default UTF-16 columns that renk-lsp also uses.
    if let Some(general) = params.capabilities.general.as_mut() {
        general.position_encodings = None;
    }
    // Code actions and inlay hints come whole, with plain text edits that renk-lsp maps.
    let text_document = params
        .capabilities
        .text_document
        .get_or_insert_with(Default::default);
    text_document.code_action = Some(CodeActionClientCapabilities {
        code_action_literal_support: Some(CodeActionLiteralSupport {
            code_action_kind: CodeActionKindLiteralSupport {
                value_set: [
                    CodeActionKind::EMPTY,
                    CodeActionKind::QUICKFIX,
                    CodeActionKind::REFACTOR,
                    CodeActionKind::REFACTOR_EXTRACT,
                    CodeActionKind::REFACTOR_INLINE,
                    CodeActionKind::REFACTOR_REWRITE,
                    CodeActionKind::SOURCE,
                    CodeActionKind::SOURCE_ORGANIZE_IMPORTS,
                ]
                .map(|kind| kind.as_str().to_string())
                .to_vec(),
            },
        }),
        ..CodeActionClientCapabilities::default()
    });
    if let Some(inlay_hint) = text_document.inlay_hint.as_mut() {
        inlay_hint.resolve_support = None;
    }
    // Completions too, with each item's own edits.
    if let Some(completion) = text_document.completion.as_mut() {
        completion.completion_list = None;
        if let Some(item) = completion.completion_item.as_mut() {
            item.resolve_support = None;
        }
    }
    if let Some(experimental) = params
        .capabilities
        .experimental
        .as_mut()
        .and_then(serde_json::Value::as_object_mut)
    {
        experimental.remove("snippetTextEdit");
    }
    params.root_uri = Some(rust_root_uri.clone());
    params.workspace_folders = Some(vec![WorkspaceFolder {
        uri: rust_root_uri.clone(),
        name: "renk-generated".to_string(),
    }]);
    params
}

/// rust-analyzer's `initialize` request for `params`, which pulls its diagnostics. rust-analyzer
/// then answers each pull with the whole set, and asks for a new pull after each change. When it
/// publishes them instead, it can stop at the syntax-only set from before the workspace finished
/// loading. lsp-types calls `workspace.diagnostics` `diagnostic`, so this edits the JSON.
fn rust_initialize_request(params: &InitializeParams) -> serde_json::Value {
    let mut request = serde_json::json!(params);
    let capabilities = &mut request["capabilities"];
    capabilities["textDocument"]["diagnostic"] = serde_json::json!({});
    capabilities["workspace"]["diagnostics"] = serde_json::json!({"refreshSupport": true});
    request
}

/// The directory of the mirror of the workspace at `root`.
fn rust_root(root: &Path) -> PathBuf {
    root.join("target").join("renk")
}

/// The directory of a mirror that holds the packages outside its workspace, at their absolute
/// paths. Inside the mirror, they become members of its workspace.
const OUTSIDE: &str = ".outside";

/// Where the mirror of the workspace at `root` keeps its copy of the file at `path`.
fn mirror_path(root: &Path, path: &Path) -> PathBuf {
    match path.strip_prefix(root) {
        Ok(relative) => rust_root(root).join(relative),
        Err(_) => rust_root(root).join(OUTSIDE).join(
            (path.components())
                .filter(|component| matches!(component, Component::Normal(_)))
                .collect::<PathBuf>(),
        ),
    }
}

/// The file that `path` in the mirror of the workspace at `root` is a copy of.
fn mirrored_path(root: &Path, path: &Path) -> Option<PathBuf> {
    let relative = path.strip_prefix(rust_root(root)).ok()?;
    Some(match relative.strip_prefix(OUTSIDE) {
        Ok(outside) => Path::new(std::path::MAIN_SEPARATOR_STR).join(outside),
        Err(_) => root.join(relative),
    })
}

/// The canonical path of a file that may not exist yet, like a new editor buffer.
fn canonical(path: &Path) -> Option<PathBuf> {
    fs::canonicalize(path).ok().or_else(|| {
        Some(
            fs::canonicalize(path.parent()?)
                .ok()?
                .join(path.file_name()?),
        )
    })
}

/// Runs `work`, which reads or writes files, on a blocking thread; `None` when it panicked.
async fn blocking<T: Send + 'static>(work: impl FnOnce() -> T + Send + 'static) -> Option<T> {
    tokio::task::spawn_blocking(work).await.ok()
}

/// The workspace of a Renk module or a Rust file, and the Rust file in its mirror: the module's
/// generated Rust, or the file's copy.
fn mirrored_file(uri: &Url) -> Option<(Workspace, PathBuf)> {
    let path = canonical(&uri.to_file_path().ok()?)?;
    let workspace = project::workspace(path.parent()?)?;
    let rust = mirror_path(&workspace.root, &path).with_extension("rs");
    Some((workspace, rust))
}

/// Copies the manifest in `dir` to the mirror of `workspace`, with each `path` dependency at its
/// copy there, and returns the copy. The root manifest's workspace gets every other package of
/// `workspace` as its members.
fn mirror_manifest(workspace: &Workspace, dir: &Path) -> Option<PathBuf> {
    let text = fs::read_to_string(dir.join("Cargo.toml")).ok()?;
    let mut manifest = text.parse::<DocumentMut>().ok()?;
    project::visit_dependency_paths(manifest.as_table_mut(), &mut |path| {
        if let Some(package) =
            (path.as_str()).and_then(|path| fs::canonicalize(dir.join(path)).ok())
        {
            let decor = path.decor().clone();
            *path = mirror_path(&workspace.root, &package)
                .display()
                .to_string()
                .into();
            *path.decor_mut() = decor;
        }
    });
    if dir == workspace.root {
        let members = (workspace.packages.iter())
            .filter(|package| **package != workspace.root)
            .filter_map(|package| {
                let copy = mirror_path(&workspace.root, package);
                let relative = copy.strip_prefix(rust_root(dir)).ok()?;
                Some(relative.display().to_string())
            })
            // In one order, so a refresh rewrites the manifest only when its packages change.
            .collect::<BTreeSet<_>>();
        let table = manifest.entry("workspace").or_insert(toml_edit::table());
        table["members"] = toml_edit::value(members.into_iter().collect::<toml_edit::Array>());
    }
    let copy = mirror_path(&workspace.root, &dir.join("Cargo.toml"));
    write_if_changed(&copy, &manifest.to_string());
    Some(copy)
}

/// Writes a module's generated Rust, which starts with renk's header, unless a file without the
/// header, which renk did not write, is there.
fn write_generated_rust_file(path: &Path, rust: &str) {
    if fs::read_to_string(path).is_ok_and(|existing| !existing.starts_with(GENERATED_HEADER)) {
        return;
    }
    write_if_changed(path, rust);
}

fn write_if_changed(path: &Path, content: &str) {
    if fs::read_to_string(path).is_ok_and(|existing| existing == content) {
        return;
    }
    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(path, content);
}

/// Brings the mirror of `workspace` up to date for `cargo check`: the manifests and hand-written
/// Rust files of its packages, and the generated Rust of their Renk modules, of the text in
/// `documents` for an open one. It removes every other Rust file and manifest of the mirror but
/// the generated Rust of the open `documents`, which may have no file yet.
fn mirror_workspace(workspace: &Workspace, documents: &HashMap<Url, String>) {
    let root = &workspace.root;
    let open = (documents.iter())
        .filter(|(uri, text)| !is_script(uri, text))
        .filter_map(|(uri, text)| Some((canonical(&uri.to_file_path().ok()?)?, (uri, text))))
        .collect::<HashMap<_, _>>();
    let mut kept = (open.keys())
        .map(|path| mirror_path(root, path).with_extension("rs"))
        .collect::<HashSet<_>>();
    let dirs = std::iter::once(root).chain(&workspace.packages);
    kept.extend(dirs.filter_map(|dir| mirror_manifest(workspace, dir)));
    for package in &workspace.packages {
        let hand_written = project::rust_sources(package).unwrap_or_default();
        let copies = (hand_written.iter())
            .map(|path| mirror_path(root, path))
            .collect::<HashSet<_>>();
        for path in project::sources(package).unwrap_or_default() {
            let rust = mirror_path(root, &path).with_extension("rs");
            kept.insert(rust.clone());
            // A hand-written file beside the module wins.
            if copies.contains(&rust) {
                continue;
            }
            let (uri, text) = match open.get(&path) {
                Some(&(uri, text)) => (uri.clone(), text.clone()),
                None => match (Url::from_file_path(&path), fs::read_to_string(&path)) {
                    (Ok(uri), Ok(text)) => (uri, text),
                    _ => continue,
                },
            };
            if !is_script(&uri, &text)
                && let Ok(generated) = generated(&uri, &text)
            {
                // Replace the copy of a deleted hand-written file with the same stem.
                write_if_changed(&rust, &generated.rust);
            }
        }
        for path in hand_written {
            let copy = mirror_path(root, &path);
            if let Ok(text) = fs::read_to_string(&path) {
                write_if_changed(&copy, &text);
            }
            kept.insert(copy);
        }
    }
    let rust_root = rust_root(root);
    for path in files(&rust_root, &rust_root.join("target")) {
        let mirrored = path.extension().is_some_and(|extension| extension == "rs")
            || path.ends_with("Cargo.toml");
        if mirrored && !kept.contains(&path) {
            let _ = fs::remove_file(&path);
        }
    }
}

/// The files under `dir`, but not under `skipped`, without following symlinks.
fn files(dir: &Path, skipped: &Path) -> Vec<PathBuf> {
    (fs::read_dir(dir).into_iter().flatten().flatten())
        .flat_map(|entry| match entry.file_type() {
            Ok(kind) if kind.is_dir() && entry.path() != skipped => files(&entry.path(), skipped),
            Ok(kind) if kind.is_file() => vec![entry.path()],
            _ => Vec::new(),
        })
        .collect()
}

/// The protocol's RequestFailed error with `message`, which the editor shows.
fn request_failed(message: String) -> Error {
    Error {
        code: ErrorCode::from(-32803),
        message: message.into(),
        data: None,
    }
}

/// A document's text as `renk fmt --write` writes it, or the error that `renk fmt` prints. rustfmt
/// runs in the document's folder, so it reads the `rustfmt.toml` of the document's project.
fn formatted(uri: &Url, text: &str) -> std::result::Result<String, String> {
    // The formatter ends even an empty file with a line break.
    if text.is_empty() {
        return Ok(String::new());
    }
    let path = uri.to_file_path().ok();
    let dir = (path.as_ref().and_then(|path| path.parent())).filter(|dir| dir.is_dir());
    let dir = dir.unwrap_or(Path::new("."));
    renk::rustfmt("", dir)?;
    let rustfmt = |rust: &str| renk::rustfmt(rust, dir).ok().flatten();
    format_source_with(text, &rustfmt).map_err(|error| {
        let name = path.map_or_else(|| uri.to_string(), |path| path.display().to_string());
        format!("{name}:{error}")
    })
}

/// Whether a document is Rust, which the editor's own rust-analyzer serves: as a Renk document,
/// its edits would turn into Renk.
fn is_rust(uri: &Url) -> bool {
    uri.to_file_path()
        .is_ok_and(|path| path.extension().is_some_and(|extension| extension == "rs"))
}

/// A document's generated Rust, as written to the file rust-analyzer and cargo read, and, for
/// each 1-based Rust line, the document line it came from and whether renk synthesized it, like
/// a closing brace or a module's generated header.
#[derive(Clone)]
struct Generated {
    rust: String,
    source_lines: Vec<(usize, bool)>,
}

#[cfg(test)]
thread_local! {
    /// How many times this thread transpiled a document.
    static TRANSPILES: std::cell::Cell<usize> = const { std::cell::Cell::new(0) };
}

type Transpiled = std::result::Result<Generated, TranspileError>;
type GeneratedDocument = (String, bool, Transpiled);

/// Each document's last text, whether it was a script, and what it transpiled to.
static GENERATED: LazyLock<std::sync::Mutex<HashMap<Url, GeneratedDocument>>> =
    LazyLock::new(Default::default);

/// [`transpile_document`] of a document, transpiling each of its versions once.
fn generated(uri: &Url, text: &str) -> Transpiled {
    let script = is_script(uri, text);
    let cache = || GENERATED.lock().unwrap_or_else(PoisonError::into_inner);
    if let Some((cached, was_script, generated)) = cache().get(uri)
        && cached == text
        && *was_script == script
    {
        return generated.clone();
    }
    let generated = transpile_document(uri, text, script);
    cache().insert(uri.clone(), (text.to_string(), script, generated.clone()));
    generated
}

fn transpile_document(uri: &Url, text: &str, script: bool) -> Transpiled {
    #[cfg(test)]
    TRANSPILES.with(|transpiles| transpiles.set(transpiles.get() + 1));
    if script {
        let package = script_rust_path(uri)
            .map_or_else(|| "script".to_string(), |path| script_package(&path));
        let script = script_rust(text, SourceSyntax::Renk, &package)?;
        let dir = uri.to_file_path().ok();
        return Ok(Generated {
            rust: match dir.as_ref().and_then(|path| path.parent()) {
                Some(dir) => absolute_dependency_paths(&script.rust, dir),
                None => script.rust,
            },
            source_lines: script.source_lines,
        });
    }
    let output = transpile(text)?;
    Ok(Generated {
        rust: format!("{GENERATED_HEADER}{}", output.rust),
        source_lines: std::iter::once((1, true))
            .chain(output.line_origins())
            .collect(),
    })
}

/// `rust`, the Rust of a script in `dir`, with each relative dependency `path` of its frontmatter
/// made absolute: rust-analyzer reads the script from renk's cache. It keeps every line where it
/// was, or returns `rust` unchanged.
fn absolute_dependency_paths(rust: &str, dir: &Path) -> String {
    let lines = rust.split_inclusive('\n').collect::<Vec<_>>();
    let Ok(Some((start, end))) = script_parts(rust).map(|parts| parts.frontmatter) else {
        return rust.to_string();
    };
    let Ok(mut manifest) = lines[start + 1..end].concat().parse::<DocumentMut>() else {
        return rust.to_string();
    };
    project::visit_dependency_paths(manifest.as_table_mut(), &mut |path| {
        if let Some(relative) = path.as_str().filter(|path| Path::new(path).is_relative()) {
            let decor = path.decor().clone();
            *path = dir.join(relative).display().to_string().into();
            *path.decor_mut() = decor;
        }
    });
    let manifest = manifest.to_string();
    if manifest.lines().count() != end - start - 1 {
        return rust.to_string();
    }
    lines[..=start].concat() + &manifest + &lines[end..].concat()
}

/// Whether a renk document runs with `renk script`: it starts with a `#!` line or frontmatter, or
/// no Cargo package around it could build it as a module.
fn is_script(uri: &Url, text: &str) -> bool {
    let headed = script_parts(text).map_or(true, |parts| parts.body_start > 0);
    let packaged = uri.to_file_path().is_ok_and(|path| {
        path.ancestors()
            .skip(1)
            .any(|dir| dir.join("Cargo.toml").is_file())
    });
    headed || !packaged
}

/// The generated cargo-script file rust-analyzer reads for a script, apart from the one
/// `renk script` builds so unsaved edits never reach a build.
fn script_rust_path(uri: &Url) -> Option<PathBuf> {
    let path = uri.to_file_path().ok()?;
    let path = fs::canonicalize(&path).unwrap_or(path);
    Some(script_cache_path(&cache_root()?.join("lsp"), &path))
}

/// The character index of a UTF-16 column of `line`.
fn char_column(line: &str, character: u32) -> usize {
    let mut units = 0;
    line.chars()
        .take_while(|c| {
            units += c.len_utf16() as u32;
            units <= character
        })
        .count()
}

/// The UTF-16 column of a character index of `line`.
fn utf16_column(line: &str, column: usize) -> u32 {
    line.chars()
        .take(column)
        .map(|c| c.len_utf16() as u32)
        .sum()
}

fn source_position_to_rust_position(
    generated: &Generated,
    text: &str,
    position: Position,
) -> Option<Position> {
    let line = position.line as usize + 1;
    let rust_line = generated
        .source_lines
        .iter()
        .position(|&(source, synthesized)| source == line && !synthesized)?;
    let source = text.lines().nth(position.line as usize).unwrap_or_default();
    let rust = generated.rust.lines().nth(rust_line).unwrap_or_default();
    let column = script_column(rust, source, char_column(source, position.character));
    Some(Position {
        line: rust_line as u32,
        character: utf16_column(rust, column),
    })
}

fn rust_range_to_source_range(generated: &Generated, text: &str, range: Range) -> Range {
    Range {
        start: rust_position_to_source_position(generated, text, range.start),
        end: rust_position_to_source_position(generated, text, range.end),
    }
}

fn rust_position_to_source_position(
    generated: &Generated,
    text: &str,
    position: Position,
) -> Position {
    let Some(&(line, synthesized)) = generated.source_lines.get(position.line as usize) else {
        return position;
    };
    let source = text.lines().nth(line.saturating_sub(1)).unwrap_or_default();
    let rust = generated
        .rust
        .lines()
        .nth(position.line as usize)
        .unwrap_or_default();
    let column = if synthesized {
        source.chars().count()
    } else {
        script_column(source, rust, char_column(rust, position.character))
    };
    Position {
        line: line.saturating_sub(1) as u32,
        character: utf16_column(source, column),
    }
}

/// The whole Rust lines generated from the document lines `range` spans.
fn rust_lines(generated: &Generated, range: Range) -> Option<Range> {
    let source = range.start.line as usize + 1..=range.end.line as usize + 1;
    let mut lines = generated
        .source_lines
        .iter()
        .enumerate()
        .filter(|(_, (line, _))| source.contains(line))
        .map(|(rust_line, _)| rust_line as u32);
    let first = lines.next()?;
    let last = lines.next_back().unwrap_or(first);
    Some(Range::new(
        Position::new(first, 0),
        Position::new(last + 1, 0),
    ))
}

/// The byte offset of `position` in `text`.
fn offset(text: &str, position: Position) -> usize {
    let mut lines = text.split_inclusive('\n');
    let before = lines
        .by_ref()
        .take(position.line as usize)
        .map(str::len)
        .sum::<usize>();
    before
        + lines
            .next()
            .map_or(0, |line| byte_column(line, position.character))
}

fn range_text(text: &str, range: Range) -> &str {
    let start = offset(text, range.start);
    &text[start..offset(text, range.end).max(start)]
}

/// Whether `a` and `b` are the same Rust tokens, ignoring the whitespace between tokens.
fn same_rust(a: &str, b: &str) -> bool {
    let tokens = |text| {
        let lexed = LexedStr::new(Edition::Edition2021, text);
        (0..lexed.len())
            .filter(|&token| lexed.kind(token) != SyntaxKind::WHITESPACE)
            .map(|token| lexed.text(token).to_string())
            .collect::<Vec<_>>()
    };
    tokens(a) == tokens(b)
}

/// An edit of a document's generated Rust as the same edit of the document, when the document
/// has the text the edit replaces where it maps to.
fn checked_edit(generated: &Generated, text: &str, edit: TextEdit) -> Option<TextEdit> {
    checked_range(generated, text, edit.range).map(|range| TextEdit::new(range, edit.new_text))
}

/// A range of a document's generated Rust at the document's positions, when the document has the
/// same text there.
fn checked_range(generated: &Generated, text: &str, range: Range) -> Option<Range> {
    let mapped = rust_range_to_source_range(generated, text, range);
    (range_text(text, mapped) == range_text(&generated.rust, range)).then_some(mapped)
}

/// rust-analyzer's semantic tokens of a document's generated Rust, in rust-analyzer's `legend`, as
/// the document's tokens in [`TOKEN_TYPES`] and [`TOKEN_MODIFIERS`]: each one of a type the legend
/// names that covers the same text in one line of the document.
fn semantic_tokens(
    generated: &Generated,
    text: &str,
    legend: &SemanticTokensLegend,
    rust: &[SemanticToken],
) -> Vec<SemanticToken> {
    let index = |names: &str, name: &str| names.split(' ').position(|known| known == name);
    // A token's bitset is a u32, so it can name only the first 32 modifiers.
    let modifiers: Vec<_> = (legend.token_modifiers.iter().take(32))
        .map(|modifier| index(TOKEN_MODIFIERS, modifier.as_str()))
        .collect();
    let mut start = Position::new(0, 0);
    let mut tokens: Vec<_> = (rust.iter())
        .filter_map(|token| {
            if token.delta_line > 0 {
                start = Position::new(start.line + token.delta_line, 0);
            }
            start.character += token.delta_start;
            let token_type = legend.token_types.get(token.token_type as usize)?;
            let token_type = index(TOKEN_TYPES, token_type.as_str())? as u32;
            let end = Position::new(start.line, start.character + token.length);
            let range = checked_range(generated, text, Range::new(start, end))?;
            let modifiers = (modifiers.iter().enumerate())
                .filter(|(bit, _)| token.token_modifiers_bitset >> bit & 1 == 1)
                .filter_map(|(_, modifier)| *modifier)
                .fold(0, |bits, modifier| bits | 1 << modifier);
            (range.start.line == range.end.line).then_some((range, token_type, modifiers))
        })
        .collect();
    tokens.sort_by_key(|(range, ..)| (range.start.line, range.start.character));
    tokens.dedup_by_key(|(range, ..)| range.start);
    let mut previous = Position::new(0, 0);
    (tokens.into_iter())
        .map(|(range, token_type, token_modifiers_bitset)| {
            let delta_line = range.start.line - previous.line;
            if delta_line > 0 {
                previous.character = 0;
            }
            let delta_start = range.start.character - previous.character;
            previous = range.start;
            SemanticToken {
                delta_line,
                delta_start,
                length: range.end.character - range.start.character,
                token_type,
                token_modifiers_bitset,
            }
        })
        .collect()
}

/// A completion of a document's generated Rust with its edits at the document's positions, or
/// `None` when an edit does not map. renk-lsp converts the extra edits, such as a new `use` line,
/// with [`renk_edits`], and drops the item when one of them overlaps the completion's own edit.
fn completion_item(
    generated: &Generated,
    text: &str,
    script: bool,
    item: CompletionItem,
) -> Option<CompletionItem> {
    let range = |range| checked_range(generated, text, range);
    let text_edit = match item.text_edit {
        Some(CompletionTextEdit::Edit(edit)) => Some(CompletionTextEdit::Edit(TextEdit {
            range: range(edit.range)?,
            ..edit
        })),
        Some(CompletionTextEdit::InsertAndReplace(edit)) => {
            Some(CompletionTextEdit::InsertAndReplace(InsertReplaceEdit {
                insert: range(edit.insert)?,
                replace: range(edit.replace)?,
                ..edit
            }))
        }
        None => None,
    };
    let edited = match &text_edit {
        Some(CompletionTextEdit::Edit(edit)) => vec![edit.range],
        Some(CompletionTextEdit::InsertAndReplace(edit)) => vec![edit.insert, edit.replace],
        None => Vec::new(),
    };
    // The protocol counts an insertion at the same position as an overlap.
    let overlaps = |edit: &TextEdit| {
        (edited.iter()).any(|range| edit.range.start <= range.end && range.start <= edit.range.end)
    };
    let additional_text_edits = item
        .additional_text_edits
        .map(|edits| {
            let edits = renk_edits(text, &generated.rust, &edits, script)?;
            (!edits.iter().any(overlaps)).then_some(edits)
        })
        .map_or(Some(None), |edits| edits.map(Some))?;
    Some(CompletionItem {
        text_edit,
        additional_text_edits,
        ..item
    })
}

/// `text` after `edits`, which do not overlap.
fn edited(text: &str, edits: &[TextEdit]) -> String {
    let mut edited = text.to_string();
    let mut edits = edits.to_vec();
    edits.sort_by_key(|edit| std::cmp::Reverse(offset(text, edit.range.start)));
    for edit in edits {
        let start = offset(text, edit.range.start);
        edited.replace_range(
            start..offset(text, edit.range.end).max(start),
            &edit.new_text,
        );
    }
    edited
}

/// Renk edits of `source` that make the change `edits` make to its generated Rust `rust`, or
/// `None` when some of it falls where `source` differs from `rust` converted back to Renk, or in
/// a script's frontmatter or `fn main` wrapper header, which do not convert back.
///
/// Both versions of the Rust convert to Renk, as [`rust_to_renk`] or for a script [`script_renk`]
/// does, and the line hunks between those conversions apply to the lines of `source` that the old
/// conversion's lines match: a hunk applies only when the lines it replaces match consecutive
/// lines of `source`, or when it inserts next to a matching line.
fn renk_edits(source: &str, rust: &str, edits: &[TextEdit], script: bool) -> Option<Vec<TextEdit>> {
    let edited = edited(rust, edits);
    let to_renk = |rust: &str| match script {
        true => script_renk(source, rust),
        false => rust_to_renk(rust).ok().map(|renk| (renk, String::new())),
    };
    let (before, left_out) = to_renk(rust)?;
    let (after, edited_left_out) = to_renk(&edited)?;
    if left_out != edited_left_out {
        return None;
    }
    let before = before.lines().collect::<Vec<_>>();
    let after = after.lines().collect::<Vec<_>>();
    let source = source.lines().collect::<Vec<_>>();

    let mut matching = vec![None; before.len()];
    for op in capture_diff_slices(Algorithm::Myers, &before, &source) {
        if let DiffOp::Equal {
            old_index,
            new_index,
            len,
        } = op
        {
            for offset in 0..len {
                matching[old_index + offset] = Some(new_index + offset);
            }
        }
    }
    capture_diff_slices(Algorithm::Myers, &before, &after)
        .iter()
        .filter(|op| op.tag() != DiffTag::Equal)
        .map(|op| {
            let (_, old, new) = op.as_tag_tuple();
            let lines = if old.is_empty() {
                let after_previous = old.start.checked_sub(1).and_then(|line| matching[line]);
                match after_previous {
                    Some(line) => line + 1..line + 1,
                    None => matching
                        .get(old.start)
                        .copied()
                        .flatten()
                        .map(|line| line..line)?,
                }
            } else {
                let start = matching[old.start]?;
                old.clone()
                    .zip(start..)
                    .all(|(line, source)| matching[line] == Some(source))
                    .then_some(start..start + old.len())?
            };
            Some(TextEdit::new(
                Range::new(
                    Position::new(lines.start as u32, 0),
                    Position::new(lines.end as u32, 0),
                ),
                after[new].iter().map(|line| format!("{line}\n")).collect(),
            ))
        })
        .collect()
}

/// A file of the editor that rust-analyzer's file is the generated Rust or the mirror copy of.
enum Origin {
    Renk {
        uri: Url,
        text: String,
        generated: Generated,
        script: bool,
    },
    File(Url),
}

/// Maps rust-analyzer's files, locations, and edits back to the editor's.
struct Origins {
    documents: HashMap<Url, String>,
    /// The open document each opened generated Rust URI is of.
    sources: HashMap<Url, Url>,
    /// The roots of the workspaces with a mirror.
    roots: Vec<PathBuf>,
    cache: HashMap<Url, Option<Origin>>,
}

impl Origins {
    fn origin(&mut self, rust_uri: &Url) -> Option<&Origin> {
        if !self.cache.contains_key(rust_uri) {
            let origin = self.find_origin(rust_uri);
            self.cache.insert(rust_uri.clone(), origin);
        }
        self.cache[rust_uri].as_ref()
    }

    /// The open document of an opened generated Rust file, or in the mirror, the Renk module on
    /// disk, read from disk unless it is open, or the hand-written file a copy is of.
    fn find_origin(&self, rust_uri: &Url) -> Option<Origin> {
        let Some(uri) = self.renk_uri(rust_uri) else {
            let path = self.mirrored(rust_uri)?;
            return path
                .is_file()
                .then(|| Url::from_file_path(path).ok().map(Origin::File))?;
        };
        let text = self.text(&uri)?;
        Some(Origin::Renk {
            generated: generated(&uri, &text).ok()?,
            script: is_script(&uri, &text),
            uri,
            text,
        })
    }

    /// The open document of an opened generated Rust file, or the Renk module on disk of a
    /// generated file in the mirror.
    fn renk_uri(&self, rust_uri: &Url) -> Option<Url> {
        if let Some(uri) = self.sources.get(rust_uri) {
            return Some(uri.clone());
        }
        let renk = self.mirrored(rust_uri)?.with_extension("rk");
        renk.is_file().then(|| Url::from_file_path(renk).ok())?
    }

    /// A document's text, read from disk unless it is open.
    fn text(&self, uri: &Url) -> Option<String> {
        match self.documents.get(uri) {
            Some(text) => Some(text.clone()),
            None => fs::read_to_string(uri.to_file_path().ok()?).ok(),
        }
    }

    /// The workspace path that a path in the mirror stands for.
    fn mirrored(&self, rust_uri: &Url) -> Option<PathBuf> {
        let path = rust_uri.to_file_path().ok()?;
        (self.roots.iter()).find_map(|root| mirrored_path(root, &path))
    }

    fn location(&mut self, location: Location) -> Location {
        match self.origin(&location.uri) {
            Some(Origin::Renk {
                uri,
                text,
                generated,
                ..
            }) => Location {
                uri: uri.clone(),
                range: rust_range_to_source_range(generated, text, location.range),
            },
            Some(Origin::File(uri)) => Location {
                uri: uri.clone(),
                ..location
            },
            None => location,
        }
    }

    fn range(&mut self, rust_uri: &Url, range: Range) -> Range {
        self.location(Location::new(rust_uri.clone(), range)).range
    }

    /// A diagnostic of generated Rust at its Renk positions, with a [`Self::dot_hint`].
    fn diagnostic(&mut self, rust_uri: &Url, diagnostic: Diagnostic) -> Diagnostic {
        let message = match self.dot_hint(rust_uri, &diagnostic) {
            Some(hint) => format!("{}\n{hint}", diagnostic.message),
            None => diagnostic.message.clone(),
        };
        let related_information = diagnostic.related_information.map(|related| {
            related
                .into_iter()
                .map(|mut information| {
                    information.location = self.location(information.location);
                    information
                })
                .collect()
        });
        Diagnostic {
            range: self.range(rust_uri, diagnostic.range),
            related_information,
            message,
            ..diagnostic
        }
    }

    /// For a resolution error on a Renk line, how renk read a dot that its range touches.
    fn dot_hint(&mut self, rust_uri: &Url, diagnostic: &Diagnostic) -> Option<String> {
        let Some(NumberOrString::String(code)) = &diagnostic.code else {
            return None;
        };
        if !RESOLUTION_ERRORS.contains(&code.as_str()) {
            return None;
        }
        let Some(Origin::Renk {
            text, generated, ..
        }) = self.origin(rust_uri)
        else {
            return None;
        };
        let Range { start, end } = diagnostic.range;
        let (line, false) = *generated.source_lines.get(start.line as usize)? else {
            return None;
        };
        let renk = text.lines().nth(line.checked_sub(1)?)?;
        let rust = generated.rust.lines().nth(start.line as usize)?;
        let column =
            |position: Position| script_column(renk, rust, char_column(rust, position.character));
        let last = if end.line == start.line {
            column(end)
        } else {
            renk.chars().count()
        };
        dot_hint(renk, rust, column(start)..last)
    }

    fn definition(
        &mut self,
        rust_uri: &Url,
        definition: GotoDefinitionResponse,
    ) -> GotoDefinitionResponse {
        match definition {
            GotoDefinitionResponse::Scalar(location) => {
                GotoDefinitionResponse::Scalar(self.location(location))
            }
            GotoDefinitionResponse::Array(locations) => GotoDefinitionResponse::Array(
                locations
                    .into_iter()
                    .map(|location| self.location(location))
                    .collect(),
            ),
            GotoDefinitionResponse::Link(links) => GotoDefinitionResponse::Link(
                links
                    .into_iter()
                    .map(|mut link| {
                        link.target_selection_range =
                            self.range(&link.target_uri, link.target_selection_range);
                        let target =
                            self.location(Location::new(link.target_uri, link.target_range));
                        link.target_uri = target.uri;
                        link.target_range = target.range;
                        link.origin_selection_range = link
                            .origin_selection_range
                            .map(|range| self.range(rust_uri, range));
                        link
                    })
                    .collect(),
            ),
        }
    }

    /// A hint in an opened generated Rust file at its document's position, or `None` on a line
    /// renk synthesized or when its edits do not map.
    fn inlay_hint(&mut self, rust_uri: &Url, hint: InlayHint) -> Option<InlayHint> {
        let Some(Origin::Renk {
            text, generated, ..
        }) = self.origin(rust_uri)
        else {
            return None;
        };
        if generated.source_lines.get(hint.position.line as usize)?.1 {
            return None;
        }
        let position = rust_position_to_source_position(generated, text, hint.position);
        let text_edits = hint
            .text_edits
            .map(|edits| {
                edits
                    .into_iter()
                    .map(|edit| checked_edit(generated, text, edit))
                    .collect::<Option<Vec<_>>>()
            })
            .map_or(Some(None), |edits| edits.map(Some))?;
        let label = match hint.label {
            InlayHintLabel::LabelParts(parts) => InlayHintLabel::LabelParts(
                parts
                    .into_iter()
                    .map(|mut part| {
                        part.location = part.location.map(|location| self.location(location));
                        part
                    })
                    .collect(),
            ),
            label => label,
        };
        Some(InlayHint {
            position,
            label,
            text_edits,
            ..hint
        })
    }

    /// Edits of rust-analyzer's file as edits of the editor's: in a Renk document, checked to
    /// replace the same text, or with `convert`, converted with [`renk_edits`] and checked to
    /// transpile to the edited Rust. `None` when an edit does not map or the Renk document does not
    /// transpile.
    fn text_edits(
        &mut self,
        rust_uri: &Url,
        edits: Vec<TextEdit>,
        convert: bool,
    ) -> Option<(Url, Vec<TextEdit>)> {
        match self.origin(rust_uri) {
            Some(Origin::Renk {
                uri,
                text,
                generated,
                script,
            }) => {
                let edits = if convert {
                    let renk = renk_edits(text, &generated.rust, &edits, *script)?;
                    // The converted text must give back the Rust that rust-analyzer's edits make.
                    let rust = transpile_document(uri, &edited(text, &renk), *script)
                        .ok()?
                        .rust;
                    same_rust(&rust, &edited(&generated.rust, &edits)).then_some(renk)?
                } else {
                    edits
                        .into_iter()
                        .map(|edit| checked_edit(generated, text, edit))
                        .collect::<Option<_>>()?
                };
                Some((uri.clone(), edits))
            }
            Some(Origin::File(uri)) => Some((uri.clone(), edits)),
            None => (self.renk_uri(rust_uri).is_none()).then(|| (self.uri(rust_uri), edits)),
        }
    }

    /// The editor's URI of a file rust-analyzer names that may not exist yet.
    fn uri(&mut self, rust_uri: &Url) -> Url {
        match self.origin(rust_uri) {
            Some(Origin::Renk { uri, .. } | Origin::File(uri)) => uri.clone(),
            None => self
                .mirrored(rust_uri)
                .and_then(|path| Url::from_file_path(path).ok())
                .unwrap_or_else(|| rust_uri.clone()),
        }
    }

    fn document_edit(
        &mut self,
        edit: TextDocumentEdit,
        convert: bool,
    ) -> std::result::Result<TextDocumentEdit, Url> {
        let edits = edit
            .edits
            .into_iter()
            .map(|edit| match edit {
                OneOf::Left(edit) => edit,
                OneOf::Right(annotated) => annotated.text_edit,
            })
            .collect();
        let mut text_document = edit.text_document;
        let (uri, edits) = (self.text_edits(&text_document.uri, edits, convert))
            .ok_or_else(|| text_document.uri.clone())?;
        text_document.uri = uri;
        Ok(TextDocumentEdit {
            text_document,
            edits: edits.into_iter().map(OneOf::Left).collect(),
        })
    }

    /// A file operation on rust-analyzer's files as one on the editor's: renaming a Renk module's
    /// generated Rust renames the module.
    fn resource_op(&mut self, op: ResourceOp) -> ResourceOp {
        match op {
            ResourceOp::Create(mut create) => {
                create.uri = self.uri(&create.uri);
                ResourceOp::Create(create)
            }
            ResourceOp::Rename(mut rename) => {
                let renk = matches!(self.origin(&rename.old_uri), Some(Origin::Renk { .. }));
                rename.old_uri = self.uri(&rename.old_uri);
                rename.new_uri = self.uri(&rename.new_uri);
                if renk && let Ok(path) = rename.new_uri.to_file_path() {
                    rename.new_uri =
                        Url::from_file_path(path.with_extension("rk")).unwrap_or(rename.new_uri);
                }
                ResourceOp::Rename(rename)
            }
            ResourceOp::Delete(mut delete) => {
                delete.uri = self.uri(&delete.uri);
                ResourceOp::Delete(delete)
            }
        }
    }

    /// rust-analyzer's rename edit as an edit of the editor's files, or a message naming the Rust
    /// text, the Renk file and the line of the first edit whose Renk text differs from that text.
    fn rename_edit(&mut self, edit: WorkspaceEdit) -> std::result::Result<WorkspaceEdit, String> {
        let document_edits = match &edit.document_changes {
            Some(DocumentChanges::Edits(edits)) => edits.iter().collect(),
            Some(DocumentChanges::Operations(operations)) => (operations.iter())
                .filter_map(|operation| match operation {
                    DocumentChangeOperation::Edit(edit) => Some(edit),
                    DocumentChangeOperation::Op(_) => None,
                })
                .collect(),
            None => Vec::new(),
        };
        let edits = (edit.changes.iter().flatten())
            .flat_map(|(uri, edits)| edits.iter().map(move |edit| (uri, edit)))
            .chain(document_edits.into_iter().flat_map(|document| {
                document.edits.iter().map(|edit| match edit {
                    OneOf::Left(edit) => (&document.text_document.uri, edit),
                    OneOf::Right(annotated) => (&document.text_document.uri, &annotated.text_edit),
                })
            }));
        for (rust_uri, edit) in edits {
            if let Some(Origin::Renk {
                uri,
                text,
                generated,
                ..
            }) = self.origin(rust_uri)
                && checked_edit(generated, text, edit.clone()).is_none()
            {
                let name = range_text(&generated.rust, edit.range);
                let path = uri.to_file_path().unwrap_or_else(|_| uri.path().into());
                let range = rust_range_to_source_range(generated, text, edit.range);
                let line = range.start.line + 1;
                return Err(format!(
                    "cannot rename `{name}` at {}:{line}. Rename it there by hand.",
                    path.display()
                ));
            }
        }
        // Every Renk edit passed `checked_edit`, so only a document that does not transpile fails.
        self.workspace_edit(edit, false).map_err(|rust_uri| {
            let uri = self.renk_uri(&rust_uri).unwrap_or(rust_uri);
            let path = uri.to_file_path().unwrap_or_else(|_| uri.path().into());
            format!(
                "cannot rename in {}, which does not transpile.",
                path.display()
            )
        })
    }

    /// A workspace edit of rust-analyzer's files as one of the editor's, or a file of
    /// rust-analyzer's with edits that do not map; `convert` as in [`Self::text_edits`].
    fn workspace_edit(
        &mut self,
        edit: WorkspaceEdit,
        convert: bool,
    ) -> std::result::Result<WorkspaceEdit, Url> {
        let changes = edit
            .changes
            .map(|changes| {
                changes
                    .into_iter()
                    .map(|(uri, edits)| self.text_edits(&uri, edits, convert).ok_or(uri))
                    .collect::<std::result::Result<HashMap<_, _>, _>>()
            })
            .transpose()?;
        let document_changes = match edit.document_changes {
            None => None,
            Some(DocumentChanges::Edits(edits)) => Some(DocumentChanges::Edits(
                edits
                    .into_iter()
                    .map(|edit| self.document_edit(edit, convert))
                    .collect::<std::result::Result<_, _>>()?,
            )),
            Some(DocumentChanges::Operations(operations)) => Some(DocumentChanges::Operations(
                operations
                    .into_iter()
                    .map(|operation| match operation {
                        DocumentChangeOperation::Edit(edit) => self
                            .document_edit(edit, convert)
                            .map(DocumentChangeOperation::Edit),
                        DocumentChangeOperation::Op(op) => {
                            Ok(DocumentChangeOperation::Op(self.resource_op(op)))
                        }
                    })
                    .collect::<std::result::Result<_, _>>()?,
            )),
        };
        Ok(WorkspaceEdit {
            changes,
            document_changes,
            change_annotations: edit.change_annotations,
        })
    }
}

/// Whether `edit` has no text edit and no file operation.
fn changes_nothing(edit: &WorkspaceEdit) -> bool {
    let document_changes = match &edit.document_changes {
        None => true,
        Some(DocumentChanges::Edits(edits)) => edits.iter().all(|edit| edit.edits.is_empty()),
        Some(DocumentChanges::Operations(operations)) => operations.iter().all(|operation| {
            matches!(operation, DocumentChangeOperation::Edit(edit) if edit.edits.is_empty())
        }),
    };
    document_changes
        && edit
            .changes
            .iter()
            .flat_map(HashMap::values)
            .all(Vec::is_empty)
}

/// The symbol of the item `node`. Its range ends with the last of the document's `lines` that the
/// source map of `output` gives the item's Rust.
#[allow(deprecated)]
fn symbol_from_node(
    node: &SourceMapNode,
    output: &TranspileOutput,
    lines: &[&str],
) -> Option<DocumentSymbol> {
    let kind = symbol_kind(&node.kind)?;
    let (name, offset) = symbol_name(node);
    let first_line = node.source_text.lines().next().unwrap_or_default();
    let line = node.source_line.saturating_sub(1) as u32;
    let start = node.source_column as u32;
    let name_start = start + utf16_len(&first_line[..offset]);
    let last_line = output
        .source_map
        .iter()
        .filter(|entry| {
            (node.generated_start_line..=node.generated_end_line).contains(&entry.generated_line)
        })
        .map(|entry| entry.source_line)
        .fold(node.source_line, usize::max)
        .saturating_sub(1);
    Some(DocumentSymbol {
        detail: Some(node.kind.clone()),
        kind,
        tags: None,
        deprecated: None,
        range: Range::new(
            Position::new(line, start),
            Position::new(
                last_line as u32,
                lines.get(last_line).map_or(0, |line| utf16_len(line)),
            ),
        ),
        selection_range: Range::new(
            Position::new(line, name_start),
            Position::new(line, name_start + utf16_len(&name)),
        ),
        name,
        children: Some(
            node.children
                .iter()
                .filter_map(|child| symbol_from_node(child, output, lines))
                .collect(),
        ),
    })
}

fn symbol_kind(kind: &str) -> Option<SymbolKind> {
    match kind {
        "struct" => Some(SymbolKind::STRUCT),
        "enum" => Some(SymbolKind::ENUM),
        "trait" => Some(SymbolKind::INTERFACE),
        "impl" => Some(SymbolKind::OBJECT),
        "module" => Some(SymbolKind::MODULE),
        "function" => Some(SymbolKind::FUNCTION),
        "member" | "field" => Some(SymbolKind::FIELD),
        _ => None,
    }
}

/// The name of the item `node` starts, and its byte offset in the node's first line: the head
/// of an `impl` without its `:`, the word after an item's keyword, or a member's first word after
/// its visibility.
fn symbol_name(node: &SourceMapNode) -> (String, usize) {
    let text = node.source_text.lines().next().unwrap_or_default();
    let keyword = match node.kind.as_str() {
        "impl" => {
            return (
                text.trim_end().trim_end_matches(':').trim_end().to_string(),
                0,
            );
        }
        "struct" | "enum" | "trait" => node.kind.as_str(),
        "module" => "mod",
        "function" => "fn",
        _ => "",
    };
    let keyword_end = text.match_indices(keyword).find_map(|(index, _)| {
        let end = index + keyword.len();
        (!keyword.is_empty()
            && !text[..index].ends_with(is_identifier_continue)
            && text[end..].starts_with(char::is_whitespace))
        .then_some(end)
    });
    let after = keyword_end.unwrap_or_else(|| {
        let rest = text.strip_prefix("pub").unwrap_or(text);
        let rest = rest
            .strip_prefix('(')
            .and_then(|group| group.split_once(')'))
            .map_or(rest, |(_, rest)| rest);
        if rest.starts_with(char::is_whitespace) {
            text.len() - rest.len()
        } else {
            0
        }
    });
    let rest = text[after..].trim_start();
    let offset = text.len() - rest.len();
    let name = rest
        .split(|character: char| !is_identifier_continue(character))
        .next()
        .unwrap_or_default();
    if name.is_empty() {
        (text.trim_end().to_string(), 0)
    } else {
        (name.to_string(), offset)
    }
}

/// The range of `text` from the 1-based character `column` of the 1-based `line` to its end.
fn line_range(text: &str, line: usize, column: usize) -> Range {
    let line_index = line.saturating_sub(1);
    let line_text = text.lines().nth(line_index).unwrap_or_default();
    Range {
        start: Position {
            line: line_index as u32,
            character: utf16_column(line_text, column.saturating_sub(1)),
        },
        end: Position {
            line: line_index as u32,
            character: utf16_len(line_text),
        },
    }
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "else", "enum", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "return", "self",
    "Self", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
];

const BUILTIN_TYPES: &[&str] = &[
    "bool", "char", "f32", "f64", "i8", "i16", "i32", "i64", "i128", "isize", "str", "u8", "u16",
    "u32", "u64", "u128", "usize",
];

#[derive(Debug, Clone, PartialEq, Eq)]
struct Word {
    text: String,
    range: Range,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Declaration {
    name: String,
    detail: String,
    kind: CompletionItemKind,
    range: Range,
}

fn hover_at_position(text: &str, position: Position) -> Option<Hover> {
    let word = word_at_position(text, position)?;
    let contents = if BUILTIN_TYPES.contains(&word.text.as_str()) {
        format!("builtin type `{}`", word.text)
    } else if KEYWORDS.contains(&word.text.as_str()) {
        format!("keyword `{}`", word.text)
    } else {
        declaration_at_position(text, &word)?.detail
    };

    Some(Hover {
        contents: HoverContents::Markup(MarkupContent {
            kind: MarkupKind::Markdown,
            value: contents,
        }),
        range: Some(word.range),
    })
}

fn definition_range_at_position(text: &str, position: Position) -> Option<Range> {
    let word = word_at_position(text, position)?;
    declaration_at_position(text, &word).map(|declaration| declaration.range)
}

fn completion_items(text: &str) -> Vec<CompletionItem> {
    let mut seen = BTreeSet::new();
    KEYWORDS
        .iter()
        .map(|keyword| CompletionItem {
            label: (*keyword).to_string(),
            kind: Some(CompletionItemKind::KEYWORD),
            ..CompletionItem::default()
        })
        .chain(BUILTIN_TYPES.iter().map(|builtin| CompletionItem {
            label: (*builtin).to_string(),
            kind: Some(CompletionItemKind::TYPE_PARAMETER),
            detail: Some("builtin type".to_string()),
            ..CompletionItem::default()
        }))
        .chain(
            collect_declarations(text)
                .into_iter()
                .map(|declaration| CompletionItem {
                    label: declaration.name,
                    kind: Some(declaration.kind),
                    detail: Some(declaration.detail),
                    ..CompletionItem::default()
                }),
        )
        .filter(|item| seen.insert(item.label.clone()))
        .collect()
}

fn declaration_at_position(text: &str, word: &Word) -> Option<Declaration> {
    let declarations = collect_declarations(text);
    declarations
        .iter()
        .rev()
        .find(|declaration| {
            declaration.name == word.text && declaration.range.start.line <= word.range.start.line
        })
        .or_else(|| {
            declarations
                .iter()
                .find(|declaration| declaration.name == word.text)
        })
        .cloned()
}

fn collect_declarations(text: &str) -> Vec<Declaration> {
    text.lines()
        .enumerate()
        .flat_map(|(index, raw)| {
            declarations_from_line(index as u32, raw)
                .into_iter()
                .map(move |mut declaration| {
                    declaration.range = utf16_range(raw, declaration.range);
                    declaration
                })
        })
        .collect()
}

fn declarations_from_line(line: u32, raw: &str) -> Vec<Declaration> {
    let text = raw.trim_start();
    if text.is_empty() || text.starts_with("//") {
        return Vec::new();
    }

    let indent = raw.len() - text.len();
    let mut declarations = Vec::new();
    if let Some(declaration) =
        item_declaration(line, indent, text, "struct", CompletionItemKind::STRUCT)
            .or_else(|| item_declaration(line, indent, text, "enum", CompletionItemKind::ENUM))
            .or_else(|| {
                item_declaration(line, indent, text, "trait", CompletionItemKind::INTERFACE)
            })
            .or_else(|| item_declaration(line, indent, text, "mod", CompletionItemKind::MODULE))
            .or_else(|| item_declaration(line, indent, text, "fn", CompletionItemKind::FUNCTION))
    {
        if declaration.kind == CompletionItemKind::FUNCTION {
            declarations.extend(parameter_declarations(line, indent, text));
        }
        declarations.push(declaration);
        return declarations;
    }

    if let Some(declaration) = let_declaration(line, indent, text) {
        declarations.push(declaration);
    } else if let Some(declaration) = field_declaration(line, indent, text) {
        declarations.push(declaration);
    }
    declarations
}

fn item_declaration(
    line: u32,
    indent: usize,
    text: &str,
    keyword: &str,
    kind: CompletionItemKind,
) -> Option<Declaration> {
    let keyword_start = keyword_position(text, keyword)?;
    let name_start = text[keyword_start + keyword.len()..]
        .find(is_identifier_start)
        .map(|offset| keyword_start + keyword.len() + offset)?;
    let name_end = identifier_end(text, name_start);
    let name = text[name_start..name_end].to_string();
    Some(Declaration {
        name,
        detail: trim_assignment_tail(text).to_string(),
        kind,
        range: range_for_span(line, indent + name_start, indent + name_end),
    })
}

fn parameter_declarations(line: u32, indent: usize, text: &str) -> Vec<Declaration> {
    let Some(fn_start) = keyword_position(text, "fn") else {
        return Vec::new();
    };
    let Some(open) = text[fn_start..].find('(').map(|offset| fn_start + offset) else {
        return Vec::new();
    };
    let Some(close) = matching_delimiter(text, open, '(', ')') else {
        return Vec::new();
    };

    split_top_level_spans(&text[open + 1..close], ',')
        .into_iter()
        .filter_map(|(start, end)| {
            let parameter = &text[open + 1 + start..open + 1 + end];
            let trimmed_start = parameter.len() - parameter.trim_start().len();
            let trimmed = parameter.trim();
            let colon = trimmed.find(':')?;
            let name = trimmed[..colon].trim();
            if name == "self" || name == "&self" || name == "&mut self" {
                return None;
            }
            let name_start = open + 1 + start + trimmed_start + trimmed[..colon].find(name)?;
            let name_end = name_start + name.len();
            Some(Declaration {
                name: name.to_string(),
                detail: format!("parameter {name}: {}", trimmed[colon + 1..].trim()),
                kind: CompletionItemKind::VARIABLE,
                range: range_for_span(line, indent + name_start, indent + name_end),
            })
        })
        .collect()
}

fn let_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let rest = text.strip_prefix("let ")?;
    let rest_offset = text.len() - rest.len();
    let rest = rest.strip_prefix("mut ").unwrap_or(rest);
    let rest_offset = if rest.as_ptr() == text[rest_offset..].as_ptr() {
        rest_offset
    } else {
        rest_offset + "mut ".len()
    };
    let name_start = rest.find(is_identifier_start)?;
    let name_end = identifier_end(rest, name_start);
    let name = &rest[name_start..name_end];
    let after_name = &rest[name_end..];
    let detail = after_name
        .trim_start()
        .strip_prefix(':')
        .and_then(|after_colon| after_colon.split('=').next())
        .map(str::trim)
        .filter(|annotation| !annotation.is_empty())
        .map(|annotation| format!("let {name}: {annotation}"))
        .unwrap_or_else(|| format!("let {name}"));

    Some(Declaration {
        name: name.to_string(),
        detail,
        kind: CompletionItemKind::VARIABLE,
        range: range_for_span(
            line,
            indent + rest_offset + name_start,
            indent + rest_offset + name_end,
        ),
    })
}

fn field_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let (text, offset) = text
        .strip_prefix("pub ")
        .map(|text| (text, "pub ".len()))
        .unwrap_or((text, 0));
    let colon = text.find(':')?;
    if text[..colon].contains([' ', '(', ')', '=']) {
        return None;
    }
    let name = text[..colon].trim();
    if name.is_empty() || !name.chars().next().is_some_and(is_identifier_start) {
        return None;
    }
    Some(Declaration {
        name: name.to_string(),
        detail: format!("field {name}: {}", text[colon + 1..].trim()),
        kind: CompletionItemKind::FIELD,
        range: range_for_span(line, indent + offset, indent + offset + name.len()),
    })
}

fn word_at_position(text: &str, position: Position) -> Option<Word> {
    let raw = text.lines().nth(position.line as usize)?;
    let cursor = byte_column(raw, position.character);
    let start = raw[..cursor]
        .char_indices()
        .rev()
        .take_while(|(_, character)| is_identifier_continue(*character))
        .last()
        .map_or(cursor, |(start, _)| start);
    let end = identifier_end(raw, cursor);
    if start == end {
        return None;
    }

    Some(Word {
        text: raw[start..end].to_string(),
        range: utf16_range(raw, range_for_span(position.line, start, end)),
    })
}

fn keyword_position(text: &str, keyword: &str) -> Option<usize> {
    text.match_indices(keyword)
        .find(|(index, _)| {
            let before = text[..*index]
                .chars()
                .next_back()
                .is_none_or(|character| !is_identifier_continue(character));
            let after = text[index + keyword.len()..]
                .chars()
                .next()
                .is_none_or(|character| !is_identifier_continue(character));
            before && after
        })
        .map(|(index, _)| index)
}

fn identifier_end(text: &str, start: usize) -> usize {
    text[start..]
        .char_indices()
        .find(|(_, character)| !is_identifier_continue(*character))
        .map_or(text.len(), |(offset, _)| start + offset)
}

fn is_identifier_start(character: char) -> bool {
    character == '_' || unicode_ident::is_xid_start(character)
}

fn is_identifier_continue(character: char) -> bool {
    unicode_ident::is_xid_continue(character)
}

fn trim_assignment_tail(text: &str) -> &str {
    text.split(" =")
        .next()
        .unwrap_or(text)
        .trim_end_matches('=')
        .trim()
}

fn matching_delimiter(text: &str, open: usize, open_char: char, close_char: char) -> Option<usize> {
    let mut depth = 0usize;
    for (index, character) in text[open..].char_indices() {
        if character == open_char {
            depth += 1;
        } else if character == close_char {
            depth = depth.saturating_sub(1);
            if depth == 0 {
                return Some(open + index);
            }
        }
    }
    None
}

fn split_top_level_spans(text: &str, delimiter: char) -> Vec<(usize, usize)> {
    let mut spans = Vec::new();
    let mut start = 0usize;
    let mut parens = 0usize;
    let mut brackets = 0usize;
    let mut braces = 0usize;
    for (index, character) in text.char_indices() {
        match character {
            '(' => parens += 1,
            ')' => parens = parens.saturating_sub(1),
            '[' => brackets += 1,
            ']' => brackets = brackets.saturating_sub(1),
            '{' => braces += 1,
            '}' => braces = braces.saturating_sub(1),
            character if character == delimiter && parens == 0 && brackets == 0 && braces == 0 => {
                spans.push((start, index));
                start = index + character.len_utf8();
            }
            _ => {}
        }
    }
    spans.push((start, text.len()));
    spans
}

/// Byte offset in `line` of an LSP column, which counts UTF-16 code units.
fn byte_column(line: &str, character: u32) -> usize {
    let mut units = 0u32;
    for (offset, character_at) in line.char_indices() {
        if units >= character {
            return offset;
        }
        units += character_at.len_utf16() as u32;
    }
    line.len()
}

fn utf16_len(line: &str) -> u32 {
    line.encode_utf16().count() as u32
}

/// Converts a single-line range from byte columns in `line` to UTF-16 columns.
fn utf16_range(line: &str, range: Range) -> Range {
    let column = |byte: u32| utf16_len(&line[..(byte as usize).min(line.len())]);
    range_for_span(
        range.start.line,
        column(range.start.character) as usize,
        column(range.end.character) as usize,
    )
}

fn range_for_span(line: u32, start: usize, end: usize) -> Range {
    Range {
        start: Position {
            line,
            character: start as u32,
        },
        end: Position {
            line,
            character: end as u32,
        },
    }
}

#[tokio::main]
async fn main() {
    let (input, server_input) = tokio::io::duplex(1 << 16);
    tokio::spawn(forward_editor_messages(tokio::io::stdin(), input));
    let (service, socket) = LspService::new(Backend::new);
    Server::new(server_input, tokio::io::stdout(), socket)
        .serve(service)
        .await;
}

