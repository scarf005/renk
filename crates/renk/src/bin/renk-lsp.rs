const GENERATED_HEADER: &str = "// @generated by renk; do not edit.\n";

#[derive(Debug, Clone)]
struct Backend {
    client: Client,
    documents: Arc<RwLock<HashMap<Url, String>>>,
    /// rust-analyzer's latest diagnostics of each Renk document, at the document's positions.
    rust_diagnostics: Arc<RwLock<HashMap<Url, Vec<Diagnostic>>>>,
    rust_analyzer: Arc<RwLock<Option<Arc<RustAnalyzerClient>>>>,
    /// The rust-analyzer each open document's generated Rust is open in, and that Rust's URI.
    /// A script's own rust-analyzer lives only here, so it exits when its entry goes.
    opened: Arc<RwLock<HashMap<Url, (Arc<RustAnalyzerClient>, Url)>>>,
    /// Serializes document syncs: tower-lsp runs notifications concurrently, which would start
    /// two rust-analyzers for one script or reorder its `didOpen` and `didChange`.
    sync: Arc<Mutex<()>>,
    initialize_params: Arc<RwLock<Option<InitializeParams>>>,
}

#[tower_lsp::async_trait]
impl LanguageServer for Backend {
    async fn initialize(&self, params: InitializeParams) -> Result<InitializeResult> {
        self.initialize_params.write().await.replace(params);

        Ok(InitializeResult {
            capabilities: ServerCapabilities {
                text_document_sync: Some(TextDocumentSyncCapability::Options(
                    TextDocumentSyncOptions {
                        open_close: Some(true),
                        change: Some(TextDocumentSyncKind::FULL),
                        save: Some(TextDocumentSyncSaveOptions::Supported(true)),
                        ..TextDocumentSyncOptions::default()
                    },
                )),
                references_provider: Some(OneOf::Left(true)),
                rename_provider: Some(OneOf::Right(RenameOptions {
                    prepare_provider: Some(true),
                    work_done_progress_options: Default::default(),
                })),
                code_action_provider: Some(CodeActionProviderCapability::Simple(true)),
                inlay_hint_provider: Some(OneOf::Left(true)),
                document_symbol_provider: Some(OneOf::Left(true)),
                hover_provider: Some(tower_lsp::lsp_types::HoverProviderCapability::Simple(true)),
                definition_provider: Some(OneOf::Left(true)),
                completion_provider: Some(CompletionOptions {
                    resolve_provider: Some(false),
                    trigger_characters: None,
                    all_commit_characters: None,
                    work_done_progress_options: Default::default(),
                    completion_item: None,
                }),
                ..ServerCapabilities::default()
            },
            server_info: None,
        })
    }

    async fn initialized(&self, params: InitializedParams) {
        if let Some(rust_analyzer) = self.rust_analyzer.read().await.as_ref() {
            rust_analyzer.notify("initialized", params).await;
        }
        self.client
            .log_message(MessageType::INFO, "renk language server initialized")
            .await;
    }

    async fn shutdown(&self) -> Result<()> {
        if let Some(rust_analyzer) = self.rust_analyzer.read().await.as_ref() {
            let _ = rust_analyzer.request("shutdown", ()).await;
        }
        Ok(())
    }

    async fn did_open(&self, params: DidOpenTextDocumentParams) {
        let _sync = self.sync.lock().await;
        let uri = params.text_document.uri;
        let version = params.text_document.version;
        let text = params.text_document.text;
        self.documents
            .write()
            .await
            .insert(uri.clone(), text.clone());
        self.sync_rust_document(&uri, &text, version).await;
        self.publish_diagnostics(uri, text).await;
    }

    async fn did_change(&self, params: DidChangeTextDocumentParams) {
        let _sync = self.sync.lock().await;
        let uri = params.text_document.uri;
        let version = params.text_document.version;
        let text = params
            .content_changes
            .into_iter()
            .last()
            .map(|change| change.text)
            .unwrap_or_default();
        self.documents
            .write()
            .await
            .insert(uri.clone(), text.clone());
        self.sync_rust_document(&uri, &text, version).await;
        self.publish_diagnostics(uri, text).await;
    }

    async fn did_save(&self, params: DidSaveTextDocumentParams) {
        if let Some((rust_analyzer, uri)) = self.rust_analyzer(&params.text_document.uri).await {
            rust_analyzer
                .notify(
                    "textDocument/didSave",
                    DidSaveTextDocumentParams {
                        text_document: TextDocumentIdentifier { uri },
                        text: None,
                    },
                )
                .await;
        }
    }

    async fn did_close(&self, params: DidCloseTextDocumentParams) {
        let _sync = self.sync.lock().await;
        self.documents
            .write()
            .await
            .remove(&params.text_document.uri);
        self.rust_diagnostics
            .write()
            .await
            .remove(&params.text_document.uri);
        self.close_rust_document(&params.text_document.uri).await;
        self.client
            .publish_diagnostics(params.text_document.uri, Vec::new(), None)
            .await;
    }

    async fn document_symbol(
        &self,
        params: DocumentSymbolParams,
    ) -> Result<Option<DocumentSymbolResponse>> {
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&params.text_document.uri) else {
            return Ok(None);
        };
        let uri = &params.text_document.uri;
        if source_syntax(uri) != SourceSyntax::Renk {
            return Ok(Some(DocumentSymbolResponse::Nested(Vec::new())));
        }
        let body = if is_script(uri, text) {
            script_body(text)
        } else {
            Ok(text.clone())
        };
        let Ok(output) = body.and_then(|body| transpile(&body)) else {
            return Ok(None);
        };

        Ok(Some(DocumentSymbolResponse::Nested(
            output
                .source_tree
                .iter()
                .filter_map(symbol_from_node)
                .collect(),
        )))
    }

    async fn hover(&self, params: HoverParams) -> Result<Option<Hover>> {
        let uri = params
            .text_document_position_params
            .text_document
            .uri
            .clone();
        let position = params.text_document_position_params.position;
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&uri) else {
            return Ok(None);
        };

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri, generated)) = self.rust_document(&uri, text).await
            && let Some(position) = source_position_to_rust_position(&generated, text, position)
        {
            rust_params.text_document_position_params.text_document.uri = rust_uri;
            rust_params.text_document_position_params.position = position;
            if let Some(mut hover) = rust_analyzer
                .request("textDocument/hover", rust_params)
                .await
                .and_then(|value| serde_json::from_value::<Hover>(value).ok())
            {
                hover.range = hover
                    .range
                    .map(|range| rust_range_to_source_range(&generated, text, range));
                return Ok(Some(hover));
            }
        }

        Ok(hover_at_position(text, position))
    }

    async fn goto_definition(
        &self,
        params: GotoDefinitionParams,
    ) -> Result<Option<GotoDefinitionResponse>> {
        let uri = params
            .text_document_position_params
            .text_document
            .uri
            .clone();
        let position = params.text_document_position_params.position;
        // Not borrowed from `documents`, whose lock mapping the definition takes again.
        let Some(text) = self.documents.read().await.get(&uri).cloned() else {
            return Ok(None);
        };
        let text = &text;

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri, generated)) = self.rust_document(&uri, text).await
            && let Some(position) = source_position_to_rust_position(&generated, text, position)
        {
            rust_params.text_document_position_params.text_document.uri = rust_uri.clone();
            rust_params.text_document_position_params.position = position;
            if let Some(definition) = rust_analyzer
                .request("textDocument/definition", rust_params)
                .await
                .and_then(|value| serde_json::from_value(value).ok())
            {
                return Ok(Some(self.origins().await.definition(&rust_uri, definition)));
            }
        }

        let Some(range) = definition_range_at_position(text, position) else {
            return Ok(None);
        };

        Ok(Some(GotoDefinitionResponse::Scalar(Location {
            uri,
            range,
        })))
    }

    async fn completion(&self, params: CompletionParams) -> Result<Option<CompletionResponse>> {
        let uri = params.text_document_position.text_document.uri.clone();
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&uri) else {
            return Ok(None);
        };

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri, generated)) = self.rust_document(&uri, text).await
            && let Some(position) = source_position_to_rust_position(
                &generated,
                text,
                params.text_document_position.position,
            )
        {
            rust_params.text_document_position.text_document.uri = rust_uri;
            rust_params.text_document_position.position = position;
            if let Some(completion) = rust_analyzer
                .request("textDocument/completion", rust_params)
                .await
                .and_then(|value| serde_json::from_value(value).ok())
            {
                return Ok(Some(completion));
            }
        }

        Ok(Some(CompletionResponse::Array(completion_items(text))))
    }

    async fn references(&self, mut params: ReferenceParams) -> Result<Option<Vec<Location>>> {
        let position = &mut params.text_document_position;
        let Some((rust_analyzer, rust_uri, ..)) = self
            .rust_position(&position.text_document.uri, &mut position.position)
            .await
        else {
            return Ok(None);
        };
        position.text_document.uri = rust_uri;
        let locations = rust_analyzer
            .request("textDocument/references", params)
            .await
            .and_then(|value| serde_json::from_value::<Vec<Location>>(value).ok());
        let mut origins = self.origins().await;
        Ok(locations.map(|locations| {
            locations
                .into_iter()
                .map(|location| origins.location(location))
                .collect()
        }))
    }

    async fn prepare_rename(
        &self,
        mut params: TextDocumentPositionParams,
    ) -> Result<Option<PrepareRenameResponse>> {
        let Some((rust_analyzer, rust_uri, text, generated)) = self
            .rust_position(&params.text_document.uri, &mut params.position)
            .await
        else {
            return Ok(None);
        };
        params.text_document.uri = rust_uri;
        let response = rust_analyzer
            .request("textDocument/prepareRename", params)
            .await
            .and_then(|value| serde_json::from_value(value).ok());
        let range = |range| {
            checked_edit(&generated, &text, TextEdit::new(range, String::new())).map(|e| e.range)
        };
        Ok(response.and_then(|response| match response {
            PrepareRenameResponse::Range(rust) => range(rust).map(PrepareRenameResponse::Range),
            PrepareRenameResponse::RangeWithPlaceholder {
                range: rust,
                placeholder,
            } => range(rust)
                .map(|range| PrepareRenameResponse::RangeWithPlaceholder { range, placeholder }),
            default => Some(default),
        }))
    }

    async fn rename(&self, mut params: RenameParams) -> Result<Option<WorkspaceEdit>> {
        let position = &mut params.text_document_position;
        let Some((rust_analyzer, rust_uri, ..)) = self
            .rust_position(&position.text_document.uri, &mut position.position)
            .await
        else {
            return Ok(None);
        };
        position.text_document.uri = rust_uri;
        let Some(edit) = rust_analyzer
            .request("textDocument/rename", params)
            .await
            .and_then(|value| serde_json::from_value(value).ok())
        else {
            return Ok(None);
        };
        self.origins()
            .await
            .workspace_edit(edit, false)
            .map(Some)
            .ok_or_else(|| Error {
                // The protocol's RequestFailed.
                code: ErrorCode::from(-32803),
                message: "the rename changes Renk text that differs from its generated Rust".into(),
                data: None,
            })
    }

    async fn code_action(
        &self,
        mut params: CodeActionParams,
    ) -> Result<Option<CodeActionResponse>> {
        let uri = params.text_document.uri.clone();
        let Some(text) = self.documents.read().await.get(&uri).cloned() else {
            return Ok(None);
        };
        let Some((rust_analyzer, rust_uri, generated)) = self.rust_document(&uri, &text).await
        else {
            return Ok(None);
        };
        let to_rust = |range: Range| {
            Some(Range::new(
                source_position_to_rust_position(&generated, &text, range.start)?,
                source_position_to_rust_position(&generated, &text, range.end)?,
            ))
        };
        let Some(range) = to_rust(params.range) else {
            return Ok(None);
        };
        params.text_document.uri = rust_uri;
        params.range = range;
        params.context.diagnostics.retain_mut(|diagnostic| {
            to_rust(diagnostic.range)
                .map(|range| diagnostic.range = range)
                .is_some()
        });
        let Some(actions) = rust_analyzer
            .request("textDocument/codeAction", params)
            .await
            .and_then(|value| serde_json::from_value::<CodeActionResponse>(value).ok())
        else {
            return Ok(None);
        };
        let mut origins = self.origins().await;
        Ok(Some(
            actions
                .into_iter()
                .filter_map(|action| match action {
                    CodeActionOrCommand::CodeAction(action) => {
                        let edit = origins.workspace_edit(action.edit.clone()?, true)?;
                        let diagnostics = action.diagnostics.map(|diagnostics| {
                            diagnostics
                                .into_iter()
                                .map(|diagnostic| Diagnostic {
                                    range: rust_range_to_source_range(
                                        &generated,
                                        &text,
                                        diagnostic.range,
                                    ),
                                    ..diagnostic
                                })
                                .collect()
                        });
                        Some(CodeActionOrCommand::CodeAction(CodeAction {
                            edit: Some(edit),
                            diagnostics,
                            command: None,
                            ..action
                        }))
                    }
                    CodeActionOrCommand::Command(_) => None,
                })
                .collect(),
        ))
    }

    async fn inlay_hint(&self, mut params: InlayHintParams) -> Result<Option<Vec<InlayHint>>> {
        let uri = params.text_document.uri.clone();
        let Some(text) = self.documents.read().await.get(&uri).cloned() else {
            return Ok(None);
        };
        let Some((rust_analyzer, rust_uri, generated)) = self.rust_document(&uri, &text).await
        else {
            return Ok(None);
        };
        let Some(range) = rust_lines(&generated, params.range) else {
            return Ok(Some(Vec::new()));
        };
        params.text_document.uri = rust_uri.clone();
        params.range = range;
        let hints = rust_analyzer
            .request("textDocument/inlayHint", params)
            .await
            .and_then(|value| serde_json::from_value::<Vec<InlayHint>>(value).ok());
        let mut origins = self.origins().await;
        Ok(hints.map(|hints| {
            hints
                .into_iter()
                .filter_map(|hint| origins.inlay_hint(&rust_uri, hint))
                .collect()
        }))
    }
}

impl Backend {
    /// The rust-analyzer a document's generated Rust is open in, and that Rust's URI.
    async fn rust_analyzer(&self, uri: &Url) -> Option<(Arc<RustAnalyzerClient>, Url)> {
        self.opened.read().await.get(uri).cloned()
    }

    /// The rust-analyzer a document with `text` is open in, its generated Rust's URI, and that Rust.
    async fn rust_document(
        &self,
        uri: &Url,
        text: &str,
    ) -> Option<(Arc<RustAnalyzerClient>, Url, Generated)> {
        let (rust_analyzer, rust_uri) = self.rust_analyzer(uri).await?;
        Some((rust_analyzer, rust_uri, generated(uri, text).ok()?))
    }

    /// Like [`Self::rust_document`] for an open document, with its text, and `position` in it
    /// moved to the generated Rust.
    async fn rust_position(
        &self,
        uri: &Url,
        position: &mut Position,
    ) -> Option<(Arc<RustAnalyzerClient>, Url, String, Generated)> {
        let text = self.documents.read().await.get(uri).cloned()?;
        let (rust_analyzer, rust_uri, generated) = self.rust_document(uri, &text).await?;
        *position = source_position_to_rust_position(&generated, &text, *position)?;
        Some((rust_analyzer, rust_uri, text, generated))
    }

    /// What maps rust-analyzer's files back to the editor's now.
    async fn origins(&self) -> Origins {
        let params = self.initialize_params.read().await;
        let roots = params
            .as_ref()
            .and_then(source_root_uri)
            .and_then(|source_root_uri| {
                let rust_root = target_renk_root_uri(&source_root_uri)?
                    .to_file_path()
                    .ok()?;
                Some((source_root_uri.to_file_path().ok()?, rust_root))
            });
        Origins {
            documents: self.documents.read().await.clone(),
            sources: self
                .opened
                .read()
                .await
                .iter()
                .map(|(uri, (_, rust_uri))| (rust_uri.clone(), uri.clone()))
                .collect(),
            roots,
            cache: HashMap::new(),
        }
    }

    /// Takes rust-analyzer's diagnostics of a Renk document's generated Rust as the document's.
    async fn rust_analyzer_notification(&self, notification: serde_json::Value) {
        if notification["method"] != "textDocument/publishDiagnostics" {
            return;
        }
        let Ok(params) =
            serde_json::from_value::<PublishDiagnosticsParams>(notification["params"].clone())
        else {
            return;
        };
        let mut origins = self.origins().await;
        let Some(Origin::Renk { uri, text, .. }) = origins.origin(&params.uri) else {
            return;
        };
        let (uri, text) = (uri.clone(), text.clone());
        let diagnostics = params
            .diagnostics
            .into_iter()
            .map(|diagnostic| origins.diagnostic(&params.uri, diagnostic))
            .collect();
        self.rust_diagnostics
            .write()
            .await
            .insert(uri.clone(), diagnostics);
        self.publish_diagnostics(uri, text).await;
    }

    /// Starts the rust-analyzer for a document: one over the generated workspace mirror, or for a
    /// script, one linked to its generated cargo-script file, which rust-analyzer resolves the
    /// frontmatter dependencies of.
    async fn ensure_rust_analyzer(&self, uri: &Url, text: &str) -> Option<Arc<RustAnalyzerClient>> {
        let script = is_script(uri, text);
        let workspace = self.rust_analyzer.read().await.as_ref().cloned();
        let existing = if script {
            self.rust_analyzer(uri)
                .await
                .map(|(rust_analyzer, _)| rust_analyzer)
                .filter(|rust_analyzer| {
                    !workspace
                        .as_ref()
                        .is_some_and(|workspace| Arc::ptr_eq(workspace, rust_analyzer))
                })
        } else {
            workspace
        };
        if existing.is_some() {
            return existing;
        }

        let mut params = self.initialize_params.read().await.as_ref().cloned()?;
        if script {
            let rust_path = script_rust_path(uri)?;
            let rust_root_uri = Url::from_directory_path(rust_path.parent()?).ok()?;
            params = rust_initialize_params(params, &rust_root_uri);
            params.initialization_options = Some(script_initialization_options(
                params.initialization_options.take(),
                &rust_path,
            ));
        } else {
            let source_root_uri = source_root_uri(&params)?;
            let rust_root_uri = target_renk_root_uri(&source_root_uri)?;
            let source_root = source_root_uri.to_file_path().ok()?;
            mirror_sources(
                &source_root,
                &rust_root_uri.to_file_path().ok()?,
                &source_root,
            );
            params = rust_initialize_params(params, &rust_root_uri);
        }
        let (notifications, mut received) = mpsc::unbounded_channel();
        match RustAnalyzerClient::spawn(params, notifications).await {
            Ok(rust_analyzer) => {
                let backend = self.clone();
                tokio::spawn(async move {
                    while let Some(notification) = received.recv().await {
                        backend.rust_analyzer_notification(notification).await;
                    }
                });
                let rust_analyzer = Arc::new(rust_analyzer);
                rust_analyzer
                    .notify("initialized", InitializedParams {})
                    .await;
                if !script {
                    self.rust_analyzer
                        .write()
                        .await
                        .replace(rust_analyzer.clone());
                }
                Some(rust_analyzer)
            }
            Err(error) => {
                self.client
                    .log_message(
                        MessageType::WARNING,
                        format!("rust-analyzer proxy disabled: {error}"),
                    )
                    .await;
                None
            }
        }
    }

    /// Sends a document's generated Rust to its rust-analyzer: a change when that rust-analyzer
    /// already has it open, otherwise an open, after closing it where it was open before (the
    /// document may have become a script or stopped being one).
    async fn sync_rust_document(&self, uri: &Url, text: &str, version: i32) {
        let Some(rust_uri) = self.rust_uri_for_renk_uri(uri, text).await else {
            return;
        };
        let Ok(rust) = generated(uri, text).map(|generated| generated.rust) else {
            return;
        };
        let Ok(path) = rust_uri.to_file_path() else {
            return;
        };
        if is_script(uri, text) {
            // Its frontmatter comes first, so no header; nothing else writes to renk's cache.
            write_if_changed(&path, &rust);
        } else {
            self.copy_generated_cargo_manifests(uri).await;
            write_generated_rust_file(&path, &rust);
        }
        let Some(rust_analyzer) = self.ensure_rust_analyzer(uri, text).await else {
            return;
        };

        let previous = self
            .opened
            .write()
            .await
            .insert(uri.clone(), (rust_analyzer.clone(), rust_uri.clone()));
        match previous {
            Some((previous, previous_uri))
                if Arc::ptr_eq(&previous, &rust_analyzer) && previous_uri == rust_uri =>
            {
                rust_analyzer
                    .notify(
                        "textDocument/didChange",
                        DidChangeTextDocumentParams {
                            text_document: VersionedTextDocumentIdentifier {
                                uri: rust_uri,
                                version,
                            },
                            content_changes: vec![TextDocumentContentChangeEvent {
                                range: None,
                                range_length: None,
                                text: rust,
                            }],
                        },
                    )
                    .await;
            }
            previous => {
                if let Some((previous, previous_uri)) = previous {
                    close_in(&previous, previous_uri).await;
                }
                rust_analyzer
                    .notify(
                        "textDocument/didOpen",
                        DidOpenTextDocumentParams {
                            text_document: TextDocumentItem {
                                uri: rust_uri,
                                language_id: "rust".to_string(),
                                version,
                                text: rust,
                            },
                        },
                    )
                    .await;
            }
        }
    }

    async fn close_rust_document(&self, uri: &Url) {
        if let Some((rust_analyzer, rust_uri)) = self.opened.write().await.remove(uri) {
            close_in(&rust_analyzer, rust_uri).await;
        }
    }

    async fn rust_uri_for_renk_uri(&self, uri: &Url, text: &str) -> Option<Url> {
        if is_script(uri, text) {
            return Url::from_file_path(script_rust_path(uri)?).ok();
        }
        let params = self.initialize_params.read().await;
        let source_root_uri = source_root_uri(params.as_ref()?)?;
        let rust_root_uri = target_renk_root_uri(&source_root_uri)?;
        rust_uri_for_renk_uri(uri, &source_root_uri, &rust_root_uri)
    }

    async fn copy_generated_cargo_manifests(&self, uri: &Url) {
        let params = self.initialize_params.read().await;
        let Some(source_root_uri) = params.as_ref().and_then(source_root_uri) else {
            return;
        };
        let Some(rust_root_uri) = target_renk_root_uri(&source_root_uri) else {
            return;
        };
        copy_generated_cargo_manifests(uri, &source_root_uri, &rust_root_uri);
    }

    /// Publishes a document's Renk syntax diagnostics with rust-analyzer's latest ones.
    async fn publish_diagnostics(&self, uri: Url, text: String) {
        let mut diagnostics = match generated(&uri, &text) {
            Ok(_) => Vec::new(),
            Err(error) => vec![Diagnostic {
                range: line_range(&text, error.line),
                severity: Some(DiagnosticSeverity::ERROR),
                source: Some("renk".to_string()),
                message: error.to_string(),
                ..Diagnostic::default()
            }],
        };
        diagnostics.extend(
            self.rust_diagnostics
                .read()
                .await
                .get(&uri)
                .into_iter()
                .flatten()
                .cloned(),
        );
        self.client
            .publish_diagnostics(uri, diagnostics, None)
            .await;
    }
}

#[derive(Debug)]
struct RustAnalyzerClient {
    sender: mpsc::UnboundedSender<serde_json::Value>,
    pending: Arc<Mutex<HashMap<u64, oneshot::Sender<serde_json::Value>>>>,
    next_id: AtomicU64,
    _child: Arc<Mutex<tokio::process::Child>>,
}

impl RustAnalyzerClient {
    /// Starts rust-analyzer, which sends its notifications to `notifications`.
    async fn spawn(
        params: InitializeParams,
        notifications: mpsc::UnboundedSender<serde_json::Value>,
    ) -> std::io::Result<Self> {
        let mut child = Command::new("rust-analyzer")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .kill_on_drop(true)
            .spawn()?;
        let stdin = child.stdin.take().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::BrokenPipe,
                "rust-analyzer stdin unavailable",
            )
        })?;
        let stdout = child.stdout.take().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::BrokenPipe,
                "rust-analyzer stdout unavailable",
            )
        })?;
        let (sender, mut receiver) = mpsc::unbounded_channel::<serde_json::Value>();
        let pending = Arc::new(Mutex::new(HashMap::new()));
        let reader_pending = pending.clone();
        let replies = sender.clone();
        let config = params
            .initialization_options
            .clone()
            .unwrap_or(serde_json::Value::Null);

        tokio::spawn(async move {
            let mut stdin = stdin;
            while let Some(message) = receiver.recv().await {
                if write_lsp_message(&mut stdin, &message).await.is_err() {
                    break;
                }
            }
        });
        tokio::spawn(async move {
            read_rust_analyzer_messages(stdout, reader_pending, replies, notifications, config)
                .await;
        });

        let client = Self {
            sender,
            pending,
            next_id: AtomicU64::new(1),
            _child: Arc::new(Mutex::new(child)),
        };
        client.request("initialize", params).await.ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::TimedOut,
                "rust-analyzer did not initialize",
            )
        })?;
        Ok(client)
    }

    async fn notify<T: serde::Serialize>(&self, method: &str, params: T) {
        let Ok(params) = serde_json::to_value(params) else {
            return;
        };
        let _ = self.sender.send(serde_json::json!({
            "jsonrpc": "2.0",
            "method": method,
            "params": params,
        }));
    }

    async fn request<T: serde::Serialize>(
        &self,
        method: &str,
        params: T,
    ) -> Option<serde_json::Value> {
        let id = self.next_id.fetch_add(1, Ordering::Relaxed);
        let params = serde_json::to_value(params).ok()?;
        let (sender, receiver) = oneshot::channel();
        self.pending.lock().await.insert(id, sender);
        if self
            .sender
            .send(serde_json::json!({
                "jsonrpc": "2.0",
                "id": id,
                "method": method,
                "params": params,
            }))
            .is_err()
        {
            self.pending.lock().await.remove(&id);
            return None;
        }
        tokio::time::timeout(std::time::Duration::from_secs(5), receiver)
            .await
            .ok()
            .and_then(std::result::Result::ok)
    }
}

async fn close_in(rust_analyzer: &RustAnalyzerClient, rust_uri: Url) {
    rust_analyzer
        .notify(
            "textDocument/didClose",
            DidCloseTextDocumentParams {
                text_document: tower_lsp::lsp_types::TextDocumentIdentifier { uri: rust_uri },
            },
        )
        .await;
}

/// The rust-analyzer settings of a script's rust-analyzer: the editor's, linked to the script's
/// generated cargo-script file.
fn script_initialization_options(
    options: Option<serde_json::Value>,
    rust_path: &Path,
) -> serde_json::Value {
    let mut options = options
        .filter(serde_json::Value::is_object)
        .unwrap_or_else(|| serde_json::json!({}));
    options["linkedProjects"] = serde_json::json!([rust_path]);
    options
}

/// Hands rust-analyzer's responses to their requests. Its own requests get an answer here: their
/// ids are rust-analyzer's, which would otherwise take the place of a response to a request of
/// ours with the same id. `workspace/configuration` gets `config`, the settings it started with,
/// once per item; the rest get an empty answer. Its notifications go to `notifications`.
async fn read_rust_analyzer_messages(
    stdout: impl tokio::io::AsyncRead + Unpin,
    pending: Arc<Mutex<HashMap<u64, oneshot::Sender<serde_json::Value>>>>,
    replies: mpsc::UnboundedSender<serde_json::Value>,
    notifications: mpsc::UnboundedSender<serde_json::Value>,
    config: serde_json::Value,
) {
    let mut reader = BufReader::new(stdout);
    loop {
        let Some(message) = read_lsp_message(&mut reader).await else {
            break;
        };
        if message.get("method").is_some() {
            if let Some(id) = message.get("id") {
                let result = if message["method"] == "workspace/configuration" {
                    let items = message["params"]["items"].as_array().map_or(0, Vec::len);
                    serde_json::Value::Array(vec![config.clone(); items])
                } else {
                    serde_json::Value::Null
                };
                let _ = replies.send(serde_json::json!({
                    "jsonrpc": "2.0",
                    "id": id,
                    "result": result,
                }));
            } else {
                let _ = notifications.send(message);
            }
            continue;
        }
        let Some(id) = message.get("id").and_then(serde_json::Value::as_u64) else {
            continue;
        };
        let response = message
            .get("result")
            .cloned()
            .unwrap_or(serde_json::Value::Null);
        if let Some(sender) = pending.lock().await.remove(&id) {
            let _ = sender.send(response);
        }
    }
}

async fn read_lsp_message<R: tokio::io::AsyncBufRead + Unpin>(
    reader: &mut R,
) -> Option<serde_json::Value> {
    let mut content_length = None;
    loop {
        let mut line = String::new();
        if reader.read_line(&mut line).await.ok()? == 0 {
            return None;
        }
        let line = line.trim_end_matches(['\r', '\n']);
        if line.is_empty() {
            break;
        }
        if let Some(value) = line.strip_prefix("Content-Length: ") {
            content_length = value.parse::<usize>().ok();
        }
    }

    let mut body = vec![0; content_length?];
    reader.read_exact(&mut body).await.ok()?;
    serde_json::from_slice(&body).ok()
}

async fn write_lsp_message<W: tokio::io::AsyncWrite + Unpin>(
    writer: &mut W,
    message: &serde_json::Value,
) -> std::io::Result<()> {
    let body = serde_json::to_vec(message)?;
    writer
        .write_all(format!("Content-Length: {}\r\n\r\n", body.len()).as_bytes())
        .await?;
    writer.write_all(&body).await?;
    writer.flush().await
}

fn source_root_uri(params: &InitializeParams) -> Option<Url> {
    params.root_uri.clone().or_else(|| {
        params
            .workspace_folders
            .as_ref()
            .and_then(|folders| folders.first())
            .map(|folder| folder.uri.clone())
    })
}

fn target_renk_root_uri(source_root_uri: &Url) -> Option<Url> {
    let mut path = source_root_uri.to_file_path().ok()?;
    path.push("target");
    path.push("renk");
    Url::from_directory_path(path).ok()
}

fn rust_initialize_params(mut params: InitializeParams, rust_root_uri: &Url) -> InitializeParams {
    // Keep rust-analyzer on the default UTF-16 columns that renk-lsp also uses.
    if let Some(general) = params.capabilities.general.as_mut() {
        general.position_encodings = None;
    }
    // Code actions and inlay hints come whole, with plain text edits that renk-lsp maps.
    let text_document = params
        .capabilities
        .text_document
        .get_or_insert_with(Default::default);
    text_document.code_action = Some(CodeActionClientCapabilities {
        code_action_literal_support: Some(CodeActionLiteralSupport {
            code_action_kind: CodeActionKindLiteralSupport {
                value_set: [
                    CodeActionKind::EMPTY,
                    CodeActionKind::QUICKFIX,
                    CodeActionKind::REFACTOR,
                    CodeActionKind::REFACTOR_EXTRACT,
                    CodeActionKind::REFACTOR_INLINE,
                    CodeActionKind::REFACTOR_REWRITE,
                    CodeActionKind::SOURCE,
                    CodeActionKind::SOURCE_ORGANIZE_IMPORTS,
                ]
                .map(|kind| kind.as_str().to_string())
                .to_vec(),
            },
        }),
        ..CodeActionClientCapabilities::default()
    });
    if let Some(inlay_hint) = text_document.inlay_hint.as_mut() {
        inlay_hint.resolve_support = None;
    }
    if let Some(experimental) = params
        .capabilities
        .experimental
        .as_mut()
        .and_then(serde_json::Value::as_object_mut)
    {
        experimental.remove("snippetTextEdit");
    }
    params.root_uri = Some(rust_root_uri.clone());
    params.workspace_folders = Some(vec![WorkspaceFolder {
        uri: rust_root_uri.clone(),
        name: "renk-generated".to_string(),
    }]);
    params
}

fn rust_uri_for_renk_uri(uri: &Url, source_root_uri: &Url, rust_root_uri: &Url) -> Option<Url> {
    let source_path = uri.to_file_path().ok()?;
    let source_root = source_root_uri.to_file_path().ok()?;
    let rust_root = rust_root_uri.to_file_path().ok()?;
    let relative = source_path
        .strip_prefix(&source_root)
        .ok()
        .map(Path::to_path_buf)
        .or_else(|| source_path.file_name().map(PathBuf::from))?;
    let mut path = rust_root.join(relative);
    path.set_extension("rs");
    Url::from_file_path(path).ok()
}

fn copy_generated_cargo_manifests(uri: &Url, source_root_uri: &Url, rust_root_uri: &Url) {
    let Ok(source_path) = uri.to_file_path() else {
        return;
    };
    let Ok(source_root) = source_root_uri.to_file_path() else {
        return;
    };
    let Ok(rust_root) = rust_root_uri.to_file_path() else {
        return;
    };
    let Some(mut current) = source_path.parent() else {
        return;
    };

    while current.starts_with(&source_root) {
        let manifest = current.join("Cargo.toml");
        if manifest.is_file()
            && let Ok(relative) = manifest.strip_prefix(&source_root)
        {
            copy_manifest_if_changed(&manifest, &rust_root.join(relative), current == source_root);
        }
        if current == source_root {
            break;
        }
        let Some(parent) = current.parent() else {
            break;
        };
        current = parent;
    }
}

fn copy_manifest_if_changed(source: &Path, destination: &Path, is_root_manifest: bool) {
    let Ok(mut content) = fs::read_to_string(source) else {
        return;
    };
    if is_root_manifest && !manifest_has_section(&content, "package") {
        content = "[workspace]\n\n[package]\nname = \"renk-generated\"\nversion = \"0.0.0\"\nedition = \"2024\"\n".to_string();
    } else if is_root_manifest && !manifest_has_section(&content, "workspace") {
        content = format!("[workspace]\n\n{content}");
    }
    write_if_changed(destination, &content);
}

fn manifest_has_section(content: &str, section: &str) -> bool {
    content
        .lines()
        .any(|line| line.trim() == format!("[{section}]"))
}

/// Writes a module's generated Rust, which starts with renk's header, unless a file without the
/// header, which renk did not write, is there.
fn write_generated_rust_file(path: &Path, rust: &str) {
    if fs::read_to_string(path).is_ok_and(|existing| !existing.starts_with(GENERATED_HEADER)) {
        return;
    }
    write_if_changed(path, rust);
}

fn write_if_changed(path: &Path, content: &str) {
    if fs::read_to_string(path).is_ok_and(|existing| existing == content) {
        return;
    }
    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(path, content);
}

/// Mirrors the crates under `dir` of `source_root` at `rust_root` for `cargo check`: each Renk
/// module's generated Rust, each hand-written Rust file, and each Cargo manifest. It skips
/// `target/`, hidden directories, and Rust that renk generated next to its Renk module.
fn mirror_sources(source_root: &Path, rust_root: &Path, dir: &Path) {
    for path in fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path())
    {
        let Ok(relative) = path.strip_prefix(source_root) else {
            continue;
        };
        let mirrored = rust_root.join(relative);
        let name = path
            .file_name()
            .and_then(|name| name.to_str())
            .unwrap_or_default();
        if path.is_dir() {
            if name != "target" && !name.starts_with('.') {
                mirror_sources(source_root, rust_root, &path);
            }
            continue;
        }
        match path.extension().and_then(|extension| extension.to_str()) {
            Some("rk") => {
                if let Ok(uri) = Url::from_file_path(&path)
                    && let Ok(text) = fs::read_to_string(&path)
                    && !is_script(&uri, &text)
                    && let Ok(generated) = generated(&uri, &text)
                {
                    write_generated_rust_file(&mirrored.with_extension("rs"), &generated.rust);
                }
            }
            Some("rs") => {
                if let Ok(text) = fs::read_to_string(&path)
                    && !(text.starts_with(GENERATED_HEADER) && path.with_extension("rk").is_file())
                {
                    write_if_changed(&mirrored, &text);
                }
            }
            _ if name == "Cargo.toml" => {
                copy_manifest_if_changed(&path, &mirrored, dir == source_root);
            }
            _ => {}
        }
    }
}

fn source_syntax(uri: &Url) -> SourceSyntax {
    match uri
        .to_file_path()
        .ok()
        .and_then(|path| {
            path.extension()
                .and_then(|extension| extension.to_str())
                .map(str::to_string)
        })
        .as_deref()
    {
        Some("rs") => SourceSyntax::Rust,
        _ => SourceSyntax::Renk,
    }
}

/// A document's generated Rust, as written to the file rust-analyzer and cargo read, and, for
/// each 1-based Rust line, the document line it came from and whether renk synthesized it, like
/// a closing brace or a module's generated header.
struct Generated {
    rust: String,
    source_lines: Vec<(usize, bool)>,
}

fn generated(uri: &Url, text: &str) -> std::result::Result<Generated, TranspileError> {
    if is_script(uri, text) {
        let package = script_rust_path(uri)
            .map_or_else(|| "script".to_string(), |path| script_package(&path));
        let script = script_rust(text, SourceSyntax::Renk, &package)?;
        return Ok(Generated {
            rust: script.rust,
            source_lines: script.source_lines,
        });
    }
    let (rust, source_lines) = if source_syntax(uri) == SourceSyntax::Rust {
        let lines = (1..=text.lines().count())
            .map(|line| (line, false))
            .collect();
        (text.to_string(), lines)
    } else {
        let output = transpile(text)?;
        let lines = output.line_origins();
        (output.rust, lines)
    };
    Ok(Generated {
        rust: format!("{GENERATED_HEADER}{rust}"),
        source_lines: std::iter::once((1, true)).chain(source_lines).collect(),
    })
}

/// Whether a renk document runs with `renk script`: it starts with a `#!` line or frontmatter, or
/// no Cargo package around it could build it as a module.
fn is_script(uri: &Url, text: &str) -> bool {
    let headed = script_parts(text).map_or(true, |parts| parts.body_start > 0);
    let packaged = uri.to_file_path().is_ok_and(|path| {
        path.ancestors()
            .skip(1)
            .any(|dir| dir.join("Cargo.toml").is_file())
    });
    source_syntax(uri) == SourceSyntax::Renk && (headed || !packaged)
}

/// The generated cargo-script file rust-analyzer reads for a script, apart from the one
/// `renk script` builds so unsaved edits never reach a build.
fn script_rust_path(uri: &Url) -> Option<PathBuf> {
    let path = uri.to_file_path().ok()?;
    let path = fs::canonicalize(&path).unwrap_or(path);
    Some(script_cache_path(&cache_root()?.join("lsp"), &path))
}

/// The character index of a UTF-16 column of `line`.
fn char_column(line: &str, character: u32) -> usize {
    let mut units = 0;
    line.chars()
        .take_while(|c| {
            units += c.len_utf16() as u32;
            units <= character
        })
        .count()
}

/// The UTF-16 column of a character index of `line`.
fn utf16_column(line: &str, column: usize) -> u32 {
    line.chars()
        .take(column)
        .map(|c| c.len_utf16() as u32)
        .sum()
}

fn source_position_to_rust_position(
    generated: &Generated,
    text: &str,
    position: Position,
) -> Option<Position> {
    let line = position.line as usize + 1;
    let rust_line = generated
        .source_lines
        .iter()
        .position(|&(source, synthesized)| source == line && !synthesized)?;
    let source = text.lines().nth(position.line as usize).unwrap_or_default();
    let rust = generated.rust.lines().nth(rust_line).unwrap_or_default();
    let column = script_column(rust, source, char_column(source, position.character));
    Some(Position {
        line: rust_line as u32,
        character: utf16_column(rust, column),
    })
}

fn rust_range_to_source_range(generated: &Generated, text: &str, range: Range) -> Range {
    Range {
        start: rust_position_to_source_position(generated, text, range.start),
        end: rust_position_to_source_position(generated, text, range.end),
    }
}

fn rust_position_to_source_position(
    generated: &Generated,
    text: &str,
    position: Position,
) -> Position {
    let Some(&(line, synthesized)) = generated.source_lines.get(position.line as usize) else {
        return position;
    };
    let source = text.lines().nth(line.saturating_sub(1)).unwrap_or_default();
    let rust = generated
        .rust
        .lines()
        .nth(position.line as usize)
        .unwrap_or_default();
    let column = if synthesized {
        source.chars().count()
    } else {
        script_column(source, rust, char_column(rust, position.character))
    };
    Position {
        line: line.saturating_sub(1) as u32,
        character: utf16_column(source, column),
    }
}

/// The whole Rust lines generated from the document lines `range` spans.
fn rust_lines(generated: &Generated, range: Range) -> Option<Range> {
    let source = range.start.line as usize + 1..=range.end.line as usize + 1;
    let mut lines = generated
        .source_lines
        .iter()
        .enumerate()
        .filter(|(_, (line, _))| source.contains(line))
        .map(|(rust_line, _)| rust_line as u32);
    let first = lines.next()?;
    let last = lines.next_back().unwrap_or(first);
    Some(Range::new(
        Position::new(first, 0),
        Position::new(last + 1, 0),
    ))
}

/// The byte offset of `position` in `text`.
fn offset(text: &str, position: Position) -> usize {
    let mut lines = text.split_inclusive('\n');
    let before = lines
        .by_ref()
        .take(position.line as usize)
        .map(str::len)
        .sum::<usize>();
    before
        + lines
            .next()
            .map_or(0, |line| byte_column(line, position.character))
}

fn range_text(text: &str, range: Range) -> &str {
    let start = offset(text, range.start);
    &text[start..offset(text, range.end).max(start)]
}

/// An edit of a document's generated Rust as the same edit of the document, when the document
/// has the text the edit replaces where it maps to.
fn checked_edit(generated: &Generated, text: &str, edit: TextEdit) -> Option<TextEdit> {
    let range = rust_range_to_source_range(generated, text, edit.range);
    (range_text(text, range) == range_text(&generated.rust, edit.range))
        .then_some(TextEdit::new(range, edit.new_text))
}

/// Renk edits of `source` that make the change `edits` make to its generated Rust `rust`, or
/// `None` when some of it falls where `source` differs from `rust` converted back to Renk.
///
/// Both versions of the Rust convert to Renk, as [`rust_to_renk`] or for a script [`script_renk`]
/// does, and the line hunks between those conversions apply to the lines of `source` that the old
/// conversion's lines match: a hunk applies only when the lines it replaces match consecutive
/// lines of `source`, or when it inserts next to a matching line.
fn renk_edits(source: &str, rust: &str, edits: &[TextEdit], script: bool) -> Option<Vec<TextEdit>> {
    let mut edited = rust.to_string();
    let mut edits = edits.to_vec();
    edits.sort_by_key(|edit| std::cmp::Reverse(offset(rust, edit.range.start)));
    for edit in edits {
        let start = offset(rust, edit.range.start);
        edited.replace_range(
            start..offset(rust, edit.range.end).max(start),
            &edit.new_text,
        );
    }
    let to_renk = |rust: &str| match script {
        true => script_renk(source, rust),
        false => rust_to_renk(rust).ok(),
    };
    let before = to_renk(rust)?;
    let after = to_renk(&edited)?;
    let before = before.lines().collect::<Vec<_>>();
    let after = after.lines().collect::<Vec<_>>();
    let source = source.lines().collect::<Vec<_>>();

    let mut matching = vec![None; before.len()];
    for op in capture_diff_slices(Algorithm::Myers, &before, &source) {
        if let DiffOp::Equal {
            old_index,
            new_index,
            len,
        } = op
        {
            for offset in 0..len {
                matching[old_index + offset] = Some(new_index + offset);
            }
        }
    }
    capture_diff_slices(Algorithm::Myers, &before, &after)
        .iter()
        .filter(|op| op.tag() != DiffTag::Equal)
        .map(|op| {
            let (_, old, new) = op.as_tag_tuple();
            let lines = if old.is_empty() {
                let after_previous = old.start.checked_sub(1).and_then(|line| matching[line]);
                match after_previous {
                    Some(line) => line + 1..line + 1,
                    None => matching
                        .get(old.start)
                        .copied()
                        .flatten()
                        .map(|line| line..line)?,
                }
            } else {
                let start = matching[old.start]?;
                old.clone()
                    .zip(start..)
                    .all(|(line, source)| matching[line] == Some(source))
                    .then_some(start..start + old.len())?
            };
            Some(TextEdit::new(
                Range::new(
                    Position::new(lines.start as u32, 0),
                    Position::new(lines.end as u32, 0),
                ),
                after[new].iter().map(|line| format!("{line}\n")).collect(),
            ))
        })
        .collect()
}

/// A file of the editor that rust-analyzer's file is the generated Rust or the mirror copy of.
enum Origin {
    Renk {
        uri: Url,
        text: String,
        generated: Generated,
        script: bool,
    },
    File(Url),
}

/// Maps rust-analyzer's files, locations, and edits back to the editor's.
struct Origins {
    documents: HashMap<Url, String>,
    /// The open document each opened generated Rust URI is of.
    sources: HashMap<Url, Url>,
    /// The workspace root and its mirror.
    roots: Option<(PathBuf, PathBuf)>,
    cache: HashMap<Url, Option<Origin>>,
}

impl Origins {
    fn origin(&mut self, rust_uri: &Url) -> Option<&Origin> {
        if !self.cache.contains_key(rust_uri) {
            let origin = self.find_origin(rust_uri);
            self.cache.insert(rust_uri.clone(), origin);
        }
        self.cache[rust_uri].as_ref()
    }

    /// The open document of an opened generated Rust file, or in the mirror, the Renk module on
    /// disk, read from disk unless it is open, or the hand-written file a copy is of.
    fn find_origin(&self, rust_uri: &Url) -> Option<Origin> {
        let uri = match self.sources.get(rust_uri) {
            Some(uri) => uri.clone(),
            None => {
                let path = self.mirrored(rust_uri)?;
                let renk = path.with_extension("rk");
                if !renk.is_file() {
                    return path
                        .is_file()
                        .then(|| Url::from_file_path(path).ok().map(Origin::File))?;
                }
                Url::from_file_path(renk).ok()?
            }
        };
        let text = match self.documents.get(&uri) {
            Some(text) => text.clone(),
            None => fs::read_to_string(uri.to_file_path().ok()?).ok()?,
        };
        Some(Origin::Renk {
            generated: generated(&uri, &text).ok()?,
            script: is_script(&uri, &text),
            uri,
            text,
        })
    }

    /// The workspace path that a path in the mirror stands for.
    fn mirrored(&self, rust_uri: &Url) -> Option<PathBuf> {
        let (source_root, rust_root) = self.roots.as_ref()?;
        let path = rust_uri.to_file_path().ok()?;
        Some(source_root.join(path.strip_prefix(rust_root).ok()?))
    }

    fn location(&mut self, location: Location) -> Location {
        match self.origin(&location.uri) {
            Some(Origin::Renk {
                uri,
                text,
                generated,
                ..
            }) => Location {
                uri: uri.clone(),
                range: rust_range_to_source_range(generated, text, location.range),
            },
            Some(Origin::File(uri)) => Location {
                uri: uri.clone(),
                ..location
            },
            None => location,
        }
    }

    fn range(&mut self, rust_uri: &Url, range: Range) -> Range {
        self.location(Location::new(rust_uri.clone(), range)).range
    }

    /// A diagnostic of generated Rust at its Renk positions, with a [`Self::dot_hint`].
    fn diagnostic(&mut self, rust_uri: &Url, diagnostic: Diagnostic) -> Diagnostic {
        let message = match self.dot_hint(rust_uri, &diagnostic) {
            Some(hint) => format!("{}\n{hint}", diagnostic.message),
            None => diagnostic.message.clone(),
        };
        let related_information = diagnostic.related_information.map(|related| {
            related
                .into_iter()
                .map(|mut information| {
                    information.location = self.location(information.location);
                    information
                })
                .collect()
        });
        Diagnostic {
            range: self.range(rust_uri, diagnostic.range),
            related_information,
            message,
            ..diagnostic
        }
    }

    /// For a resolution error on a Renk line, how renk read a dot that its range touches.
    fn dot_hint(&mut self, rust_uri: &Url, diagnostic: &Diagnostic) -> Option<String> {
        let Some(NumberOrString::String(code)) = &diagnostic.code else {
            return None;
        };
        if !RESOLUTION_ERRORS.contains(&code.as_str()) {
            return None;
        }
        let Some(Origin::Renk {
            text, generated, ..
        }) = self.origin(rust_uri)
        else {
            return None;
        };
        let Range { start, end } = diagnostic.range;
        let (line, false) = *generated.source_lines.get(start.line as usize)? else {
            return None;
        };
        let renk = text.lines().nth(line.checked_sub(1)?)?;
        let rust = generated.rust.lines().nth(start.line as usize)?;
        let column =
            |position: Position| script_column(renk, rust, char_column(rust, position.character));
        let last = if end.line == start.line {
            column(end)
        } else {
            renk.chars().count()
        };
        dot_hint(renk, rust, column(start)..last)
    }

    fn definition(
        &mut self,
        rust_uri: &Url,
        definition: GotoDefinitionResponse,
    ) -> GotoDefinitionResponse {
        match definition {
            GotoDefinitionResponse::Scalar(location) => {
                GotoDefinitionResponse::Scalar(self.location(location))
            }
            GotoDefinitionResponse::Array(locations) => GotoDefinitionResponse::Array(
                locations
                    .into_iter()
                    .map(|location| self.location(location))
                    .collect(),
            ),
            GotoDefinitionResponse::Link(links) => GotoDefinitionResponse::Link(
                links
                    .into_iter()
                    .map(|mut link| {
                        link.target_selection_range =
                            self.range(&link.target_uri, link.target_selection_range);
                        let target =
                            self.location(Location::new(link.target_uri, link.target_range));
                        link.target_uri = target.uri;
                        link.target_range = target.range;
                        link.origin_selection_range = link
                            .origin_selection_range
                            .map(|range| self.range(rust_uri, range));
                        link
                    })
                    .collect(),
            ),
        }
    }

    /// A hint in an opened generated Rust file at its document's position, or `None` on a line
    /// renk synthesized or when its edits do not map.
    fn inlay_hint(&mut self, rust_uri: &Url, hint: InlayHint) -> Option<InlayHint> {
        let Some(Origin::Renk {
            text, generated, ..
        }) = self.origin(rust_uri)
        else {
            return None;
        };
        if generated.source_lines.get(hint.position.line as usize)?.1 {
            return None;
        }
        let position = rust_position_to_source_position(generated, text, hint.position);
        let text_edits = hint
            .text_edits
            .map(|edits| {
                edits
                    .into_iter()
                    .map(|edit| checked_edit(generated, text, edit))
                    .collect::<Option<Vec<_>>>()
            })
            .map_or(Some(None), |edits| edits.map(Some))?;
        let label = match hint.label {
            InlayHintLabel::LabelParts(parts) => InlayHintLabel::LabelParts(
                parts
                    .into_iter()
                    .map(|mut part| {
                        part.location = part.location.map(|location| self.location(location));
                        part
                    })
                    .collect(),
            ),
            label => label,
        };
        Some(InlayHint {
            position,
            label,
            text_edits,
            ..hint
        })
    }

    /// Edits of rust-analyzer's file as edits of the editor's: in a Renk document, checked to
    /// replace the same text, or with `convert`, converted with [`renk_edits`]. `None` when an
    /// edit does not map.
    fn text_edits(
        &mut self,
        rust_uri: &Url,
        edits: Vec<TextEdit>,
        convert: bool,
    ) -> Option<(Url, Vec<TextEdit>)> {
        match self.origin(rust_uri) {
            Some(Origin::Renk {
                uri,
                text,
                generated,
                script,
            }) => {
                let edits = if convert {
                    renk_edits(text, &generated.rust, &edits, *script)?
                } else {
                    edits
                        .into_iter()
                        .map(|edit| checked_edit(generated, text, edit))
                        .collect::<Option<_>>()?
                };
                Some((uri.clone(), edits))
            }
            Some(Origin::File(uri)) => Some((uri.clone(), edits)),
            None => Some((self.uri(rust_uri), edits)),
        }
    }

    /// The editor's URI of a file rust-analyzer names that may not exist yet.
    fn uri(&mut self, rust_uri: &Url) -> Url {
        match self.origin(rust_uri) {
            Some(Origin::Renk { uri, .. } | Origin::File(uri)) => uri.clone(),
            None => self
                .mirrored(rust_uri)
                .and_then(|path| Url::from_file_path(path).ok())
                .unwrap_or_else(|| rust_uri.clone()),
        }
    }

    fn document_edit(&mut self, edit: TextDocumentEdit, convert: bool) -> Option<TextDocumentEdit> {
        let edits = edit
            .edits
            .into_iter()
            .map(|edit| match edit {
                OneOf::Left(edit) => edit,
                OneOf::Right(annotated) => annotated.text_edit,
            })
            .collect();
        let (uri, edits) = self.text_edits(&edit.text_document.uri, edits, convert)?;
        let mut text_document = edit.text_document;
        text_document.uri = uri;
        Some(TextDocumentEdit {
            text_document,
            edits: edits.into_iter().map(OneOf::Left).collect(),
        })
    }

    /// A file operation on rust-analyzer's files as one on the editor's: renaming a Renk module's
    /// generated Rust renames the module.
    fn resource_op(&mut self, op: ResourceOp) -> ResourceOp {
        match op {
            ResourceOp::Create(mut create) => {
                create.uri = self.uri(&create.uri);
                ResourceOp::Create(create)
            }
            ResourceOp::Rename(mut rename) => {
                let renk = matches!(self.origin(&rename.old_uri), Some(Origin::Renk { .. }));
                rename.old_uri = self.uri(&rename.old_uri);
                rename.new_uri = self.uri(&rename.new_uri);
                if renk && let Ok(path) = rename.new_uri.to_file_path() {
                    rename.new_uri =
                        Url::from_file_path(path.with_extension("rk")).unwrap_or(rename.new_uri);
                }
                ResourceOp::Rename(rename)
            }
            ResourceOp::Delete(mut delete) => {
                delete.uri = self.uri(&delete.uri);
                ResourceOp::Delete(delete)
            }
        }
    }

    /// A workspace edit of rust-analyzer's files as one of the editor's, or `None` when any of
    /// its edits does not map; `convert` as in [`Self::text_edits`].
    fn workspace_edit(&mut self, edit: WorkspaceEdit, convert: bool) -> Option<WorkspaceEdit> {
        let changes = edit
            .changes
            .map(|changes| {
                changes
                    .into_iter()
                    .map(|(uri, edits)| self.text_edits(&uri, edits, convert))
                    .collect::<Option<HashMap<_, _>>>()
            })
            .map_or(Some(None), |changes| changes.map(Some))?;
        let document_changes = match edit.document_changes {
            None => None,
            Some(DocumentChanges::Edits(edits)) => Some(DocumentChanges::Edits(
                edits
                    .into_iter()
                    .map(|edit| self.document_edit(edit, convert))
                    .collect::<Option<_>>()?,
            )),
            Some(DocumentChanges::Operations(operations)) => Some(DocumentChanges::Operations(
                operations
                    .into_iter()
                    .map(|operation| match operation {
                        DocumentChangeOperation::Edit(edit) => self
                            .document_edit(edit, convert)
                            .map(DocumentChangeOperation::Edit),
                        DocumentChangeOperation::Op(op) => {
                            Some(DocumentChangeOperation::Op(self.resource_op(op)))
                        }
                    })
                    .collect::<Option<_>>()?,
            )),
        };
        Some(WorkspaceEdit {
            changes,
            document_changes,
            change_annotations: edit.change_annotations,
        })
    }
}

#[allow(deprecated)]
fn symbol_from_node(node: &SourceMapNode) -> Option<DocumentSymbol> {
    let kind = symbol_kind(&node.kind)?;
    Some(DocumentSymbol {
        name: symbol_name(node),
        detail: Some(node.kind.clone()),
        kind,
        tags: None,
        deprecated: None,
        range: node_range(node),
        selection_range: node_range(node),
        children: Some(node.children.iter().filter_map(symbol_from_node).collect()),
    })
}

fn symbol_kind(kind: &str) -> Option<SymbolKind> {
    match kind {
        "struct" => Some(SymbolKind::STRUCT),
        "enum" => Some(SymbolKind::ENUM),
        "trait" => Some(SymbolKind::INTERFACE),
        "impl" => Some(SymbolKind::OBJECT),
        "module" => Some(SymbolKind::MODULE),
        "function" => Some(SymbolKind::FUNCTION),
        "member" | "field" => Some(SymbolKind::FIELD),
        _ => None,
    }
}

fn symbol_name(node: &SourceMapNode) -> String {
    let text = node.source_text.trim();
    if let Some(name) = item_name(text, "struct")
        .or_else(|| item_name(text, "enum"))
        .or_else(|| item_name(text, "trait"))
        .or_else(|| item_name(text, "mod"))
        .or_else(|| item_name(text, "fn"))
    {
        name
    } else if let Some(rest) = text.strip_prefix("impl") {
        format!("impl{}", rest)
    } else {
        text.split([':', '=', '(', ' '])
            .next()
            .unwrap_or(text)
            .to_string()
    }
}

fn item_name(text: &str, keyword: &str) -> Option<String> {
    let index = text.find(keyword)? + keyword.len();
    let rest = text[index..].trim_start();
    let name = rest
        .split(|character: char| !is_identifier_continue(character))
        .find(|part| !part.is_empty())?;
    Some(name.to_string())
}

fn node_range(node: &SourceMapNode) -> Range {
    let line = node.source_line.saturating_sub(1) as u32;
    let first_line = node.source_text.lines().next().unwrap_or_default();
    Range {
        start: Position {
            line,
            character: node.source_column as u32,
        },
        end: Position {
            line,
            character: node.source_column as u32 + utf16_len(first_line),
        },
    }
}

fn line_range(text: &str, line: usize) -> Range {
    let line_index = line.saturating_sub(1);
    let length = text
        .lines()
        .nth(line_index)
        .map(utf16_len)
        .unwrap_or_default();
    Range {
        start: Position {
            line: line_index as u32,
            character: 0,
        },
        end: Position {
            line: line_index as u32,
            character: length,
        },
    }
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "else", "enum", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "return", "self",
    "Self", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
];

const BUILTIN_TYPES: &[&str] = &[
    "bool", "char", "f32", "f64", "i8", "i16", "i32", "i64", "i128", "isize", "str", "u8", "u16",
    "u32", "u64", "u128", "usize",
];

#[derive(Debug, Clone, PartialEq, Eq)]
struct Word {
    text: String,
    range: Range,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Declaration {
    name: String,
    detail: String,
    kind: CompletionItemKind,
    range: Range,
}

fn hover_at_position(text: &str, position: Position) -> Option<Hover> {
    let word = word_at_position(text, position)?;
    let contents = if BUILTIN_TYPES.contains(&word.text.as_str()) {
        format!("builtin type `{}`", word.text)
    } else if KEYWORDS.contains(&word.text.as_str()) {
        format!("keyword `{}`", word.text)
    } else {
        declaration_at_position(text, &word)?.detail
    };

    Some(Hover {
        contents: HoverContents::Markup(MarkupContent {
            kind: MarkupKind::Markdown,
            value: contents,
        }),
        range: Some(word.range),
    })
}

fn definition_range_at_position(text: &str, position: Position) -> Option<Range> {
    let word = word_at_position(text, position)?;
    declaration_at_position(text, &word).map(|declaration| declaration.range)
}

fn completion_items(text: &str) -> Vec<CompletionItem> {
    let mut seen = BTreeSet::new();
    KEYWORDS
        .iter()
        .map(|keyword| CompletionItem {
            label: (*keyword).to_string(),
            kind: Some(CompletionItemKind::KEYWORD),
            ..CompletionItem::default()
        })
        .chain(BUILTIN_TYPES.iter().map(|builtin| CompletionItem {
            label: (*builtin).to_string(),
            kind: Some(CompletionItemKind::TYPE_PARAMETER),
            detail: Some("builtin type".to_string()),
            ..CompletionItem::default()
        }))
        .chain(
            collect_declarations(text)
                .into_iter()
                .map(|declaration| CompletionItem {
                    label: declaration.name,
                    kind: Some(declaration.kind),
                    detail: Some(declaration.detail),
                    ..CompletionItem::default()
                }),
        )
        .filter(|item| seen.insert(item.label.clone()))
        .collect()
}

fn declaration_at_position(text: &str, word: &Word) -> Option<Declaration> {
    let declarations = collect_declarations(text);
    declarations
        .iter()
        .rev()
        .find(|declaration| {
            declaration.name == word.text && declaration.range.start.line <= word.range.start.line
        })
        .or_else(|| {
            declarations
                .iter()
                .find(|declaration| declaration.name == word.text)
        })
        .cloned()
}

fn collect_declarations(text: &str) -> Vec<Declaration> {
    text.lines()
        .enumerate()
        .flat_map(|(index, raw)| {
            declarations_from_line(index as u32, raw)
                .into_iter()
                .map(move |mut declaration| {
                    declaration.range = utf16_range(raw, declaration.range);
                    declaration
                })
        })
        .collect()
}

fn declarations_from_line(line: u32, raw: &str) -> Vec<Declaration> {
    let text = raw.trim_start();
    if text.is_empty() || text.starts_with("//") {
        return Vec::new();
    }

    let indent = raw.len() - text.len();
    let mut declarations = Vec::new();
    if let Some(declaration) =
        item_declaration(line, indent, text, "struct", CompletionItemKind::STRUCT)
            .or_else(|| item_declaration(line, indent, text, "enum", CompletionItemKind::ENUM))
            .or_else(|| {
                item_declaration(line, indent, text, "trait", CompletionItemKind::INTERFACE)
            })
            .or_else(|| item_declaration(line, indent, text, "mod", CompletionItemKind::MODULE))
            .or_else(|| item_declaration(line, indent, text, "fn", CompletionItemKind::FUNCTION))
    {
        if declaration.kind == CompletionItemKind::FUNCTION {
            declarations.extend(parameter_declarations(line, indent, text));
        }
        declarations.push(declaration);
        return declarations;
    }

    if let Some(declaration) = let_declaration(line, indent, text) {
        declarations.push(declaration);
    } else if let Some(declaration) = field_declaration(line, indent, text) {
        declarations.push(declaration);
    }
    declarations
}

fn item_declaration(
    line: u32,
    indent: usize,
    text: &str,
    keyword: &str,
    kind: CompletionItemKind,
) -> Option<Declaration> {
    let keyword_start = keyword_position(text, keyword)?;
    let name_start = text[keyword_start + keyword.len()..]
        .find(is_identifier_start)
        .map(|offset| keyword_start + keyword.len() + offset)?;
    let name_end = identifier_end(text, name_start);
    let name = text[name_start..name_end].to_string();
    Some(Declaration {
        name,
        detail: trim_assignment_tail(text).to_string(),
        kind,
        range: range_for_span(line, indent + name_start, indent + name_end),
    })
}

fn parameter_declarations(line: u32, indent: usize, text: &str) -> Vec<Declaration> {
    let Some(fn_start) = keyword_position(text, "fn") else {
        return Vec::new();
    };
    let Some(open) = text[fn_start..].find('(').map(|offset| fn_start + offset) else {
        return Vec::new();
    };
    let Some(close) = matching_delimiter(text, open, '(', ')') else {
        return Vec::new();
    };

    split_top_level_spans(&text[open + 1..close], ',')
        .into_iter()
        .filter_map(|(start, end)| {
            let parameter = &text[open + 1 + start..open + 1 + end];
            let trimmed_start = parameter.len() - parameter.trim_start().len();
            let trimmed = parameter.trim();
            let colon = trimmed.find(':')?;
            let name = trimmed[..colon].trim();
            if name == "self" || name == "&self" || name == "&mut self" {
                return None;
            }
            let name_start = open + 1 + start + trimmed_start + trimmed[..colon].find(name)?;
            let name_end = name_start + name.len();
            Some(Declaration {
                name: name.to_string(),
                detail: format!("parameter {name}: {}", trimmed[colon + 1..].trim()),
                kind: CompletionItemKind::VARIABLE,
                range: range_for_span(line, indent + name_start, indent + name_end),
            })
        })
        .collect()
}

fn let_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let rest = text.strip_prefix("let ")?;
    let rest_offset = text.len() - rest.len();
    let rest = rest.strip_prefix("mut ").unwrap_or(rest);
    let rest_offset = if rest.as_ptr() == text[rest_offset..].as_ptr() {
        rest_offset
    } else {
        rest_offset + "mut ".len()
    };
    let name_start = rest.find(is_identifier_start)?;
    let name_end = identifier_end(rest, name_start);
    let name = &rest[name_start..name_end];
    let after_name = &rest[name_end..];
    let detail = after_name
        .trim_start()
        .strip_prefix(':')
        .and_then(|after_colon| after_colon.split('=').next())
        .map(str::trim)
        .filter(|annotation| !annotation.is_empty())
        .map(|annotation| format!("let {name}: {annotation}"))
        .unwrap_or_else(|| format!("let {name}"));

    Some(Declaration {
        name: name.to_string(),
        detail,
        kind: CompletionItemKind::VARIABLE,
        range: range_for_span(
            line,
            indent + rest_offset + name_start,
            indent + rest_offset + name_end,
        ),
    })
}

fn field_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let (text, offset) = text
        .strip_prefix("pub ")
        .map(|text| (text, "pub ".len()))
        .unwrap_or((text, 0));
    let colon = text.find(':')?;
    if text[..colon].contains([' ', '(', ')', '=']) {
        return None;
    }
    let name = text[..colon].trim();
    if name.is_empty() || !name.chars().next().is_some_and(is_identifier_start) {
        return None;
    }
    Some(Declaration {
        name: name.to_string(),
        detail: format!("field {name}: {}", text[colon + 1..].trim()),
        kind: CompletionItemKind::FIELD,
        range: range_for_span(line, indent + offset, indent + offset + name.len()),
    })
}

fn word_at_position(text: &str, position: Position) -> Option<Word> {
    let raw = text.lines().nth(position.line as usize)?;
    let cursor = byte_column(raw, position.character);
    let start = raw[..cursor]
        .char_indices()
        .rev()
        .take_while(|(_, character)| is_identifier_continue(*character))
        .last()
        .map_or(cursor, |(start, _)| start);
    let end = identifier_end(raw, cursor);
    if start == end {
        return None;
    }

    Some(Word {
        text: raw[start..end].to_string(),
        range: utf16_range(raw, range_for_span(position.line, start, end)),
    })
}

fn keyword_position(text: &str, keyword: &str) -> Option<usize> {
    text.match_indices(keyword)
        .find(|(index, _)| {
            let before = text[..*index]
                .chars()
                .next_back()
                .is_none_or(|character| !is_identifier_continue(character));
            let after = text[index + keyword.len()..]
                .chars()
                .next()
                .is_none_or(|character| !is_identifier_continue(character));
            before && after
        })
        .map(|(index, _)| index)
}

fn identifier_end(text: &str, start: usize) -> usize {
    text[start..]
        .char_indices()
        .find(|(_, character)| !is_identifier_continue(*character))
        .map_or(text.len(), |(offset, _)| start + offset)
}

fn is_identifier_start(character: char) -> bool {
    character == '_' || unicode_ident::is_xid_start(character)
}

fn is_identifier_continue(character: char) -> bool {
    unicode_ident::is_xid_continue(character)
}

fn trim_assignment_tail(text: &str) -> &str {
    text.split(" =")
        .next()
        .unwrap_or(text)
        .trim_end_matches('=')
        .trim()
}

fn matching_delimiter(text: &str, open: usize, open_char: char, close_char: char) -> Option<usize> {
    let mut depth = 0usize;
    for (index, character) in text[open..].char_indices() {
        if character == open_char {
            depth += 1;
        } else if character == close_char {
            depth = depth.saturating_sub(1);
            if depth == 0 {
                return Some(open + index);
            }
        }
    }
    None
}

fn split_top_level_spans(text: &str, delimiter: char) -> Vec<(usize, usize)> {
    let mut spans = Vec::new();
    let mut start = 0usize;
    let mut parens = 0usize;
    let mut brackets = 0usize;
    let mut braces = 0usize;
    for (index, character) in text.char_indices() {
        match character {
            '(' => parens += 1,
            ')' => parens = parens.saturating_sub(1),
            '[' => brackets += 1,
            ']' => brackets = brackets.saturating_sub(1),
            '{' => braces += 1,
            '}' => braces = braces.saturating_sub(1),
            character if character == delimiter && parens == 0 && brackets == 0 && braces == 0 => {
                spans.push((start, index));
                start = index + character.len_utf8();
            }
            _ => {}
        }
    }
    spans.push((start, text.len()));
    spans
}

/// Byte offset in `line` of an LSP column, which counts UTF-16 code units.
fn byte_column(line: &str, character: u32) -> usize {
    let mut units = 0u32;
    for (offset, character_at) in line.char_indices() {
        if units >= character {
            return offset;
        }
        units += character_at.len_utf16() as u32;
    }
    line.len()
}

fn utf16_len(line: &str) -> u32 {
    line.encode_utf16().count() as u32
}

/// Converts a single-line range from byte columns in `line` to UTF-16 columns.
fn utf16_range(line: &str, range: Range) -> Range {
    let column = |byte: u32| utf16_len(&line[..(byte as usize).min(line.len())]);
    range_for_span(
        range.start.line,
        column(range.start.character) as usize,
        column(range.end.character) as usize,
    )
}

fn range_for_span(line: u32, start: usize, end: usize) -> Range {
    Range {
        start: Position {
            line,
            character: start as u32,
        },
        end: Position {
            line,
            character: end as u32,
        },
    }
}

