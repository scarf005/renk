const GENERATED_HEADER: &str = "// @generated by renk; do not edit.\n";

#[derive(Debug)]
struct Backend {
    client: Client,
    documents: Arc<RwLock<HashMap<Url, String>>>,
    rust_analyzer: Arc<RwLock<Option<Arc<RustAnalyzerClient>>>>,
    /// The rust-analyzer each open document's generated Rust is open in, and that Rust's URI.
    /// A script's own rust-analyzer lives only here, so it exits when its entry goes.
    opened: Arc<RwLock<HashMap<Url, (Arc<RustAnalyzerClient>, Url)>>>,
    /// Serializes document syncs: tower-lsp runs notifications concurrently, which would start
    /// two rust-analyzers for one script or reorder its `didOpen` and `didChange`.
    sync: Arc<Mutex<()>>,
    initialize_params: Arc<RwLock<Option<InitializeParams>>>,
}

#[tower_lsp::async_trait]
impl LanguageServer for Backend {
    async fn initialize(&self, params: InitializeParams) -> Result<InitializeResult> {
        self.initialize_params.write().await.replace(params);

        Ok(InitializeResult {
            capabilities: ServerCapabilities {
                text_document_sync: Some(TextDocumentSyncCapability::Kind(
                    TextDocumentSyncKind::FULL,
                )),
                document_symbol_provider: Some(OneOf::Left(true)),
                hover_provider: Some(tower_lsp::lsp_types::HoverProviderCapability::Simple(true)),
                definition_provider: Some(OneOf::Left(true)),
                completion_provider: Some(CompletionOptions {
                    resolve_provider: Some(false),
                    trigger_characters: None,
                    all_commit_characters: None,
                    work_done_progress_options: Default::default(),
                    completion_item: None,
                }),
                ..ServerCapabilities::default()
            },
            server_info: None,
        })
    }

    async fn initialized(&self, params: InitializedParams) {
        if let Some(rust_analyzer) = self.rust_analyzer.read().await.as_ref() {
            rust_analyzer.notify("initialized", params).await;
        }
        self.client
            .log_message(MessageType::INFO, "renk language server initialized")
            .await;
    }

    async fn shutdown(&self) -> Result<()> {
        if let Some(rust_analyzer) = self.rust_analyzer.read().await.as_ref() {
            let _ = rust_analyzer.request("shutdown", ()).await;
        }
        Ok(())
    }

    async fn did_open(&self, params: DidOpenTextDocumentParams) {
        let _sync = self.sync.lock().await;
        let uri = params.text_document.uri;
        let version = params.text_document.version;
        let text = params.text_document.text;
        self.documents
            .write()
            .await
            .insert(uri.clone(), text.clone());
        self.sync_rust_document(&uri, &text, version).await;
        self.publish_diagnostics(uri, text).await;
    }

    async fn did_change(&self, params: DidChangeTextDocumentParams) {
        let _sync = self.sync.lock().await;
        let uri = params.text_document.uri;
        let version = params.text_document.version;
        let text = params
            .content_changes
            .into_iter()
            .last()
            .map(|change| change.text)
            .unwrap_or_default();
        self.documents
            .write()
            .await
            .insert(uri.clone(), text.clone());
        self.sync_rust_document(&uri, &text, version).await;
        self.publish_diagnostics(uri, text).await;
    }

    async fn did_close(&self, params: DidCloseTextDocumentParams) {
        let _sync = self.sync.lock().await;
        self.documents
            .write()
            .await
            .remove(&params.text_document.uri);
        self.close_rust_document(&params.text_document.uri).await;
        self.client
            .publish_diagnostics(params.text_document.uri, Vec::new(), None)
            .await;
    }

    async fn document_symbol(
        &self,
        params: DocumentSymbolParams,
    ) -> Result<Option<DocumentSymbolResponse>> {
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&params.text_document.uri) else {
            return Ok(None);
        };
        let uri = &params.text_document.uri;
        if source_syntax(uri) != SourceSyntax::Renk {
            return Ok(Some(DocumentSymbolResponse::Nested(Vec::new())));
        }
        let body = if is_script(uri, text) {
            script_body(text)
        } else {
            Ok(text.clone())
        };
        let Ok(output) = body.and_then(|body| transpile(&body)) else {
            return Ok(None);
        };

        Ok(Some(DocumentSymbolResponse::Nested(
            output
                .source_tree
                .iter()
                .filter_map(symbol_from_node)
                .collect(),
        )))
    }

    async fn hover(&self, params: HoverParams) -> Result<Option<Hover>> {
        let uri = params
            .text_document_position_params
            .text_document
            .uri
            .clone();
        let position = params.text_document_position_params.position;
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&uri) else {
            return Ok(None);
        };

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri)) = self.rust_analyzer(&uri).await
            && let Some(position) = source_position_to_rust_position(&uri, text, position)
        {
            rust_params.text_document_position_params.text_document.uri = rust_uri;
            rust_params.text_document_position_params.position = position;
            if let Some(mut hover) = rust_analyzer
                .request("textDocument/hover", rust_params)
                .await
                .and_then(|value| serde_json::from_value::<Hover>(value).ok())
            {
                hover.range = hover
                    .range
                    .map(|range| rust_range_to_source_range(&uri, text, range));
                return Ok(Some(hover));
            }
        }

        Ok(hover_at_position(text, position))
    }

    async fn goto_definition(
        &self,
        params: GotoDefinitionParams,
    ) -> Result<Option<GotoDefinitionResponse>> {
        let uri = params
            .text_document_position_params
            .text_document
            .uri
            .clone();
        let position = params.text_document_position_params.position;
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&uri) else {
            return Ok(None);
        };

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri)) = self.rust_analyzer(&uri).await
            && let Some(position) = source_position_to_rust_position(&uri, text, position)
        {
            rust_params.text_document_position_params.text_document.uri = rust_uri.clone();
            rust_params.text_document_position_params.position = position;
            if let Some(definition) = rust_analyzer
                .request("textDocument/definition", rust_params)
                .await
                .and_then(|value| serde_json::from_value(value).ok())
            {
                return Ok(Some(rust_definition_to_renk_definition(
                    text, &uri, &rust_uri, definition,
                )));
            }
        }

        let Some(range) = definition_range_at_position(text, position) else {
            return Ok(None);
        };

        Ok(Some(GotoDefinitionResponse::Scalar(Location {
            uri,
            range,
        })))
    }

    async fn completion(&self, params: CompletionParams) -> Result<Option<CompletionResponse>> {
        let uri = params.text_document_position.text_document.uri.clone();
        let documents = self.documents.read().await;
        let Some(text) = documents.get(&uri) else {
            return Ok(None);
        };

        let mut rust_params = params.clone();
        if let Some((rust_analyzer, rust_uri)) = self.rust_analyzer(&uri).await
            && let Some(position) =
                source_position_to_rust_position(&uri, text, params.text_document_position.position)
        {
            rust_params.text_document_position.text_document.uri = rust_uri;
            rust_params.text_document_position.position = position;
            if let Some(completion) = rust_analyzer
                .request("textDocument/completion", rust_params)
                .await
                .and_then(|value| serde_json::from_value(value).ok())
            {
                return Ok(Some(completion));
            }
        }

        Ok(Some(CompletionResponse::Array(completion_items(text))))
    }
}

impl Backend {
    /// The rust-analyzer a document's generated Rust is open in, and that Rust's URI.
    async fn rust_analyzer(&self, uri: &Url) -> Option<(Arc<RustAnalyzerClient>, Url)> {
        self.opened.read().await.get(uri).cloned()
    }

    /// Starts the rust-analyzer for a document: one over the generated workspace mirror, or for a
    /// script, one linked to its generated cargo-script file, which rust-analyzer resolves the
    /// frontmatter dependencies of.
    async fn ensure_rust_analyzer(&self, uri: &Url, text: &str) -> Option<Arc<RustAnalyzerClient>> {
        let script = is_script(uri, text);
        let workspace = self.rust_analyzer.read().await.as_ref().cloned();
        let existing = if script {
            self.rust_analyzer(uri)
                .await
                .map(|(rust_analyzer, _)| rust_analyzer)
                .filter(|rust_analyzer| {
                    !workspace
                        .as_ref()
                        .is_some_and(|workspace| Arc::ptr_eq(workspace, rust_analyzer))
                })
        } else {
            workspace
        };
        if existing.is_some() {
            return existing;
        }

        let mut params = self.initialize_params.read().await.as_ref().cloned()?;
        if script {
            let rust_path = script_rust_path(uri)?;
            let rust_root_uri = Url::from_directory_path(rust_path.parent()?).ok()?;
            params = rust_initialize_params(params, &rust_root_uri);
            params.initialization_options = Some(script_initialization_options(
                params.initialization_options.take(),
                &rust_path,
            ));
        } else {
            let rust_root_uri = target_renk_root_uri(&source_root_uri(&params)?)?;
            params = rust_initialize_params(params, &rust_root_uri);
        }
        match RustAnalyzerClient::spawn(params).await {
            Ok(rust_analyzer) => {
                let rust_analyzer = Arc::new(rust_analyzer);
                rust_analyzer
                    .notify("initialized", InitializedParams {})
                    .await;
                if !script {
                    self.rust_analyzer
                        .write()
                        .await
                        .replace(rust_analyzer.clone());
                }
                Some(rust_analyzer)
            }
            Err(error) => {
                self.client
                    .log_message(
                        MessageType::WARNING,
                        format!("rust-analyzer proxy disabled: {error}"),
                    )
                    .await;
                None
            }
        }
    }

    /// Sends a document's generated Rust to its rust-analyzer: a change when that rust-analyzer
    /// already has it open, otherwise an open, after closing it where it was open before (the
    /// document may have become a script or stopped being one).
    async fn sync_rust_document(&self, uri: &Url, text: &str, version: i32) {
        let Some(rust_uri) = self.rust_uri_for_renk_uri(uri, text).await else {
            return;
        };
        let Ok(rust) = generated(uri, text).map(|generated| generated.rust) else {
            return;
        };
        if is_script(uri, text) {
            write_script_rust_file(&rust_uri, &rust);
        } else {
            self.copy_generated_cargo_manifests(uri).await;
            write_generated_rust_file(&rust_uri, &rust);
        }
        let Some(rust_analyzer) = self.ensure_rust_analyzer(uri, text).await else {
            return;
        };

        let previous = self
            .opened
            .write()
            .await
            .insert(uri.clone(), (rust_analyzer.clone(), rust_uri.clone()));
        match previous {
            Some((previous, previous_uri))
                if Arc::ptr_eq(&previous, &rust_analyzer) && previous_uri == rust_uri =>
            {
                rust_analyzer
                    .notify(
                        "textDocument/didChange",
                        DidChangeTextDocumentParams {
                            text_document: VersionedTextDocumentIdentifier {
                                uri: rust_uri,
                                version,
                            },
                            content_changes: vec![TextDocumentContentChangeEvent {
                                range: None,
                                range_length: None,
                                text: rust,
                            }],
                        },
                    )
                    .await;
            }
            previous => {
                if let Some((previous, previous_uri)) = previous {
                    close_in(&previous, previous_uri).await;
                }
                rust_analyzer
                    .notify(
                        "textDocument/didOpen",
                        DidOpenTextDocumentParams {
                            text_document: TextDocumentItem {
                                uri: rust_uri,
                                language_id: "rust".to_string(),
                                version,
                                text: rust,
                            },
                        },
                    )
                    .await;
            }
        }
    }

    async fn close_rust_document(&self, uri: &Url) {
        if let Some((rust_analyzer, rust_uri)) = self.opened.write().await.remove(uri) {
            close_in(&rust_analyzer, rust_uri).await;
        }
    }

    async fn rust_uri_for_renk_uri(&self, uri: &Url, text: &str) -> Option<Url> {
        if is_script(uri, text) {
            return Url::from_file_path(script_rust_path(uri)?).ok();
        }
        let params = self.initialize_params.read().await;
        let source_root_uri = source_root_uri(params.as_ref()?)?;
        let rust_root_uri = target_renk_root_uri(&source_root_uri)?;
        rust_uri_for_renk_uri(uri, &source_root_uri, &rust_root_uri)
    }

    async fn copy_generated_cargo_manifests(&self, uri: &Url) {
        let params = self.initialize_params.read().await;
        let Some(source_root_uri) = params.as_ref().and_then(source_root_uri) else {
            return;
        };
        let Some(rust_root_uri) = target_renk_root_uri(&source_root_uri) else {
            return;
        };
        copy_generated_cargo_manifests(uri, &source_root_uri, &rust_root_uri);
    }

    async fn publish_diagnostics(&self, uri: Url, text: String) {
        let diagnostics = match generated(&uri, &text) {
            Ok(_) => Vec::new(),
            Err(error) => vec![Diagnostic {
                range: line_range(&text, error.line),
                severity: Some(DiagnosticSeverity::ERROR),
                source: Some("renk".to_string()),
                message: error.to_string(),
                ..Diagnostic::default()
            }],
        };
        self.client
            .publish_diagnostics(uri, diagnostics, None)
            .await;
    }
}

#[derive(Debug)]
struct RustAnalyzerClient {
    sender: mpsc::UnboundedSender<serde_json::Value>,
    pending: Arc<Mutex<HashMap<u64, oneshot::Sender<serde_json::Value>>>>,
    next_id: AtomicU64,
    _child: Arc<Mutex<tokio::process::Child>>,
}

impl RustAnalyzerClient {
    async fn spawn(params: InitializeParams) -> std::io::Result<Self> {
        let mut child = Command::new("rust-analyzer")
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .kill_on_drop(true)
            .spawn()?;
        let stdin = child.stdin.take().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::BrokenPipe,
                "rust-analyzer stdin unavailable",
            )
        })?;
        let stdout = child.stdout.take().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::BrokenPipe,
                "rust-analyzer stdout unavailable",
            )
        })?;
        let (sender, mut receiver) = mpsc::unbounded_channel::<serde_json::Value>();
        let pending = Arc::new(Mutex::new(HashMap::new()));
        let reader_pending = pending.clone();
        let replies = sender.clone();
        let config = params
            .initialization_options
            .clone()
            .unwrap_or(serde_json::Value::Null);

        tokio::spawn(async move {
            let mut stdin = stdin;
            while let Some(message) = receiver.recv().await {
                if write_lsp_message(&mut stdin, &message).await.is_err() {
                    break;
                }
            }
        });
        tokio::spawn(async move {
            read_rust_analyzer_messages(stdout, reader_pending, replies, config).await;
        });

        let client = Self {
            sender,
            pending,
            next_id: AtomicU64::new(1),
            _child: Arc::new(Mutex::new(child)),
        };
        client.request("initialize", params).await.ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::TimedOut,
                "rust-analyzer did not initialize",
            )
        })?;
        Ok(client)
    }

    async fn notify<T: serde::Serialize>(&self, method: &str, params: T) {
        let Ok(params) = serde_json::to_value(params) else {
            return;
        };
        let _ = self.sender.send(serde_json::json!({
            "jsonrpc": "2.0",
            "method": method,
            "params": params,
        }));
    }

    async fn request<T: serde::Serialize>(
        &self,
        method: &str,
        params: T,
    ) -> Option<serde_json::Value> {
        let id = self.next_id.fetch_add(1, Ordering::Relaxed);
        let params = serde_json::to_value(params).ok()?;
        let (sender, receiver) = oneshot::channel();
        self.pending.lock().await.insert(id, sender);
        if self
            .sender
            .send(serde_json::json!({
                "jsonrpc": "2.0",
                "id": id,
                "method": method,
                "params": params,
            }))
            .is_err()
        {
            self.pending.lock().await.remove(&id);
            return None;
        }
        tokio::time::timeout(std::time::Duration::from_secs(5), receiver)
            .await
            .ok()
            .and_then(std::result::Result::ok)
    }
}

async fn close_in(rust_analyzer: &RustAnalyzerClient, rust_uri: Url) {
    rust_analyzer
        .notify(
            "textDocument/didClose",
            DidCloseTextDocumentParams {
                text_document: tower_lsp::lsp_types::TextDocumentIdentifier { uri: rust_uri },
            },
        )
        .await;
}

/// The rust-analyzer settings of a script's rust-analyzer: the editor's, linked to the script's
/// generated cargo-script file.
fn script_initialization_options(
    options: Option<serde_json::Value>,
    rust_path: &Path,
) -> serde_json::Value {
    let mut options = options
        .filter(serde_json::Value::is_object)
        .unwrap_or_else(|| serde_json::json!({}));
    options["linkedProjects"] = serde_json::json!([rust_path]);
    options
}

/// Hands rust-analyzer's responses to their requests. Its own requests get an answer here: their
/// ids are rust-analyzer's, which would otherwise take the place of a response to a request of
/// ours with the same id. `workspace/configuration` gets `config`, the settings it started with,
/// once per item; the rest get an empty answer.
async fn read_rust_analyzer_messages(
    stdout: impl tokio::io::AsyncRead + Unpin,
    pending: Arc<Mutex<HashMap<u64, oneshot::Sender<serde_json::Value>>>>,
    replies: mpsc::UnboundedSender<serde_json::Value>,
    config: serde_json::Value,
) {
    let mut reader = BufReader::new(stdout);
    loop {
        let Some(message) = read_lsp_message(&mut reader).await else {
            break;
        };
        if message.get("method").is_some() {
            if let Some(id) = message.get("id") {
                let result = if message["method"] == "workspace/configuration" {
                    let items = message["params"]["items"].as_array().map_or(0, Vec::len);
                    serde_json::Value::Array(vec![config.clone(); items])
                } else {
                    serde_json::Value::Null
                };
                let _ = replies.send(serde_json::json!({
                    "jsonrpc": "2.0",
                    "id": id,
                    "result": result,
                }));
            }
            continue;
        }
        let Some(id) = message.get("id").and_then(serde_json::Value::as_u64) else {
            continue;
        };
        let response = message
            .get("result")
            .cloned()
            .unwrap_or(serde_json::Value::Null);
        if let Some(sender) = pending.lock().await.remove(&id) {
            let _ = sender.send(response);
        }
    }
}

async fn read_lsp_message<R: tokio::io::AsyncBufRead + Unpin>(
    reader: &mut R,
) -> Option<serde_json::Value> {
    let mut content_length = None;
    loop {
        let mut line = String::new();
        if reader.read_line(&mut line).await.ok()? == 0 {
            return None;
        }
        let line = line.trim_end_matches(['\r', '\n']);
        if line.is_empty() {
            break;
        }
        if let Some(value) = line.strip_prefix("Content-Length: ") {
            content_length = value.parse::<usize>().ok();
        }
    }

    let mut body = vec![0; content_length?];
    reader.read_exact(&mut body).await.ok()?;
    serde_json::from_slice(&body).ok()
}

async fn write_lsp_message<W: tokio::io::AsyncWrite + Unpin>(
    writer: &mut W,
    message: &serde_json::Value,
) -> std::io::Result<()> {
    let body = serde_json::to_vec(message)?;
    writer
        .write_all(format!("Content-Length: {}\r\n\r\n", body.len()).as_bytes())
        .await?;
    writer.write_all(&body).await?;
    writer.flush().await
}

fn source_root_uri(params: &InitializeParams) -> Option<Url> {
    params.root_uri.clone().or_else(|| {
        params
            .workspace_folders
            .as_ref()
            .and_then(|folders| folders.first())
            .map(|folder| folder.uri.clone())
    })
}

fn target_renk_root_uri(source_root_uri: &Url) -> Option<Url> {
    let mut path = source_root_uri.to_file_path().ok()?;
    path.push("target");
    path.push("renk");
    Url::from_directory_path(path).ok()
}

fn rust_initialize_params(mut params: InitializeParams, rust_root_uri: &Url) -> InitializeParams {
    // Keep rust-analyzer on the default UTF-16 columns that renk-lsp also uses.
    if let Some(general) = params.capabilities.general.as_mut() {
        general.position_encodings = None;
    }
    params.root_uri = Some(rust_root_uri.clone());
    params.workspace_folders = Some(vec![WorkspaceFolder {
        uri: rust_root_uri.clone(),
        name: "renk-generated".to_string(),
    }]);
    params
}

fn rust_uri_for_renk_uri(uri: &Url, source_root_uri: &Url, rust_root_uri: &Url) -> Option<Url> {
    let source_path = uri.to_file_path().ok()?;
    let source_root = source_root_uri.to_file_path().ok()?;
    let rust_root = rust_root_uri.to_file_path().ok()?;
    let relative = source_path
        .strip_prefix(&source_root)
        .ok()
        .map(Path::to_path_buf)
        .or_else(|| source_path.file_name().map(PathBuf::from))?;
    let mut path = rust_root.join(relative);
    path.set_extension("rs");
    Url::from_file_path(path).ok()
}

fn copy_generated_cargo_manifests(uri: &Url, source_root_uri: &Url, rust_root_uri: &Url) {
    let Ok(source_path) = uri.to_file_path() else {
        return;
    };
    let Ok(source_root) = source_root_uri.to_file_path() else {
        return;
    };
    let Ok(rust_root) = rust_root_uri.to_file_path() else {
        return;
    };
    let Some(mut current) = source_path.parent() else {
        return;
    };

    while current.starts_with(&source_root) {
        let manifest = current.join("Cargo.toml");
        if manifest.is_file()
            && let Ok(relative) = manifest.strip_prefix(&source_root)
        {
            copy_manifest_if_changed(&manifest, &rust_root.join(relative), current == source_root);
        }
        if current == source_root {
            break;
        }
        let Some(parent) = current.parent() else {
            break;
        };
        current = parent;
    }
}

fn copy_manifest_if_changed(source: &Path, destination: &Path, is_root_manifest: bool) {
    let Ok(mut content) = fs::read_to_string(source) else {
        return;
    };
    if is_root_manifest && !manifest_has_section(&content, "package") {
        content = "[workspace]\n\n[package]\nname = \"renk-generated\"\nversion = \"0.0.0\"\nedition = \"2024\"\n".to_string();
    } else if is_root_manifest && !manifest_has_section(&content, "workspace") {
        content = format!("[workspace]\n\n{content}");
    }
    if fs::read_to_string(destination).is_ok_and(|existing| existing == content) {
        return;
    }
    if let Some(parent) = destination.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(destination, content);
}

fn manifest_has_section(content: &str, section: &str) -> bool {
    content
        .lines()
        .any(|line| line.trim() == format!("[{section}]"))
}

fn write_generated_rust_file(uri: &Url, rust: &str) {
    let Ok(path) = uri.to_file_path() else {
        return;
    };
    let generated = format!("{GENERATED_HEADER}{rust}");
    if let Ok(existing) = fs::read_to_string(&path) {
        if !existing.starts_with(GENERATED_HEADER) || existing == generated {
            return;
        }
    }
    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(path, generated);
}

/// Writes a script's generated cargo-script file, which must start with its frontmatter, so it has
/// no generated header; it lives in renk's cache, which nothing else writes to.
fn write_script_rust_file(uri: &Url, rust: &str) {
    let Ok(path) = uri.to_file_path() else {
        return;
    };
    if fs::read_to_string(&path).is_ok_and(|existing| existing == rust) {
        return;
    }
    if let Some(parent) = path.parent() {
        let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(path, rust);
}

fn source_syntax(uri: &Url) -> SourceSyntax {
    match uri
        .to_file_path()
        .ok()
        .and_then(|path| {
            path.extension()
                .and_then(|extension| extension.to_str())
                .map(str::to_string)
        })
        .as_deref()
    {
        Some("rs") => SourceSyntax::Rust,
        _ => SourceSyntax::Renk,
    }
}

/// A document's generated Rust and, for each 1-based Rust line, the document line it came from
/// and whether renk synthesized it, like a closing brace.
struct Generated {
    rust: String,
    source_lines: Vec<(usize, bool)>,
}

fn generated(uri: &Url, text: &str) -> std::result::Result<Generated, TranspileError> {
    if source_syntax(uri) == SourceSyntax::Rust {
        return Ok(Generated {
            rust: text.to_string(),
            source_lines: (1..=text.lines().count())
                .map(|line| (line, false))
                .collect(),
        });
    }
    if is_script(uri, text) {
        let package = script_rust_path(uri)
            .map_or_else(|| "script".to_string(), |path| script_package(&path));
        let script = script_rust(text, SourceSyntax::Renk, &package)?;
        return Ok(Generated {
            rust: script.rust,
            source_lines: script.source_lines,
        });
    }
    let output = transpile(text)?;
    Ok(Generated {
        source_lines: output.line_origins(),
        rust: output.rust,
    })
}

/// Whether a renk document runs with `renk script`: it starts with a `#!` line or frontmatter, or
/// no Cargo package around it could build it as a module.
fn is_script(uri: &Url, text: &str) -> bool {
    let headed = script_parts(text).map_or(true, |parts| parts.body_start > 0);
    let packaged = uri.to_file_path().is_ok_and(|path| {
        path.ancestors()
            .skip(1)
            .any(|dir| dir.join("Cargo.toml").is_file())
    });
    source_syntax(uri) == SourceSyntax::Renk && (headed || !packaged)
}

/// The generated cargo-script file rust-analyzer reads for a script, apart from the one
/// `renk script` builds so unsaved edits never reach a build.
fn script_rust_path(uri: &Url) -> Option<PathBuf> {
    let path = uri.to_file_path().ok()?;
    let path = fs::canonicalize(&path).unwrap_or(path);
    Some(script_cache_path(&cache_root()?.join("lsp"), &path))
}

/// The character index of a UTF-16 column of `line`.
fn char_column(line: &str, character: u32) -> usize {
    let mut units = 0;
    line.chars()
        .take_while(|c| {
            units += c.len_utf16() as u32;
            units <= character
        })
        .count()
}

/// The UTF-16 column of a character index of `line`.
fn utf16_column(line: &str, column: usize) -> u32 {
    line.chars()
        .take(column)
        .map(|c| c.len_utf16() as u32)
        .sum()
}

fn source_position_to_rust_position(uri: &Url, text: &str, position: Position) -> Option<Position> {
    let generated = generated(uri, text).ok()?;
    let line = position.line as usize + 1;
    let rust_line = generated
        .source_lines
        .iter()
        .position(|&(source, synthesized)| source == line && !synthesized)?;
    let source = text.lines().nth(position.line as usize).unwrap_or_default();
    let rust = generated.rust.lines().nth(rust_line).unwrap_or_default();
    let column = script_column(rust, source, char_column(source, position.character));
    Some(Position {
        line: rust_line as u32,
        character: utf16_column(rust, column),
    })
}

fn rust_range_to_source_range(uri: &Url, text: &str, range: Range) -> Range {
    Range {
        start: rust_position_to_source_position(uri, text, range.start),
        end: rust_position_to_source_position(uri, text, range.end),
    }
}

fn rust_position_to_source_position(uri: &Url, text: &str, position: Position) -> Position {
    let Ok(generated) = generated(uri, text) else {
        return position;
    };
    let Some(&(line, synthesized)) = generated.source_lines.get(position.line as usize) else {
        return position;
    };
    let source = text.lines().nth(line.saturating_sub(1)).unwrap_or_default();
    let rust = generated
        .rust
        .lines()
        .nth(position.line as usize)
        .unwrap_or_default();
    let column = if synthesized {
        source.chars().count()
    } else {
        script_column(source, rust, char_column(rust, position.character))
    };
    Position {
        line: line.saturating_sub(1) as u32,
        character: utf16_column(source, column),
    }
}

fn rust_definition_to_renk_definition(
    text: &str,
    renk_uri: &Url,
    rust_uri: &Url,
    definition: GotoDefinitionResponse,
) -> GotoDefinitionResponse {
    match definition {
        GotoDefinitionResponse::Scalar(location) => GotoDefinitionResponse::Scalar(
            rust_location_to_renk_location(text, renk_uri, rust_uri, location),
        ),
        GotoDefinitionResponse::Array(locations) => GotoDefinitionResponse::Array(
            locations
                .into_iter()
                .map(|location| rust_location_to_renk_location(text, renk_uri, rust_uri, location))
                .collect(),
        ),
        GotoDefinitionResponse::Link(links) => GotoDefinitionResponse::Link(
            links
                .into_iter()
                .map(|link| {
                    rust_location_link_to_renk_location_link(text, renk_uri, rust_uri, link)
                })
                .collect(),
        ),
    }
}

fn rust_location_to_renk_location(
    text: &str,
    renk_uri: &Url,
    rust_uri: &Url,
    mut location: Location,
) -> Location {
    if rust_uri == &location.uri {
        location.uri = renk_uri.clone();
        location.range = rust_range_to_source_range(renk_uri, text, location.range);
    }
    location
}

fn rust_location_link_to_renk_location_link(
    text: &str,
    renk_uri: &Url,
    rust_uri: &Url,
    mut link: LocationLink,
) -> LocationLink {
    if rust_uri == &link.target_uri {
        link.target_uri = renk_uri.clone();
        link.target_range = rust_range_to_source_range(renk_uri, text, link.target_range);
        link.target_selection_range =
            rust_range_to_source_range(renk_uri, text, link.target_selection_range);
        link.origin_selection_range = link
            .origin_selection_range
            .map(|range| rust_range_to_source_range(renk_uri, text, range));
    }
    link
}

#[allow(deprecated)]
fn symbol_from_node(node: &SourceMapNode) -> Option<DocumentSymbol> {
    let kind = symbol_kind(&node.kind)?;
    Some(DocumentSymbol {
        name: symbol_name(node),
        detail: Some(node.kind.clone()),
        kind,
        tags: None,
        deprecated: None,
        range: node_range(node),
        selection_range: node_range(node),
        children: Some(node.children.iter().filter_map(symbol_from_node).collect()),
    })
}

fn symbol_kind(kind: &str) -> Option<SymbolKind> {
    match kind {
        "struct" => Some(SymbolKind::STRUCT),
        "enum" => Some(SymbolKind::ENUM),
        "trait" => Some(SymbolKind::INTERFACE),
        "impl" => Some(SymbolKind::OBJECT),
        "module" => Some(SymbolKind::MODULE),
        "function" => Some(SymbolKind::FUNCTION),
        "member" | "field" => Some(SymbolKind::FIELD),
        _ => None,
    }
}

fn symbol_name(node: &SourceMapNode) -> String {
    let text = node.source_text.trim();
    if let Some(name) = item_name(text, "struct")
        .or_else(|| item_name(text, "enum"))
        .or_else(|| item_name(text, "trait"))
        .or_else(|| item_name(text, "mod"))
        .or_else(|| item_name(text, "fn"))
    {
        name
    } else if let Some(rest) = text.strip_prefix("impl") {
        format!("impl{}", rest)
    } else {
        text.split([':', '=', '(', ' '])
            .next()
            .unwrap_or(text)
            .to_string()
    }
}

fn item_name(text: &str, keyword: &str) -> Option<String> {
    let index = text.find(keyword)? + keyword.len();
    let rest = text[index..].trim_start();
    let name = rest
        .split(|character: char| !is_identifier_continue(character))
        .find(|part| !part.is_empty())?;
    Some(name.to_string())
}

fn node_range(node: &SourceMapNode) -> Range {
    let line = node.source_line.saturating_sub(1) as u32;
    let first_line = node.source_text.lines().next().unwrap_or_default();
    Range {
        start: Position {
            line,
            character: node.source_column as u32,
        },
        end: Position {
            line,
            character: node.source_column as u32 + utf16_len(first_line),
        },
    }
}

fn line_range(text: &str, line: usize) -> Range {
    let line_index = line.saturating_sub(1);
    let length = text
        .lines()
        .nth(line_index)
        .map(utf16_len)
        .unwrap_or_default();
    Range {
        start: Position {
            line: line_index as u32,
            character: 0,
        },
        end: Position {
            line: line_index as u32,
            character: length,
        },
    }
}

const KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "else", "enum", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "return", "self",
    "Self", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while",
];

const BUILTIN_TYPES: &[&str] = &[
    "bool", "char", "f32", "f64", "i8", "i16", "i32", "i64", "i128", "isize", "str", "u8", "u16",
    "u32", "u64", "u128", "usize",
];

#[derive(Debug, Clone, PartialEq, Eq)]
struct Word {
    text: String,
    range: Range,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Declaration {
    name: String,
    detail: String,
    kind: CompletionItemKind,
    range: Range,
}

fn hover_at_position(text: &str, position: Position) -> Option<Hover> {
    let word = word_at_position(text, position)?;
    let contents = if BUILTIN_TYPES.contains(&word.text.as_str()) {
        format!("builtin type `{}`", word.text)
    } else if KEYWORDS.contains(&word.text.as_str()) {
        format!("keyword `{}`", word.text)
    } else {
        declaration_at_position(text, &word)?.detail
    };

    Some(Hover {
        contents: HoverContents::Markup(MarkupContent {
            kind: MarkupKind::Markdown,
            value: contents,
        }),
        range: Some(word.range),
    })
}

fn definition_range_at_position(text: &str, position: Position) -> Option<Range> {
    let word = word_at_position(text, position)?;
    declaration_at_position(text, &word).map(|declaration| declaration.range)
}

fn completion_items(text: &str) -> Vec<CompletionItem> {
    let mut seen = BTreeSet::new();
    KEYWORDS
        .iter()
        .map(|keyword| CompletionItem {
            label: (*keyword).to_string(),
            kind: Some(CompletionItemKind::KEYWORD),
            ..CompletionItem::default()
        })
        .chain(BUILTIN_TYPES.iter().map(|builtin| CompletionItem {
            label: (*builtin).to_string(),
            kind: Some(CompletionItemKind::TYPE_PARAMETER),
            detail: Some("builtin type".to_string()),
            ..CompletionItem::default()
        }))
        .chain(
            collect_declarations(text)
                .into_iter()
                .map(|declaration| CompletionItem {
                    label: declaration.name,
                    kind: Some(declaration.kind),
                    detail: Some(declaration.detail),
                    ..CompletionItem::default()
                }),
        )
        .filter(|item| seen.insert(item.label.clone()))
        .collect()
}

fn declaration_at_position(text: &str, word: &Word) -> Option<Declaration> {
    let declarations = collect_declarations(text);
    declarations
        .iter()
        .rev()
        .find(|declaration| {
            declaration.name == word.text && declaration.range.start.line <= word.range.start.line
        })
        .or_else(|| {
            declarations
                .iter()
                .find(|declaration| declaration.name == word.text)
        })
        .cloned()
}

fn collect_declarations(text: &str) -> Vec<Declaration> {
    text.lines()
        .enumerate()
        .flat_map(|(index, raw)| {
            declarations_from_line(index as u32, raw)
                .into_iter()
                .map(move |mut declaration| {
                    declaration.range = utf16_range(raw, declaration.range);
                    declaration
                })
        })
        .collect()
}

fn declarations_from_line(line: u32, raw: &str) -> Vec<Declaration> {
    let text = raw.trim_start();
    if text.is_empty() || text.starts_with("//") {
        return Vec::new();
    }

    let indent = raw.len() - text.len();
    let mut declarations = Vec::new();
    if let Some(declaration) =
        item_declaration(line, indent, text, "struct", CompletionItemKind::STRUCT)
            .or_else(|| item_declaration(line, indent, text, "enum", CompletionItemKind::ENUM))
            .or_else(|| {
                item_declaration(line, indent, text, "trait", CompletionItemKind::INTERFACE)
            })
            .or_else(|| item_declaration(line, indent, text, "mod", CompletionItemKind::MODULE))
            .or_else(|| item_declaration(line, indent, text, "fn", CompletionItemKind::FUNCTION))
    {
        if declaration.kind == CompletionItemKind::FUNCTION {
            declarations.extend(parameter_declarations(line, indent, text));
        }
        declarations.push(declaration);
        return declarations;
    }

    if let Some(declaration) = let_declaration(line, indent, text) {
        declarations.push(declaration);
    } else if let Some(declaration) = field_declaration(line, indent, text) {
        declarations.push(declaration);
    }
    declarations
}

fn item_declaration(
    line: u32,
    indent: usize,
    text: &str,
    keyword: &str,
    kind: CompletionItemKind,
) -> Option<Declaration> {
    let keyword_start = keyword_position(text, keyword)?;
    let name_start = text[keyword_start + keyword.len()..]
        .find(is_identifier_start)
        .map(|offset| keyword_start + keyword.len() + offset)?;
    let name_end = identifier_end(text, name_start);
    let name = text[name_start..name_end].to_string();
    Some(Declaration {
        name,
        detail: trim_assignment_tail(text).to_string(),
        kind,
        range: range_for_span(line, indent + name_start, indent + name_end),
    })
}

fn parameter_declarations(line: u32, indent: usize, text: &str) -> Vec<Declaration> {
    let Some(fn_start) = keyword_position(text, "fn") else {
        return Vec::new();
    };
    let Some(open) = text[fn_start..].find('(').map(|offset| fn_start + offset) else {
        return Vec::new();
    };
    let Some(close) = matching_delimiter(text, open, '(', ')') else {
        return Vec::new();
    };

    split_top_level_spans(&text[open + 1..close], ',')
        .into_iter()
        .filter_map(|(start, end)| {
            let parameter = &text[open + 1 + start..open + 1 + end];
            let trimmed_start = parameter.len() - parameter.trim_start().len();
            let trimmed = parameter.trim();
            let colon = trimmed.find(':')?;
            let name = trimmed[..colon].trim();
            if name == "self" || name == "&self" || name == "&mut self" {
                return None;
            }
            let name_start = open + 1 + start + trimmed_start + trimmed[..colon].find(name)?;
            let name_end = name_start + name.len();
            Some(Declaration {
                name: name.to_string(),
                detail: format!("parameter {name}: {}", trimmed[colon + 1..].trim()),
                kind: CompletionItemKind::VARIABLE,
                range: range_for_span(line, indent + name_start, indent + name_end),
            })
        })
        .collect()
}

fn let_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let rest = text.strip_prefix("let ")?;
    let rest_offset = text.len() - rest.len();
    let rest = rest.strip_prefix("mut ").unwrap_or(rest);
    let rest_offset = if rest.as_ptr() == text[rest_offset..].as_ptr() {
        rest_offset
    } else {
        rest_offset + "mut ".len()
    };
    let name_start = rest.find(is_identifier_start)?;
    let name_end = identifier_end(rest, name_start);
    let name = &rest[name_start..name_end];
    let after_name = &rest[name_end..];
    let detail = after_name
        .trim_start()
        .strip_prefix(':')
        .and_then(|after_colon| after_colon.split('=').next())
        .map(str::trim)
        .filter(|annotation| !annotation.is_empty())
        .map(|annotation| format!("let {name}: {annotation}"))
        .unwrap_or_else(|| format!("let {name}"));

    Some(Declaration {
        name: name.to_string(),
        detail,
        kind: CompletionItemKind::VARIABLE,
        range: range_for_span(
            line,
            indent + rest_offset + name_start,
            indent + rest_offset + name_end,
        ),
    })
}

fn field_declaration(line: u32, indent: usize, text: &str) -> Option<Declaration> {
    let (text, offset) = text
        .strip_prefix("pub ")
        .map(|text| (text, "pub ".len()))
        .unwrap_or((text, 0));
    let colon = text.find(':')?;
    if text[..colon].contains([' ', '(', ')', '=']) {
        return None;
    }
    let name = text[..colon].trim();
    if name.is_empty() || !name.chars().next().is_some_and(is_identifier_start) {
        return None;
    }
    Some(Declaration {
        name: name.to_string(),
        detail: format!("field {name}: {}", text[colon + 1..].trim()),
        kind: CompletionItemKind::FIELD,
        range: range_for_span(line, indent + offset, indent + offset + name.len()),
    })
}

fn word_at_position(text: &str, position: Position) -> Option<Word> {
    let raw = text.lines().nth(position.line as usize)?;
    let cursor = byte_column(raw, position.character);
    let start = raw[..cursor]
        .char_indices()
        .rev()
        .take_while(|(_, character)| is_identifier_continue(*character))
        .last()
        .map_or(cursor, |(start, _)| start);
    let end = identifier_end(raw, cursor);
    if start == end {
        return None;
    }

    Some(Word {
        text: raw[start..end].to_string(),
        range: utf16_range(raw, range_for_span(position.line, start, end)),
    })
}

fn keyword_position(text: &str, keyword: &str) -> Option<usize> {
    text.match_indices(keyword)
        .find(|(index, _)| {
            let before = text[..*index]
                .chars()
                .next_back()
                .is_none_or(|character| !is_identifier_continue(character));
            let after = text[index + keyword.len()..]
                .chars()
                .next()
                .is_none_or(|character| !is_identifier_continue(character));
            before && after
        })
        .map(|(index, _)| index)
}

fn identifier_end(text: &str, start: usize) -> usize {
    text[start..]
        .char_indices()
        .find(|(_, character)| !is_identifier_continue(*character))
        .map_or(text.len(), |(offset, _)| start + offset)
}

fn is_identifier_start(character: char) -> bool {
    character == '_' || unicode_ident::is_xid_start(character)
}

fn is_identifier_continue(character: char) -> bool {
    unicode_ident::is_xid_continue(character)
}

fn trim_assignment_tail(text: &str) -> &str {
    text.split(" =")
        .next()
        .unwrap_or(text)
        .trim_end_matches('=')
        .trim()
}

fn matching_delimiter(text: &str, open: usize, open_char: char, close_char: char) -> Option<usize> {
    let mut depth = 0usize;
    for (index, character) in text[open..].char_indices() {
        if character == open_char {
            depth += 1;
        } else if character == close_char {
            depth = depth.saturating_sub(1);
            if depth == 0 {
                return Some(open + index);
            }
        }
    }
    None
}

fn split_top_level_spans(text: &str, delimiter: char) -> Vec<(usize, usize)> {
    let mut spans = Vec::new();
    let mut start = 0usize;
    let mut parens = 0usize;
    let mut brackets = 0usize;
    let mut braces = 0usize;
    for (index, character) in text.char_indices() {
        match character {
            '(' => parens += 1,
            ')' => parens = parens.saturating_sub(1),
            '[' => brackets += 1,
            ']' => brackets = brackets.saturating_sub(1),
            '{' => braces += 1,
            '}' => braces = braces.saturating_sub(1),
            character if character == delimiter && parens == 0 && brackets == 0 && braces == 0 => {
                spans.push((start, index));
                start = index + character.len_utf8();
            }
            _ => {}
        }
    }
    spans.push((start, text.len()));
    spans
}

/// Byte offset in `line` of an LSP column, which counts UTF-16 code units.
fn byte_column(line: &str, character: u32) -> usize {
    let mut units = 0u32;
    for (offset, character_at) in line.char_indices() {
        if units >= character {
            return offset;
        }
        units += character_at.len_utf16() as u32;
    }
    line.len()
}

fn utf16_len(line: &str) -> u32 {
    line.encode_utf16().count() as u32
}

/// Converts a single-line range from byte columns in `line` to UTF-16 columns.
fn utf16_range(line: &str, range: Range) -> Range {
    let column = |byte: u32| utf16_len(&line[..(byte as usize).min(line.len())]);
    range_for_span(
        range.start.line,
        column(range.start.character) as usize,
        column(range.end.character) as usize,
    )
}

fn range_for_span(line: u32, start: usize, end: usize) -> Range {
    Range {
        start: Position {
            line,
            character: start as u32,
        },
        end: Position {
            line,
            character: end as u32,
        },
    }
}

