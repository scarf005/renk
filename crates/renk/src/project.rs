//! The Cargo packages that one cargo call can build, and the `.rk` sources in them.

use std::{
    fs,
    io::{self, Read},
    path::{Path, PathBuf},
};

use toml_edit::{DocumentMut, TableLike, Value};

/// The first line of every Rust file that renk writes beside a `.rk` source.
pub const GENERATED_HEADER: &str = "// @generated by renk; do not edit.\n";

/// The files and directories of a package that cargo reads sources from.
const SOURCE_ROOTS: [&str; 5] = ["build.rk", "src", "examples", "tests", "benches"];

/// A workspace and the directories of the packages that cargo can build in it.
pub struct Workspace {
    /// The directory that rustc runs in. rustc names the files of packages under it relative to it.
    pub root: PathBuf,
    /// Every package under `root`, and every package that a `path` dependency names outside it.
    pub packages: Vec<PathBuf>,
}

/// The workspace of the package at the manifest `start`, or of the nearest package above the
/// directory `start`. Cargo cannot answer this before the first transpile, because it rejects a
/// package whose only sources are `.rk` files.
pub fn workspace(start: &Path) -> Option<Workspace> {
    let manifest = if start.is_file() {
        start.to_path_buf()
    } else {
        start
            .ancestors()
            .map(|dir| dir.join("Cargo.toml"))
            .find(|path| path.is_file())?
    };
    let package = fs::canonicalize(manifest.parent()?).ok()?;
    let named = manifest_at(&package).and_then(|document| {
        let path = document.get("package")?.get("workspace")?.as_str()?;
        fs::canonicalize(package.join(path)).ok()
    });
    let root = named
        .or_else(|| {
            package
                .ancestors()
                .find(|dir| {
                    manifest_at(dir).is_some_and(|document| document.contains_key("workspace"))
                })
                .map(Path::to_path_buf)
        })
        .unwrap_or(package);

    let mut queue = Vec::new();
    let _ = walk(&root, &mut |path| {
        if path.file_name().is_some_and(|name| name == "Cargo.toml") {
            queue.extend(path.parent().map(Path::to_path_buf));
        }
    });
    let mut seen = queue.clone();
    let mut packages = Vec::new();
    // A path dependency can name a package that has path dependencies of its own.
    while let Some(dir) = queue.pop() {
        let Some(mut document) = manifest_at(&dir) else {
            continue;
        };
        visit_dependency_paths(document.as_table_mut(), &mut |path| {
            let found = path
                .as_str()
                .and_then(|path| fs::canonicalize(dir.join(path)).ok())
                .filter(|path| !path.starts_with(&root) && !seen.contains(path));
            if let Some(path) = found {
                seen.push(path.clone());
                queue.push(path);
            }
        });
        if document.contains_key("package") {
            packages.push(dir);
        }
    }
    Some(Workspace { root, packages })
}

/// The manifest in `dir`, if it is valid TOML.
fn manifest_at(dir: &Path) -> Option<DocumentMut> {
    fs::read_to_string(dir.join("Cargo.toml"))
        .ok()?
        .parse()
        .ok()
}

/// Calls `visit` with the `path` of each dependency in the manifest `table`: the dependency
/// tables of the package, of each `target`, of the `workspace`, and of each `patch` source.
pub fn visit_dependency_paths(table: &mut dyn TableLike, visit: &mut dyn FnMut(&mut Value)) {
    for (key, item) in table.iter_mut() {
        let Some(table) = item.as_table_like_mut() else {
            continue;
        };
        match key.get() {
            "dependencies" | "dev-dependencies" | "build-dependencies" => {
                visit_paths(table, visit);
            }
            "workspace" => visit_dependency_paths(table, visit),
            "target" | "patch" => {
                for (_, item) in table.iter_mut() {
                    match item.as_table_like_mut() {
                        Some(table) if key.get() == "target" => {
                            visit_dependency_paths(table, visit);
                        }
                        Some(table) => visit_paths(table, visit),
                        None => {}
                    }
                }
            }
            _ => {}
        }
    }
}

/// Calls `visit` with the `path` of each dependency in the dependency table `dependencies`.
fn visit_paths(dependencies: &mut dyn TableLike, visit: &mut dyn FnMut(&mut Value)) {
    for (_, dependency) in dependencies.iter_mut() {
        if let Some(path) = dependency
            .as_table_like_mut()
            .and_then(|dependency| dependency.get_mut("path"))
            .and_then(|path| path.as_value_mut())
        {
            visit(path);
        }
    }
}

/// Calls `visit` with each file under `dir`. It skips `target`, `node_modules`, and the
/// directories whose names start with `.`.
fn walk(dir: &Path, visit: &mut dyn FnMut(&Path)) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let path = entry?.path();
        let skipped = path
            .file_name()
            .and_then(|name| name.to_str())
            .is_some_and(|name| {
                name.starts_with('.') || name == "target" || name == "node_modules"
            });
        if path.is_dir() {
            if !skipped {
                walk(&path, visit)?;
            }
        } else {
            visit(&path);
        }
    }
    Ok(())
}

/// The `.rk` files in the source directories of `package`, and its `build.rk`. It deletes each
/// generated `.rs` file there that has no `.rk` file with the same stem beside it.
pub fn sources(package: &Path) -> io::Result<Vec<PathBuf>> {
    let mut sources = Vec::new();
    let mut rust = Vec::new();
    let mut visit = |path: &Path| match path.extension().and_then(|extension| extension.to_str()) {
        Some("rk") => sources.push(path.to_path_buf()),
        Some("rs") => rust.push(path.to_path_buf()),
        _ => {}
    };
    for root in SOURCE_ROOTS.map(|root| package.join(root)) {
        if root.is_dir() {
            walk(&root, &mut visit)?;
        } else {
            for path in [root.with_extension("rs"), root] {
                if path.is_file() {
                    visit(&path);
                }
            }
        }
    }
    for path in rust {
        if !path.with_extension("rk").exists() && is_generated(&path) {
            fs::remove_file(path)?;
        }
    }
    Ok(sources)
}

fn is_generated(path: &Path) -> bool {
    let mut header = [0; GENERATED_HEADER.len()];
    fs::File::open(path).is_ok_and(|mut file| file.read_exact(&mut header).is_ok())
        && header == GENERATED_HEADER.as_bytes()
}

/// Writes `rust`, which starts with [`GENERATED_HEADER`], to `path`. It refuses to replace a file
/// without the header and leaves a file with the same text untouched.
pub fn write_generated(path: &Path, rust: &str) -> Result<(), String> {
    match fs::read_to_string(path) {
        Ok(existing) if existing == rust => return Ok(()),
        Ok(existing) if existing.starts_with(GENERATED_HEADER) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        _ => {
            return Err(format!(
                "refusing to overwrite non-generated Rust file: {}",
                path.display()
            ));
        }
    }
    fs::write(path, rust).map_err(|error| format!("{}: {error}", path.display()))
}
