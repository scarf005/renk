//! The Cargo packages that one cargo call can build, and the `.rk` sources in them.

use std::{
    fs,
    io::{self, Read},
    path::{Path, PathBuf},
};

use toml_edit::{DocumentMut, TableLike, Value};

/// The first line of every Rust file that renk writes beside a `.rk` source.
pub const GENERATED_HEADER: &str = "// @generated by renk; do not edit.\n";

/// The files and directories of a package that cargo reads sources from.
const SOURCE_ROOTS: [&str; 5] = ["build.rk", "src", "examples", "tests", "benches"];

/// A workspace and the directories of the packages that cargo can build in it.
pub struct Workspace {
    /// The directory that rustc runs in. rustc names the files of packages under it relative to it.
    pub root: PathBuf,
    /// The root package, the `workspace.members` that `workspace.exclude` keeps, and every package
    /// that a `path` dependency of those names, inside or outside `root`.
    pub packages: Vec<PathBuf>,
}

/// The workspace of the package at the manifest `start`, or of the nearest package above the
/// directory `start`. Cargo cannot answer this before the first transpile, because it rejects a
/// package whose only sources are `.rk` files.
pub fn workspace(start: &Path) -> Option<Workspace> {
    let manifest = if start.is_file() {
        start.to_path_buf()
    } else {
        start
            .ancestors()
            .map(|dir| dir.join("Cargo.toml"))
            .find(|path| path.is_file())?
    };
    let package = fs::canonicalize(manifest.parent()?).ok()?;
    let named = manifest_at(&package).and_then(|document| {
        let path = document.get("package")?.get("workspace")?.as_str()?;
        fs::canonicalize(package.join(path)).ok()
    });
    let root = named
        .or_else(|| {
            package
                .ancestors()
                .find(|dir| {
                    manifest_at(dir).is_some_and(|document| {
                        document.contains_key("workspace")
                            && !excluded(dir, &document)
                                .iter()
                                .any(|path| package.starts_with(path))
                    })
                })
                .map(Path::to_path_buf)
        })
        .unwrap_or(package);

    let mut queue = Vec::new();
    if let Some(document) = manifest_at(&root) {
        queue.push(root.clone());
        let excluded = excluded(&root, &document);
        for pattern in workspace_paths(&document, "members") {
            let parts = pattern
                .split('/')
                .filter(|part| !matches!(*part, "" | "."))
                .collect::<Vec<_>>();
            let mut found = Vec::new();
            expand(&root, &parts, &mut found);
            queue.extend(
                found
                    .into_iter()
                    .filter_map(|dir| fs::canonicalize(dir).ok())
                    .filter(|dir| !excluded.iter().any(|path| dir.starts_with(path))),
            );
        }
    }
    let mut seen = Vec::new();
    queue.retain(|dir| {
        let new = !seen.contains(dir);
        if new {
            seen.push(dir.clone());
        }
        new
    });
    let mut packages = Vec::new();
    // A path dependency can name a package that has path dependencies of its own.
    while let Some(dir) = queue.pop() {
        let Some(mut document) = manifest_at(&dir) else {
            continue;
        };
        visit_dependency_paths(document.as_table_mut(), &mut |path| {
            let found = path
                .as_str()
                .and_then(|path| fs::canonicalize(dir.join(path)).ok())
                .filter(|path| !seen.contains(path));
            if let Some(path) = found {
                seen.push(path.clone());
                queue.push(path);
            }
        });
        if document.contains_key("package") {
            packages.push(dir);
        }
    }
    Some(Workspace { root, packages })
}

/// The strings of the array `workspace.<key>` in `document`.
fn workspace_paths<'a>(document: &'a DocumentMut, key: &str) -> impl Iterator<Item = &'a str> {
    document
        .get("workspace")
        .and_then(|workspace| workspace.get(key))
        .and_then(|paths| paths.as_array())
        .into_iter()
        .flatten()
        .filter_map(|path| path.as_str())
}

/// The `workspace.exclude` paths of the manifest `document` in `dir`.
fn excluded(dir: &Path, document: &DocumentMut) -> Vec<PathBuf> {
    workspace_paths(document, "exclude")
        .map(|path| dir.join(path))
        .collect()
}

/// Pushes to `found` each directory below `dir` that the path components `parts` name, as the
/// `glob` crate matches them for cargo. A component can hold `*`, `?`, `[abc]`, `[a-z]` and
/// `[!abc]`, and a `**` component stands for any number of directories. A symlink to a directory
/// matches a component but is not entered by `**`.
fn expand(dir: &Path, parts: &[&str], found: &mut Vec<PathBuf>) {
    let Some((part, rest)) = parts.split_first() else {
        found.push(dir.to_path_buf());
        return;
    };
    if !part.contains(['*', '?', '[']) {
        return expand(&dir.join(part), rest, found);
    }
    if *part == "**" {
        expand(dir, rest, found);
    }
    let pattern = part.chars().collect::<Vec<_>>();
    for entry in fs::read_dir(dir).into_iter().flatten().flatten() {
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        if *part == "**" {
            if entry.file_type().is_ok_and(|kind| kind.is_dir()) {
                expand(&entry.path(), parts, found);
            }
        } else if entry.path().is_dir() && wildcard(&pattern, &name.chars().collect::<Vec<_>>()) {
            expand(&entry.path(), rest, found);
        }
    }
}

/// Whether `name` matches `pattern`, where `*` stands for any characters, `?` for one, and
/// `[abc]`, `[a-z]` and `[!abc]` for one character in or out of a set.
fn wildcard(pattern: &[char], name: &[char]) -> bool {
    let Some((&c, rest)) = pattern.split_first() else {
        return name.is_empty();
    };
    if c == '*' {
        return (0..=name.len()).any(|skip| wildcard(rest, &name[skip..]));
    }
    let Some((&first, name_rest)) = name.split_first() else {
        return false;
    };
    // The set ends at the first `]` after its first character, so `[]]` holds `]`.
    let set_end = (c == '[')
        .then(|| {
            let start = usize::from(rest.first() == Some(&'!'));
            let end = rest[start..].iter().skip(1).position(|&c| c == ']');
            end.map(|end| start + 1 + end)
        })
        .flatten();
    let (matched, rest) = match set_end {
        Some(end) => (in_set(&rest[..end], first), &rest[end + 1..]),
        None => (c == '?' || c == first, rest),
    };
    matched && wildcard(rest, name_rest)
}

/// Whether `c` is in the set `body`, the text between `[` and `]`.
fn in_set(body: &[char], c: char) -> bool {
    let (negated, body) = match body.split_first() {
        Some(('!', body)) => (true, body),
        _ => (false, body),
    };
    let mut i = 0;
    let mut found = false;
    while i < body.len() {
        if body.get(i + 1) == Some(&'-') && i + 2 < body.len() {
            found |= (body[i]..=body[i + 2]).contains(&c);
            i += 3;
        } else {
            found |= body[i] == c;
            i += 1;
        }
    }
    found != negated
}

/// The manifest in `dir`, if it is valid TOML.
fn manifest_at(dir: &Path) -> Option<DocumentMut> {
    fs::read_to_string(dir.join("Cargo.toml"))
        .ok()?
        .parse()
        .ok()
}

/// Calls `visit` with the `path` of each dependency in the manifest `table`: the dependency
/// tables of the package, of each `target`, of the `workspace`, and of each `patch` source.
pub fn visit_dependency_paths(table: &mut dyn TableLike, visit: &mut dyn FnMut(&mut Value)) {
    for (key, item) in table.iter_mut() {
        let Some(table) = item.as_table_like_mut() else {
            continue;
        };
        match key.get() {
            "dependencies" | "dev-dependencies" | "build-dependencies" => {
                visit_paths(table, visit);
            }
            "workspace" => visit_dependency_paths(table, visit),
            "target" | "patch" => {
                for (_, item) in table.iter_mut() {
                    match item.as_table_like_mut() {
                        Some(table) if key.get() == "target" => {
                            visit_dependency_paths(table, visit);
                        }
                        Some(table) => visit_paths(table, visit),
                        None => {}
                    }
                }
            }
            _ => {}
        }
    }
}

/// Calls `visit` with the `path` of each dependency in the dependency table `dependencies`.
fn visit_paths(dependencies: &mut dyn TableLike, visit: &mut dyn FnMut(&mut Value)) {
    for (_, dependency) in dependencies.iter_mut() {
        if let Some(path) = dependency
            .as_table_like_mut()
            .and_then(|dependency| dependency.get_mut("path"))
            .and_then(|path| path.as_value_mut())
        {
            visit(path);
        }
    }
}

/// Whether `walk` skips the directory `name`.
fn skipped(name: &str) -> bool {
    name.starts_with('.') || name == "target" || name == "node_modules"
}

/// Calls `visit` with each file under `dir`, but enters only the directories that `enter` accepts.
/// It skips `target`, `node_modules`, the directories whose names start with `.`, and symlinks to
/// directories.
fn walk(dir: &Path, enter: &dyn Fn(&Path) -> bool, visit: &mut dyn FnMut(&Path)) -> io::Result<()> {
    if !enter(dir) {
        return Ok(());
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            if !skipped(&entry.file_name().to_string_lossy()) {
                walk(&path, enter, visit)?;
            }
        } else if !path.is_dir() {
            visit(&path);
        }
    }
    Ok(())
}

/// The `.rk` files under `dir` in sorted order, found as `walk` does.
pub fn renk_files(dir: &Path) -> io::Result<Vec<PathBuf>> {
    let mut files = Vec::new();
    walk(dir, &|_| true, &mut |path| {
        if path.extension().is_some_and(|extension| extension == "rk") {
            files.push(path.to_path_buf());
        }
    })?;
    files.sort();
    Ok(files)
}

/// The `.rk` and the `.rs` files in the source directories of `package`, and its `build.rk` and
/// `build.rs`, but not those of a package nested in them.
fn package_files(package: &Path) -> io::Result<(Vec<PathBuf>, Vec<PathBuf>)> {
    let mut renk = Vec::new();
    let mut rust = Vec::new();
    let mut visit = |path: &Path| match path.extension().and_then(|extension| extension.to_str()) {
        Some("rk") => renk.push(path.to_path_buf()),
        Some("rs") => rust.push(path.to_path_buf()),
        _ => {}
    };
    // A directory with its own manifest is another package, such as `tests/fixtures/demo`.
    let own = |dir: &Path| !dir.join("Cargo.toml").is_file();
    for root in SOURCE_ROOTS.map(|root| package.join(root)) {
        if root.is_dir() {
            walk(&root, &own, &mut visit)?;
        } else {
            for path in [root.with_extension("rs"), root] {
                if path.is_file() {
                    visit(&path);
                }
            }
        }
    }
    Ok((renk, rust))
}

/// The `.rk` files of `package`, found as `package_files` does. It deletes each generated `.rs`
/// file there that has no `.rk` file with the same stem beside it.
pub fn sources(package: &Path) -> io::Result<Vec<PathBuf>> {
    let (sources, rust) = package_files(package)?;
    for path in rust {
        if !path.with_extension("rk").exists() && is_generated(&path) {
            fs::remove_file(path)?;
        }
    }
    Ok(sources)
}

fn is_generated(path: &Path) -> bool {
    let mut header = [0; GENERATED_HEADER.len()];
    fs::File::open(path).is_ok_and(|mut file| file.read_exact(&mut header).is_ok())
        && header == GENERATED_HEADER.as_bytes()
}

/// Writes `rust`, which starts with [`GENERATED_HEADER`], to `path`. It refuses to replace a file
/// without the header and leaves a file with the same text untouched.
pub fn write_generated(path: &Path, rust: &str) -> Result<(), String> {
    match fs::read_to_string(path) {
        Ok(existing) if existing == rust => return Ok(()),
        Ok(existing) if existing.starts_with(GENERATED_HEADER) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {}
        _ => {
            return Err(format!(
                "refusing to overwrite non-generated Rust file: {}",
                path.display()
            ));
        }
    }
    fs::write(path, rust).map_err(|error| format!("{}: {error}", path.display()))
}

/// The hand-written `.rs` files of `package`, found as `package_files` does. It leaves out the
/// Rust files that renk generated.
pub fn rust_sources(package: &Path) -> io::Result<Vec<PathBuf>> {
    let (_, rust) = package_files(package)?;
    Ok(rust
        .into_iter()
        .filter(|path| !is_generated(path))
        .collect())
}
